# Expected values are SymPy's outputs for the same calls (Set operations and handlers).

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); m <- Symbol("m"); n <- Symbol("n")
a <- Symbol("a", real = TRUE); b <- Symbol("b", real = TRUE)
xr <- Symbol("xr", real = TRUE); yr <- Symbol("yr", real = TRUE)
p <- Symbol("p", positive = TRUE); i <- Symbol("i", integer = TRUE)
mi_fmt <- function(v) {
  if (is.null(v)) return("None")
  if (is.logical(v)) return(if (is.na(v)) "None" else if (v) "True" else "False")
  if (is.character(v)) return(v)
  gsub("\n", " ", sstr(v))
}

