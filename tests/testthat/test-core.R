# Expected strings come from SymPy (commit 86150a81) with ** written as ^.

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z")
a <- Symbol("a"); b <- Symbol("b")
s <- function(e) sstr(e)

test_that("Add and Mul canonicalize like SymPy", {
  expect_equal(s(2 * (x + y)), "2*x + 2*y")
  expect_equal(s(2 * x * (x + y)), "2*x*(x + y)")
  expect_equal(s(-(x + y)), "-x - y")
  expect_equal(s(x^2 + x * y + y^2 + x + y + 1), "x^2 + x*y + x + y^2 + y + 1")
  expect_equal(s(x / 2 + x), "3*x/2")
  expect_equal(s((x + 1)^2 * (x + 1)), "(x + 1)^3")
  expect_equal(s(x - y), "x - y")
  expect_equal(s(x * y^-2 / 3), "x/(3*y^2)")
  expect_equal(s(Rational(2, 3) * x), "2*x/3")
  expect_equal(s(1 / (2 * x)), "1/(2*x)")
  expect_equal(s(-x / 2), "-x/2")
  expect_true(x + x == 2 * x)
  expect_true(x * y == y * x)
  expect_equal(s(x - x), "0")
})

