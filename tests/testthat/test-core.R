  expect_equal(sstr(gamma(Rational(-1, 2))), "-2*sqrt(pi)")
  # decided at increasing precision, as SymPy: is_positive False, is_negative True
  expect_false(is_positive(Integer("100000000000000000") * sqrt(S(2)) - Integer("141421356237309510")))
  expect_true(is_negative(Integer("100000000000000000") * sqrt(S(2)) - Integer("141421356237309510")))
  expect_equal(sstr(to_cnf(Xor(a, b, c))), "(a | b | c) & (a | ~b | ~c) & (b | ~a | ~c) & (c | ~a | ~b)")
  expect_equal(as.numeric(N(zeta(Rational(1, 2)))), -1.46035450880959, tolerance = 1e-12)
  expect_equal(sstr(Eq(Float(1), 1)), "True")
  expect_equal(sstr(Le(oo, oo)), "True")
  expect_equal(sstr(Lt(oo, oo)), "False")
  expect_equal(sstr(sin(sym_pi * Integer(paste0("1", strrep("0", 400))))), "0")
  expect_equal(sstr(subs(diff(acosh(x), x), x, -2)), "-sqrt(3)/3")
  expect_equal(as.complex(N(erfc(1 + sym_I))), complex(real = -0.316151281697948, imaginary = -0.190453469237835), tolerance = 1e-12)
  expect_equal(as.complex(N(loggamma(Rational(-1, 2)))), complex(real = 1.26551212348465, imaginary = -pi), tolerance = 1e-12)
  expect_equal(as.numeric(N(elliptic_e(Rational(1, 2), 0))), 0.5)
  expect_equal(as.numeric(N(Ei(1))), 1.89511781635594, tolerance = 1e-12)
  expect_equal(sstr(subs(rewrite(Heaviside(x, 0), "Piecewise"), x, 0)), "0")
  expect_equal(vapply(0:4, function(i) sstr(tribonacci(i)), ""), c("0", "1", "1", "2", "4"))
  expect_equal(sstr(bernoulli(1)), "1/2")
  expect_equal(sstr(bernoulli(1, x)), "x - 1/2")
})

