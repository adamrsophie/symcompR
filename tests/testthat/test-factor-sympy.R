# Expected values are SymPy's outputs for the same calls (factor and factor_list).

skip_on_cran()

for (.v in c("x","y","z","t","w","a","b","c")) assign(.v, Symbol(.v))
mi_fmt <- function(v) {
  if (is.null(v)) return("None")
  if (is_sym(v)) return(gsub("\n", " ", sstr(v)))
  if (is.list(v) && !is.null(v$coeff)) {
    fs <- vapply(v$factors, function(p) paste0("(", sstr(p[[1L]]), ", ", sstr(as_sym(p[[2L]])), ")"), "")
    return(paste0("(", sstr(v$coeff), ", [", paste(fs, collapse = ", "), "])"))
  }
  sstr(v)
}

test_that("factor and factor_list match SymPy", {
  expect_equal(mi_fmt(sym_factor(expand((x * y + z) * (x + y * z + 2) * (x - z)))), "(x - z)*(x*y + z)*(x + y*z + 2)")
  expect_equal(mi_fmt(sym_factor(expand((x ^ 3 * y + 2 * x + y ^ 2 - 1) * (x * y ^ 2 + 3 * y + x)))), "(x*y^2 + x + 3*y)*(x^3*y + 2*x + y^2 - 1)")
  expect_equal(mi_fmt(sym_factor(expand((x ^ 5 + y ^ 4 * x + 7) * (x ^ 4 * y ^ 3 - y + 2 * x)))), "(x^5 + x*y^4 + 7)*(x^4*y^3 + 2*x - y)")
  expect_equal(mi_fmt(sym_factor(expand((x ^ 2 * y * z + 3 * x * y - z ^ 2 + 1) * (x * z ^ 3 - 2 * y ^ 2 * z + x - 5)))), "(x*z^3 + x - 2*y^2*z - 5)*(x^2*y*z + 3*x*y - z^2 + 1)")
  expect_equal(mi_fmt(factor_list(expand((x + y) ^ 3 * (x - 2 * y) ^ 2 * (x * y + 1)))), "(1, [(x*y + 1, 1), (x - 2*y, 2), (x + y, 3)])")
  expect_equal(mi_fmt(sym_factor(expand((x ^ 10 * y + y ^ 7 - 3) * (x ^ 8 - x * y ^ 9 + 2)))), "(x^8 - x*y^9 + 2)*(x^10*y + y^7 - 3)")
  expect_equal(mi_fmt(factor_list(1)), "(1, [])")
  expect_equal(mi_fmt(factor_list(6)), "(6, [])")
  expect_equal(mi_fmt(factor_list(sqrt(as_sym(3)), x)), "(sqrt(3), [])")
  expect_equal(mi_fmt(factor_list((-1) ^ x, x)), "(1, [(-1, x)])")
  expect_equal(mi_fmt(factor_list((2 * x) ^ y, x)), "(1, [(2, y), (x, y)])")
  expect_equal(mi_fmt(factor_list(sqrt(x * y), x)), "(1, [(x*y, 1/2)])")
  expect_equal(mi_fmt(factor_list(3 * x)), "(3, [(x, 1)])")
  expect_equal(mi_fmt(factor_list(3 * x ^ 2)), "(3, [(x, 2)])")
  expect_equal(mi_fmt(sym_factor(3 * x)), "3*x")
  expect_equal(mi_fmt(sym_factor(3 * x ^ 2)), "3*x^2")
  expect_equal(mi_fmt(sym_factor((2 * x ^ 2 + 2) ^ 7)), "128*(x^2 + 1)^7")
  expect_equal(mi_fmt(sym_factor(sqrt(3 * x ^ 2 - 3))), "sqrt(3)*sqrt((x - 1)*(x + 1))")
  expect_equal(mi_fmt(sym_factor(sqrt(3 * x ^ 2 + 3))), "sqrt(3)*sqrt(x^2 + 1)")
  expect_equal(mi_fmt(sym_factor((y * x ^ 2 - y) ^ t)), "(y*(x - 1)*(x + 1))^t")
  expect_equal(mi_fmt(sym_factor((y * x ^ 2 + y) ^ t)), "(y*(x^2 + 1))^t")
  expect_equal(mi_fmt(sym_factor(x ^ 2 + 4 * sym_I * x - 4)), "(x + 2*I)^2")
  expect_equal(mi_fmt(sym_factor(x - 1)), "x - 1")
  expect_equal(mi_fmt(sym_factor(-x - 1)), "-x - 1")
  expect_equal(mi_fmt(sym_factor(6 * x - 10)), "2*(3*x - 5)")
  expect_equal(mi_fmt(sym_factor(1 / (x ^ 2 + 2 * x + 1 / x) - 1)), "-(x^3 + 2*x^2 - x + 1)/(x^3 + 2*x^2 + 1)")
  expect_equal(mi_fmt(sym_factor(sqrt(-x))), "sqrt(-x)")
  expect_equal(mi_fmt(sym_factor(sqrt(x ^ 2))), "sqrt(x^2)")
  expect_equal(mi_fmt(sym_factor(expand((0.5 * x + 1) * (0.5 * y + 1)))), "1.0*(0.5*x + 1.0)*(0.5*y + 1.0)")
  expect_equal(mi_fmt(sym_factor(expand((0.5 * x + 0.5) ^ 2))), "0.25*(1.0*x + 1.0)^2")
  expect_equal(mi_fmt(factor_list(x ^ 3 - x * y ^ 2, t, w, x)), "(1, [(x, 1), (x - y, 1), (x + y, 1)])")
  expect_equal(mi_fmt(factor_list((x + 1) * (x ^ 6 - 1))), "(1, [(x - 1, 1), (x + 1, 2), (x^2 - x + 1, 1), (x^2 + x + 1, 1)])")
  expect_equal(mi_fmt(factor_list((x - sqrt(as_sym(2)) * S_Pi) * (x + sqrt(as_sym(2)) * S_Pi), x)), "(1, [(x - sqrt(2)*pi, 1), (x + sqrt(2)*pi, 1)])")
  expect_equal(mi_fmt(sym_factor((6 * x - 10) / (3 * x - 6))), "2*(3*x - 5)/(3*(x - 2))")
  expect_equal(mi_fmt(factor_list(x * (x + y))), "(1, [(x, 1), (x + y, 1)])")
  expect_equal(mi_fmt(factor_list(sqrt(as_sym(2)) * x)), "(sqrt(2), [(x, 1)])")
  expect_equal(mi_fmt(factor_list(sqrt(as_sym(2)) * sin(x), sin(x))), "(sqrt(2), [(sin(x), 1)])")
  expect_equal(mi_fmt(sym_factor(6)), "6")
  expect_equal(mi_fmt(sym_factor(sqrt(x * y))), "sqrt(x*y)")
})
