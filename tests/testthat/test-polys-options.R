# Expected strings are SymPy outputs for the same calls.

x <- Symbol("x"); y <- Symbol("y"); I <- sym_I
sqrt <- function(v) base::sqrt(if (is.numeric(v)) Integer(v) else v)
fmt <- function(v) {
  if (is_sym(v)) return(sstr(v))
  if (inherits(v, "Poly")) return(paste(capture.output(print(v)), collapse = ""))
  if (is.list(v) && !is.null(v$coeff)) return(paste0("(", sstr(v$coeff), ", [", paste(vapply(v$factors, function(p) paste0("(", sstr(p[[1]]), ", ", sstr(as_sym(p[[2]])), ")"), ""), collapse = ", "), "])"))
  if (is.list(v) && !is.null(v$q)) return(paste0("(", sstr(v$q), ", ", sstr(v$r), ")"))
  format(v)
}

test_that("modulus, extension, gaussian and domain options match SymPy", {
  expect_equal(fmt(sym_factor(x^2+1, modulus=2)), "(x + 1)^2")
  expect_equal(fmt(sym_factor(x^2+1, modulus=5)), "(x - 2)*(x + 2)")
  expect_equal(fmt(sym_factor(2*x^2+2, modulus=5)), "2*(x - 2)*(x + 2)")
  expect_equal(fmt(factor_list(x^2+1, modulus=5)), "(1, [(x + 2, 1), (x - 2, 1)])")
  expect_equal(fmt(sym_factor(x^4+x^3+x+1, modulus=3)), "(x + 1)^4")
  expect_equal(fmt(factor_list(x^6-1, modulus=7)), "(1, [(x + 1, 1), (x + 2, 1), (x + 3, 1), (x - 3, 1), (x - 2, 1), (x - 1, 1)])")
  expect_equal(fmt(sym_factor(x^5+x+1, modulus=2)), "(x^2 + x + 1)*(x^3 + x^2 + 1)")
  expect_equal(fmt(sqf(x^2+2*x+1, modulus=3)), "(x + 1)^2")
  expect_equal(fmt(sqf_list(x^5+x^4+x^3+x^2, modulus=2)), "(1, [(x, 2), (x + 1, 3)])")
  expect_equal(fmt(sqf_list(x^3+1, modulus=3)), "(1, [(x + 1, 3)])")
  expect_equal(fmt(gcd(x^2-1, x-1, modulus=2)), "x + 1")
  expect_equal(fmt(gcd(x^3+2*x+1, x^2+x+3, modulus=5)), "1")
  expect_equal(fmt(lcm(x^2+1, x+1, modulus=2)), "x^2 + 1")
  expect_equal(fmt(div(x^3+1, x+2, modulus=5)), "(x^2 - 2*x - 1, -2)")
  expect_equal(fmt(rem(x^4+1, x^2+3, modulus=7)), "3")
  expect_equal(fmt(Poly(x^2+1, x, modulus=5)), "Poly(x^2 + 1, x, modulus=5)")
  expect_equal(fmt(Poly(x^2+3*x+4, x, modulus=5)), "Poly(x^2 - 2*x - 1, x, modulus=5)")
  expect_equal(fmt(sym_factor(x^2-2, extension=sqrt(2))), "(x - sqrt(2))*(x + sqrt(2))")
  expect_equal(fmt(sym_factor(x^4+1, extension=sqrt(2))), "(x^2 - sqrt(2)*x + 1)*(x^2 + sqrt(2)*x + 1)")
  expect_equal(fmt(sym_factor(x^2+1, gaussian=TRUE)), "(x - I)*(x + I)")
  expect_equal(fmt(sym_factor(x^2+1, extension=I)), "(x - I)*(x + I)")
  expect_equal(fmt(factor_list(x^2-2, extension=sqrt(2))), "(1, [(x - sqrt(2), 1), (x + sqrt(2), 1)])")
  expect_equal(fmt(sym_factor(x^4-5*x^2+6, extension=list(sqrt(2), sqrt(3)))), "(x - sqrt(2))*(x + sqrt(2))*(x - sqrt(3))*(x + sqrt(3))")
  expect_equal(fmt(sym_factor(x^2-2*sqrt(2)*x+2, extension=sqrt(2))), "(x - sqrt(2))^2")
  expect_equal(fmt(sym_factor(x^3-2, extension=Integer(2)^Rational(1,3))), "(x - 2^(1/3))*(x^2 + 2^(1/3)*x + 2^(2/3))")
  expect_equal(fmt(sym_factor(x^2+4, gaussian=TRUE)), "(x - 2*I)*(x + 2*I)")
  expect_equal(fmt(sym_factor(2*x^2+2, gaussian=TRUE)), "2*(x - I)*(x + I)")
  expect_equal(fmt(sym_factor(x^4-4, extension=sqrt(2))), "(x - sqrt(2))*(x + sqrt(2))*(x^2 + 2)")
  expect_equal(fmt(sym_factor(x^2-3, extension=sqrt(2))), "x^2 - 3")
  expect_equal(fmt(sym_factor(x^6-1, extension=sqrt(Integer(-3)))), "(x - 1)*(x + 1)*(x - 1/2 - sqrt(3)*I/2)*(x - 1/2 + sqrt(3)*I/2)*(x + 1/2 - sqrt(3)*I/2)*(x + 1/2 + sqrt(3)*I/2)")
  expect_equal(fmt(factor_list(x^4+1, extension=sqrt(2))), "(1, [(x^2 - sqrt(2)*x + 1, 1), (x^2 + sqrt(2)*x + 1, 1)])")
  expect_equal(fmt(sym_factor(x^2 - 2, extension=TRUE)), "x^2 - 2")
  expect_equal(fmt(sym_factor(x^2-sqrt(2)*x, extension=TRUE)), "x*(x - sqrt(2))")
  expect_equal(fmt(sym_factor(x^2-2, domain=algebraic_field(QQ, sqrt(2)))), "(x - sqrt(2))*(x + sqrt(2))")
  expect_equal(fmt(sym_factor(x^2+1, domain=GF(5))), "(x - 2)*(x + 2)")
  expect_equal(fmt(sym_factor(x^2+1, domain='ZZ_I')), "(x - I)*(x + I)")
  expect_equal(fmt(sym_factor(x^3+x^2+x+1, modulus=2)), "(x + 1)^3")
  expect_equal(fmt(sym_factor(3*x^2 - 3, modulus=7)), "3*(x - 1)*(x + 1)")
  expect_equal(fmt(sym_factor(x^2 - 2*y^2, extension=sqrt(2))), "(x - sqrt(2)*y)*(x + sqrt(2)*y)")
  expect_equal(fmt(sym_factor(x^2*y^2 - 2, extension=sqrt(2))), "(x*y - sqrt(2))*(x*y + sqrt(2))")
  expect_equal(fmt(sym_factor(x^2 + y^2, gaussian=TRUE)), "(x - I*y)*(x + I*y)")
})

test_that("primitive elements", {
  r <- primitive_element(list(sqrt(2), sqrt(3)), x, ex = TRUE)
  expect_equal(sstr(r[[1L]]), "x^4 - 10*x^2 + 1")
  expect_equal(vapply(r[[2L]], sstr, ""), c("1", "1"))
  expect_equal(vapply(r[[3L]][[1L]], sstr, ""), c("1/2", "0", "-9/2", "0"))
  expect_equal(vapply(r[[3L]][[2L]], sstr, ""), c("-1/2", "0", "11/2", "0"))
  r <- primitive_element(list(sqrt(2), Integer(2)^Rational(1, 3), I), x)
  expect_equal(sstr(r[[1L]]), "x^12 - 6*x^10 - 8*x^9 + 39*x^8 - 92*x^6 + 816*x^5 + 423*x^4 - 864*x^3 + 642*x^2 - 1608*x + 929")
})
