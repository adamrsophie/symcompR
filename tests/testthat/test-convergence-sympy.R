# Expected values are SymPy's outputs for the same calls (Sum and Product limits and convergence).

skip_on_cran()

for (v in c("a", "b", "c", "d", "k", "m", "x", "y", "z")) assign(v, Symbol(v))
n <- Symbol("n", integer = TRUE)
f <- Piecewise(list(n^(-2), Le(n, 1)), list(n^2, Gt(n, 1)))
eq <- (x - 2) * (x^2 - 6 * x + 4) * exp(-x)
fmt <- function(r) {
  if (is.logical(r)) return(if (isTRUE(r)) "True" else "False")
  if (is.list(r) && !is_sym(r)) return(paste0("(", paste(vapply(r, fmt, ""), collapse = ", "), ")"))
  if (is.numeric(r)) return(as.character(r))
  sstr(r)
}

test_that("Sum and Product limits and convergence match SymPy", {
  expect_equal(fmt(is_convergent(Sum(n/(2*n + 1), list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(sym_factorial(n)/5^n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(3^(-2*n - 1)*n^n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((-1)^n*n, list(n, 3, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((-1)^n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(log(1/n), list(n, 2, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(sin(n), list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((-12)^n/n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(1/(n^2 + 1), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/n^Rational(6, 5), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(2/(n*sqrt(n - 1)), list(n, 2, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(sqrt(n)*sqrt(n)), list(n, 2, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(sym_factorial(n) / sym_factorial(n+2), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(RisingFactorial(5,n)/RisingFactorial(7,n),list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum((RisingFactorial(1, n)*RisingFactorial(2, n))/(RisingFactorial(3, n)*sym_factorial(n)),list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(1/(n + log(n)), list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(1/(n^2*log(n)), list(n, 2, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n*log(n)), list(n, 2, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(2/(n*log(n)*log(log(n))^2), list(n, 5, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(2/(n*log(n)^2), list(n, 2, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum((n - 1)/(n^2*log(n)^3), list(n, 2, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n*log(n)*log(log(n))), list(n, 5, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((n - 1)/(n*log(n)^3), list(n, 3, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(2/(n^2*log(n)), list(n, 2, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n*sqrt(log(n))*log(log(n))), list(n, 100, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(log(log(n))/(n*log(n)^2), list(n, 100, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(log(n)/n^2, list(n, 5, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum((-1)^(n - 1)/(n^2 - 1), list(n, 3, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n^2 + 1), list(n, -oo, 1)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n - 1), list(n, -oo, -1)))), "False")
  expect_equal(fmt(is_convergent(Sum(1/(n^2 - 1), list(n, -oo, -5)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n^2 - 1), list(n, -oo, 2)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(n^2 - 1), list(n, -oo, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(f, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(f, list(n, -oo, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(f, list(n, 1, 100)))), "True")
  expect_equal(fmt(is_convergent(Sum(f, list(n, -oo, 1)))), "True")
  expect_equal(fmt(is_convergent(Sum(log(n)/n^3, list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(-log(n)/n^3, list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(eq, list(x, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(eq, list(x, 1, 2)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(x^3), list(x, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/(x^Rational(1, 2)), list(x, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(1/n - 3/(3*n +2), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(4/(n + 2) - 5/(n + 1) + 1/n,list(n, 7, oo)))), "True")
  expect_equal(fmt(is_absolutely_convergent(Sum((-1)^n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_absolutely_convergent(Sum((-1)^n/n^2, list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(sin(n)/n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(sin(2*n)/n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((-n + (n^3 + 1)^(Rational(1, 3)))/log(n), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(sin(n)^2 + cos(n)^2 - 1, list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(sin(sym_pi*n), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_absolutely_convergent(Sum((-1)^n/sqrt(n), list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((-1)^(2*n)/n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum((-2)^n + (-3)^n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(sin(n) / n^3, list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(sin(n) * log(n) / n^3, list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(1/log(log(n)), list(n, 22, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(sin(n)/log(log(n)), list(n, 22, oo)))), "False")
  expect_equal(fmt(is_convergent(Sum(5^n/gamma(n+1), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Sum(sym_factorial(n)/sym_factorial(n + 2), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Product(1/n^2, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Product(exp(1/n^2), list(n, 1, oo)))), "True")
  expect_equal(fmt(is_convergent(Product(1/n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Product(1 + 1/n, list(n, 1, oo)))), "False")
  expect_equal(fmt(is_convergent(Product(1 + 1/n^2, list(n, 1, oo)))), "True")
  expect_equal(fmt(reverse_order(Sum(1/n^2, list(n, 1, oo)), n)), "Sum(-1/n^2, (n, oo, 0))")
  expect_equal(fmt(reverse_order(Sum(x*n, list(n, a, b)), 0)), "Sum(-n*x, (n, b + 1, a - 1))")
  expect_equal(fmt(reverse_order(Sum(x*n*m, list(n, 1, 3), list(m, a, b)), 1)), "Sum(-m*n*x, (n, 1, 3), (m, b + 1, a - 1))")
  expect_equal(fmt(reverse_order(Product(x*n, list(n, a, b)), 0)), "Product(1/(n*x), (n, b + 1, a - 1))")
  expect_equal(fmt(reverse_order(Product(n^2, list(n, 1, 10)), n)), "Product(n^(-2), (n, 11, 0))")
  expect_equal(fmt(change_index(Sum(x^2, list(x, a, b)), x, x + 1, y)), "Sum((y - 1)^2, (y, a + 1, b + 1))")
  expect_equal(fmt(change_index(Sum(x^2, list(x, a, b)), x, -x - 1)), "Sum((-x - 1)^2, (x, -b - 1, -a - 1))")
  expect_equal(fmt(change_index(Product(x, list(x, a, b)), x, 2 - x, y)), "Product(2 - y, (y, 2 - b, 2 - a))")
  expect_equal(fmt(sym_reorder(Sum(x*y, list(x, 1, 3), list(y, a, b)), list(x, y))), "Sum(x*y, (y, a, b), (x, 1, 3))")
  expect_equal(fmt(reorder_limit(Sum(x*y*z, list(x, a, b), list(y, c, d), list(z, 1, 3)), 0, 2)), "Sum(x*y*z, (z, 1, 3), (y, c, d), (x, a, b))")
  expect_equal(fmt(sum_index(Sum(x, list(x, 1, 5)), x)), "0")
  expect_equal(fmt(euler_maclaurin(Sum(1/k^2, list(k, 1, m)), m=1, n=1)), "(79/48 - 1/m + 1/(2*m^2) - 1/(6*m^3), Abs(1/960 - 1/(30*m^5)))")
  expect_equal(fmt(euler_maclaurin(Sum(1/k, list(k, 1, m)), m=2, n=2)), "(log(m) - log(3) + 16289/9720 + 1/(2*m) - 1/(12*m^2) + 1/(120*m^4), Abs(1/183708 - 1/(252*m^6)))")
  expect_equal(fmt(euler_maclaurin(Sum(k^3, list(k, 1, 10)), m=2, n=2)), "(3025, 0)")
  expect_equal(fmt(euler_maclaurin(Sum(x^2, list(x, a, b)), m=1, n=1)), "(a^2 - a/6 + b^3/3 + b^2/2 + b/6 - (a + 1)^3/3 + (a + 1)^2/2 - 1/6, 0)")
  expect_equal(fmt(euler_maclaurin(Sum(exp(-k), list(k, 0, m)), m=1, n=2)), "(1139*exp(-1)/720 + 1 - 419*exp(-m)/720, Abs(exp(-1)/30240 - exp(-m)/30240))")
})
