# Reference values from SymPy's RootSum, symmetrize and Poly printing.
test_that("RootSum evaluates rational sums and keeps the rest as SymPy", {
  x <- Symbol("x"); a <- Symbol("a")
  expect_equal(sstr(RootSum(x^3 + x + 1, Lambda(x, x^2))), "-2")
  expect_equal(sstr(RootSum(x^3 + x + 1, Lambda(x, 1/(x + 2)))), "13/9")
  expect_equal(sstr(RootSum(x^3 + x + 1)), "0")
  expect_equal(sstr(RootSum(x^2 - 2, Lambda(x, x^3))), "0")
  expect_equal(sstr(RootSum(2*x^3 + 4, Lambda(x, x^2 + 1))), "3")
  expect_equal(sstr(RootSum(x^2 + 1, Lambda(x, 1/(x + a)))), "2*a/(a^2 + 1)")
  expect_equal(sstr(RootSum(x^2 - 2, Lambda(x, log(x)), quadratic = TRUE)), "2*log(sqrt(2)) + I*pi")
  expect_equal(sstr(RootSum(x^3 - 1, Lambda(x, log(x + 1)))), "RootSum(w^2 + w + 1, Lambda(w, log(w + 1))) + log(2)")
  r <- RootSum(x^5 + x + 3, Lambda(x, log(x + 1)))
  expect_equal(sstr(r), "RootSum(w^5 + w + 3, Lambda(w, log(w + 1)))")
  expect_equal(latex(r), "\\operatorname{RootSum} {\\left(w^{5} + w + 3, \\left( w \\mapsto \\log{\\left(w + 1 \\right)} \\right)\\right)}")
  expect_equal(sstr(doit(r)), sstr(r))
  expect_equal(sstr(N(r)), "3.14159265358979*I")
  expect_length(free_symbols(r), 0L)
  expect_equal(sstr(diff(RootSum(x^5 + x + 3, Lambda(x, log(x + a))), a)), "(5*a^4 + 1)/(a^5 + a - 3)")
})

test_that("log of a negative number and Lambda LaTeX follow SymPy", {
  x <- Symbol("x"); a <- Symbol("a"); p <- Symbol("p", positive = TRUE)
  expect_equal(sstr(log(-sqrt(Integer(2)))), "log(sqrt(2)) + I*pi")
  expect_equal(sstr(log(-sym_pi)), "log(pi) + I*pi")
  expect_equal(sstr(log(-2*p)), "log(-2*p)")
  expect_equal(sstr(log(-sym_E)), "1 + I*pi")
  expect_equal(latex(Lambda(x, x^2)), "\\left( x \\mapsto x^{2} \\right)")
  expect_equal(latex(Lambda(list(x, a), x + a)), "\\left( \\left( x, \\  a\\right) \\mapsto a + x \\right)")
})

test_that("symmetrize and Poly generators follow SymPy's ordering", {
  x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); a <- Symbol("a"); b <- Symbol("b")
  s <- function(r) paste(sstr(r[[1L]]), "|", sstr(r[[2L]]))
  expect_equal(s(symmetrize(x^2 + y^2 + a)), "-2*a*x - 2*a*y - 2*x*y + (a + x + y)^2 | -a^2 + a")
  expect_equal(s(symmetrize(x^3 + y^2 + z)), "3*x*y*z + (x + y + z)^3 - 3*(x + y + z)*(x*y + x*z + y*z) | -y^3 + y^2 - z^3 + z")
  expect_equal(s(symmetrize(x*y + 2*x + 3)), "x*y + 2*x + 2*y + 3 | -2*y")
  expect_equal(s(symmetrize(x^2 + y^2 + a, x, y)), "a - 2*x*y + (x + y)^2 | 0")
  out <- function(p) paste(capture.output(print(p)), collapse = "")
  expect_equal(out(Poly(a*x + b)), "Poly(x*a + b, x, a, b, domain='ZZ')")
  expect_equal(out(Poly(a*x^2*y - 3*x + a + 2, x, y)), "Poly(a*x^2*y - 3*x + a + 2, x, y, domain='ZZ[a]')")
  expect_equal(out(Poly(x^2*(a + 1) - x, x)), "Poly((a + 1)*x^2 - x, x, domain='ZZ[a]')")
  expect_equal(out(Poly(x/2 - 1, x)), "Poly(1/2*x - 1, x, domain='QQ')")
  expect_equal(out(Poly(x + sin(y))), "Poly(x + (sin(y)), x, sin(y), domain='ZZ')")
})
