.bt <- new.env(parent = asNamespace("symcompR"))
eval(parse(text = r"---(.u <- physics_units()
for (.nm in ls(.u)) assign(.nm, get(.nm, .u), envir = environment())
x <- Symbol("x"); y <- Symbol("y"); f <- Function("f")
pylist <- function(x) structure(as.list(x), class = "pylist")
pyset <- function(x) structure(as.list(x), class = "pyset")
.fmt <- function(v) {
  if (is.null(v)) return("None")
  if (inherits(v, "pylist")) return(paste0("[", paste(vapply(v, .upy_repr, ""), collapse = ", "), "]"))
  if (inherits(v, "pyset")) return(paste0("{", paste(sort(vapply(v, .upy_repr, ""), method = "radix"), collapse = ", "), "}"))
  if (is.logical(v) && length(v) == 1L) return(if (is.na(v)) "None" else if (v) "True" else "False")
  if (is_sym(v) || inherits(v, "symmatrix")) return(sstr(v))
  if (inherits(v, c("units_dict", "UnitSystem", "DimensionSystem"))) return(format(v))
  if (is.character(v) && length(v) == 1L) return(v)
  if (is.numeric(v) && length(v) == 1L) return(as.character(v))
  if (is.list(v)) return(.upy_repr(v))
  paste(format(v), collapse = " ")
}
)---"), envir = .bt)
.run <- function(code) {
  e <- .bt
  NULL
  gsub("\n", " ", get(".fmt", envir = .bt)(eval(parse(text = code), envir = e)), fixed = TRUE)
}
.setup <- function(code) invisible(eval(parse(text = code), envir = .bt))
.err <- function(code) tryCatch({ .run(code); "no error" }, error = function(e) gsub("\n", " ", conditionMessage(e), fixed = TRUE))

