x <- Symbol("x"); y <- Symbol("y"); a <- Symbol("a"); b <- Symbol("b")
s <- function(e) sstr(e)

test_that("extra special functions match SymPy", {
  expect_equal(s(Rem(-7, 3)), "-1")
  expect_equal(s(Rem(7, -3)), "1")
  expect_equal(vapply(0:9, function(i) s(andre(i)), ""), c("1", "1", "1", "2", "5", "16", "61", "272", "1385", "7936"))
  expect_equal(s(multigamma(x, 1)), "gamma(x)")
  expect_equal(s(multigamma(3, 2)), "3*pi/2")
  expect_equal(s(stieltjes(0)), "EulerGamma")
  expect_equal(s(riemann_xi(2)), "pi/6")
  expect_equal(s(owens_t(0, a)), "atan(a)/(2*pi)")
  expect_equal(as.numeric(N(owens_t(1, 2))), 0.0784681869930841, tolerance = 1e-12)
  expect_equal(s(erf2inv(0, y)), "erfinv(y)")
  expect_equal(s(marcumq(1, 0, b)), "exp(-b^2/2)")
  expect_equal(as.numeric(N(hyper(list(1, 2), list(3), Rational(1, 2)))), 1.54517744447956, tolerance = 1e-12)
  expect_equal(s(hyper(list(a, b), list(x), 0)), "hyper((a, b), (x,), 0)")
  expect_equal(vapply(jn_zeros(1, 2), function(z) as.numeric(z), 0), c(4.49340945790906, 7.72525183693771), tolerance = 1e-12)
  expect_equal(s(SingularityFunction(5, 2, 3)), "27")
  expect_equal(s(SingularityFunction(1, 2, 3)), "0")
  expect_equal(s(SingularityFunction(2, 2, -1)), "oo")
  expect_equal(s(diff(SingularityFunction(x, 2, 3), x)), "3*SingularityFunction(x, 2, 2)")
  expect_equal(as.numeric(N(betainc_regularized(2, 3, 0, Rational(1, 2)))), 0.6875, tolerance = 1e-12)
  expect_equal(as.numeric(N(jtheta(3, 1, Rational(1, 2)))), 0.505893885730485, tolerance = 1e-12)
  expect_equal(as.numeric(N(appellf1(1, 1, 1, 2, Rational(1, 2), Rational(1, 3)))), 1.72609243471069, tolerance = 1e-10)
  expect_equal(s(polar_lift(2)), "2*exp_polar(0)")
  expect_equal(s(unpolarify(exp_polar(x))), "exp(x)")
  expect_equal(s(periodic_argument(exp_polar(3 * sym_I * sym_pi), 2 * sym_pi)), "pi")
  expect_equal(s(principal_branch(exp_polar(3 * sym_I * sym_pi), 2 * sym_pi)), "exp_polar(I*pi)")
  expect_equal(s(piecewise_exclusive(Piecewise(list(1, x < 1), list(2, x < 2), list(3, TRUE)))),
               "Piecewise((1, x < 1), (2, (x >= 1) & (x < 2)), (3, x >= 2))")
  expect_equal(as.complex(N(hn1(0, 1))), complex(real = 0.841470984807897, imaginary = -0.54030230586814), tolerance = 1e-12)
})

test_that("third review round fixes", {
  A <- Symbol("A", commutative = FALSE); B <- Symbol("B", commutative = FALSE); C <- Symbol("C", commutative = FALSE)
  expect_equal(s(factor_terms(B * A + A)), "A + B*A")
  expect_equal(s(unpolarify(sqrt(exp_polar(2 * sym_pi * sym_I)))), "-1")
  expect_equal(s(principal_branch(-2, 2 * sym_pi)), "2*exp_polar(I*pi)")
  expect_equal(Re(as.complex(N(riemann_xi(S_Half + sym_I)))), 0.485757429670983, tolerance = 1e-12)
  expect_equal(as.complex(N(betainc(1, 1, 0, 1 + sym_I))), 1 + 1i, tolerance = 1e-12)
  expect_equal(as.numeric(jn_zeros(100, 1)[[1]]), 109.350128931692, tolerance = 1e-10)
  expect_equal(as.numeric(N(appellf1(1, Rational(-1, 2), 1, 2, Rational(1, 2), Rational(1, 3)))), 1.03645636336325, tolerance = 1e-10)
  expect_equal(as.numeric(N(hyper(list(-1), list(-1), Rational(1, 2)))), exp(0.5), tolerance = 1e-12)
  expect_equal(s(marcumq(2, 0, 1)), "3*exp(-1/2)/2")
  expect_equal(mod_inverse(3, -11), -7)
  expect_equal(integer_log(-8, -2), list(e = 3, exact = TRUE))
  expect_equal(s(bool_map(Or(And(a, b), And(a, Not(b))), x)$expr), "a")
  expect_equal(vapply(div(Float(1) * x + y, x, x), s, "")[["q"]], "1.00000000000000")
  expect_equal(vapply(gcdex(x, sqrt(Integer(2)) * x, x), s, ""), c(s = "0", t = "sqrt(2)/2", h = "x"))
  expect_equal(s(Eq(Rational("1e-400"), 0)), "False")
  expect_equal(s(expand_power_exp(A^(B + C))), "A^(B + C)")
  expect_equal(s(A^(-1) * B), "A^(-1)*B")
  expect_error(nsolve(exp(10^16 * x), x, 0), "did not converge")
  expect_equal(s(Eq(Float(NaN), Float(NaN))), "False")
  expect_equal(s(FiniteSet(0, oo)), "{0, oo}")
  ev <- Symbol("e", even = TRUE)
  expect_length(solve(ev - 1, ev), 0)
  expect_length(free_symbols(Subs(x + y, Tuple(x, y), Tuple(0, 1))), 0)
  expect_equal(s(coeff(x + y + 1, x + y, 0)), "0")
  expect_equal(s(nsolve(x^2 + 1, x, 1i)), "1.0*I")
})

test_that("exclusive bounds compare exactly and hyper converges near the unit circle", {
  xr <- Symbol("x", real = TRUE); n <- Integer("9007199254740992")
  p <- Piecewise(list(0, xr <= n), list(1, xr >= n + 1), list(2, TRUE))
  expect_equal(s(subs(piecewise_exclusive(p), xr, n + Rational(1, 2))), "2")
  expect_equal(sstr(N(hyper(list(1, 1), list(2), Rational(9999, 10000)))), "9.21126149812599")
})
