x <- Symbol("x"); y <- Symbol("y")
s <- function(e) sstr(e)

test_that("core helpers and assumption predicates", {
  expect_equal(s(Add(x, 1, x)), "2*x + 1")
  expect_equal(s(doit(Subs(x^2, x, 3))), "9")
  expect_true(ask(Q$positive(x^2 + 1), Q$real(x)))
  expect_equal(s(refine(sqrt(x^2), Q$positive(x))), "x")
  expect_equal(s(refine(Abs(x), Q$negative(x))), "-x")
  expect_equal(s(parse_expr("x**2")), "x^2")
  expect_true(identical(true$key, S_true$key))
})

test_that("polynomial and function aliases match SymPy", {
  expect_equal(s(cyclotomic_poly(12, x)), "x^4 - x^2 + 1")
  expect_equal(s(monic(3*x^2 + 6*x + 9, x)), "x^2 + 2*x + 3")
  expect_equal(s(sym_rf(x, 3)), "x*(x + 1)*(x + 2)")
  expect_equal(s(LeviCivita(1, 3, 2)), "-1")
  expect_equal(s(residue(1 / (x^2 + 1), x, sym_I)), "-I/2")
  k <- Symbol("k", integer = TRUE)
  expect_equal(s(hypersimp(sym_factorial(k), k)), "k + 1")
  expect_equal(vapply(finite_diff_weights(2, list(-1, 0, 1), 0)[[3]][[3]], s, ""), c("1", "-2", "1"))
  expect_equal(vapply(finite_diff_weights(1, list(0, 1, 2))[[2]][[3]], s, ""), c("-1/2", "0", "1/2"))
  expect_equal(vapply(finite_diff_weights(1, list(0, 1), 0)[[1]][[2]], s, ""), c("1", "0"))
  expect_equal(s(LeviCivita(1, 2, 4)), "3")
  expect_equal(s(LeviCivita(x, x, 1)), "0")
  expect_equal(s(casoratian(list(S(2)^k, S(3)^k), k)), "1")
})

test_that("calculus utilities", {
  expect_equal(s(singularities(1 / (x^2 - 1), x)), "{-1, 1}")
  expect_equal(s(singularities(1 / (x^2 + 1), x)), "{-I, I}")
  expect_equal(s(maximum(1 / x, x, Interval(1, 2))), "1")
  expect_equal(s(minimum(log(x), x, Interval(1, 2))), "0")
  r <- Symbol("r", real = TRUE)
  expect_equal(s(singularities(1 / (r^2 + 1), r)), "EmptySet")
  expect_equal(s(singularities(log(x), x)), "{0}")
  expect_equal(s(minimum(1 / x, x, Interval(-1, 1))), "-oo")
  expect_equal(s(maximum(1 / x^2, x, Interval(-1, 1))), "oo")
  expect_equal(s(minimum(1 / x, x, Interval(0, 1))), "1")
  u <- Function("u")
  expect_equal(s(euler_equations(Derivative(u(x), x, 2)^2 / 2, u(x), x)[[1]]), "Eq(Derivative(u(x), (x, 4)), 0)")
  expect_equal(s(euler_equations(Derivative(u(x), x)^2 / 2 - u(x)^2 / 2, u(x), x)[[1]]),
               "Eq(-u(x) - Derivative(u(x), (x, 2)), 0)")
  expect_equal(s(diff(Derivative(u(x), x)^2, u(x))), "0")
  expect_equal(s(minimum(x^2 - 2*x, x)), "-1")
  expect_equal(s(maximum(sin(x), x, Interval(0, sym_pi))), "1")
  expect_true(is_increasing(exp(x), Reals, x))
  expect_false(is_increasing(x^2, Reals, x))
  expect_true(is_increasing(x^2, Interval(0, oo), x))
  expect_equal(s(periodicity(sin(2*x), x)), "pi")
  t <- Symbol("t", positive = TRUE); sp <- Symbol("s", positive = TRUE)
  expect_equal(s(mellin_transform(exp(-t), t, sp, noconds = TRUE)), "gamma(s)")
})

test_that("solver and matrix helpers", {
  m <- linear_eq_to_matrix(list(x + 2*y - 3, 3*x - y), list(x, y))
  expect_equal(vapply(m[[2L]]$data, s, ""), c("3", "0"))
