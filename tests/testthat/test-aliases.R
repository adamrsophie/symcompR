test_that("alias review fixes", {
  x <- Symbol("x")
  expect_false(checksol(x, list(x = Rational(1, "10000000000000"))))
  expect_equal(as.character(continued_fraction_iterator(Integer("9007199254740993") + sqrt(S(2)), 3)),
               c("9007199254740994", "2", "2"))
  a <- Integer("100000000000000000000")
  expect_s3_class(convex_hull(Point(a, 0), Point(a + 1, 1), Point(a + 2, 0)), "GeoPolygon")
  expect_equal(sstr(maximum(1 + x * Rational(1, "100000000000000000000"), x, Interval(0, 1))),
               "100000000000000000001/100000000000000000000")
  expect_equal(sstr(maximum(x, x, FiniteSet(0, 1))), "1")
  expect_equal(sstr(minimum(Integer(5), x)), "5")
  set.seed(1)
  expect_equal(sstr(random_poly(x, 2, 5, 5)), "5*x^2 + 5*x + 5")
  expect_equal(vapply(solve_linear(1, x = x), sstr, ""), c("0", "1"))
  expect_length(closest_points(Point(0, 0), Point(1, 0), Point(0, 1)), 2)
  expect_equal(group(list(1, 1, 2)), list(list(1, 1), list(2)))
  expect_true(is_increasing(1))
  expect_equal(flatten(c(1, 2, 3)), list(1, 2, 3))
  expect_equal(sstr(monic(0, x)), "0")
  expect_equal(unflatten(numeric()), list())
})

