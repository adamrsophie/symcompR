  expect_equal(s(solve_linear(3*x + 6, 0, x)[[2]]), "-2")
  expect_equal(s(reduce_inequalities(list(x^2 < 4, x > 0), x)), "(0 < x) & (x < 2)")
  expect_equal(s(permanent(Matrix(list(list(1, 2), list(3, 4))))), "10")
  expect_equal(vapply(covering_product(list(1, 2), list(3, 4)), s, ""), c("3", "18"))
  expect_equal(vapply(intersecting_product(list(1, 2), list(3, 4)), s, ""), c("13", "8"))
  expect_equal(mathematica_code(sin(x)^2 + exp(x)), "Exp[x] + Sin[x]^2")
  expect_equal(julia_code(x^2 + Rational(1, 2)), "x .^ 2 + 1 // 2")
  expect_equal(topological_sort(1:4, list(c(1, 2), c(2, 3), c(1, 4))), c(1L, 2L, 3L, 4L))
})

test_that("attaching the package masks no base R function", {
  ex <- getNamespaceExports("symcompR")
  for (p in c("base", "stats", "graphics", "grDevices", "utils", "datasets", "methods")) {
    base_names <- if (p == "base") ls(baseenv(), all.names = TRUE) else getNamespaceExports(p)
    if (p == "datasets") base_names <- ls(as.environment("package:datasets"))
    expect_identical(intersect(ex, base_names), character(), label = p)
  }
})

test_that("set printing follows SymPy default_sort_key", {
