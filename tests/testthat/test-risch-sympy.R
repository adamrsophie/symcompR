# Expected values are SymPy's outputs for the same calls (risch_integrate).

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); a <- Symbol("a"); t0 <- Symbol("t0")
mi_fmt <- function(v) if (is.null(v)) "None" else gsub("\n", " ", sstr(v))

test_that("risch_integrate match SymPy", {
  expect_equal(mi_fmt(risch_integrate(t0*exp(x), x)), "t0*exp(x)")
  expect_equal(mi_fmt(risch_integrate(sin(x), x, rewrite_complex = TRUE)), "-exp(I*x)/2 - exp(-I*x)/2")
  expect_equal(mi_fmt(risch_integrate((1 + 2*x^2 + x^4 + 2*x^3*exp(2*x^2))/(x^4*exp(x^2) + 2*x^2*exp(x^2) + exp(x^2)), x)), "Integral(exp(-x^2), x) + exp(x^2)/(x^2 + 1)")
  expect_equal(mi_fmt(risch_integrate(0, x)), "0")
  expect_equal(mi_fmt(risch_integrate(log(x/exp(x) + 1), x)), "x*log(x*exp(-x) + 1) + Integral((x^2 - x)/(x + exp(x)), x)")
  expect_equal(mi_fmt(risch_integrate((log(-1/y)/2 - log(1/y)/2)/y - (log(1 - 1/y)/2 - log(1 + 1/y)/2)/y, y)), "log(1/y)*log(1 - 1/y)/2 - log(1/y)*log(1 + 1/y)/2 + Integral((I*pi*y^2 - 2*y*log(1/y) - I*pi)/(2*y^3 - 2*y), y)")
  expect_equal(mi_fmt(risch_integrate(x^x, x)), "Integral(x^x, x)")
  expect_equal(mi_fmt(risch_integrate(x^x*log(x), x)), "Integral(x^x*log(x), x)")
  expect_equal(mi_fmt(risch_integrate(log(x^x), x)), "x^2*log(x)/2 - x^2/4")
  expect_equal(mi_fmt(risch_integrate(log(x^y), x)), "-x*y + x*log(x^y)")
  expect_equal(mi_fmt(risch_integrate(log(sqrt(x)), x)), "x*log(sqrt(x)) - x/2")
  expect_equal(mi_fmt(risch_integrate(exp(x), x)), "exp(x)")
  expect_equal(mi_fmt(risch_integrate(x*exp(x), x)), "(x - 1)*exp(x)")
  expect_equal(mi_fmt(risch_integrate(x^2*exp(x), x)), "(x^2 - 2*x + 2)*exp(x)")
  expect_equal(mi_fmt(risch_integrate(exp(2*x) + exp(x), x)), "exp(2*x)/2 + exp(x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)/(1 + exp(x)), x)), "log(exp(x) + 1)")
  expect_equal(mi_fmt(risch_integrate(exp(x)/(1 + exp(2*x)), x)), "RootSum(4*w^2 + 1, Lambda(w, w*log(2*w + exp(x))))")
  expect_equal(mi_fmt(risch_integrate(1/(1 + exp(x)), x)), "x - log(exp(x) + 1)")
  expect_equal(mi_fmt(risch_integrate(x/(1 + exp(x)), x)), "Integral(x/(exp(x) + 1), x)")
  expect_equal(mi_fmt(risch_integrate(exp(x^2), x)), "Integral(exp(x^2), x)")
  expect_equal(mi_fmt(risch_integrate(x*exp(x^2), x)), "exp(x^2)/2")
  expect_equal(mi_fmt(risch_integrate(exp(-x^2), x)), "Integral(exp(-x^2), x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)/x, x)), "Integral(exp(x)/x, x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)*(1 + 1/x), x)), "Integral((x*exp(x) + exp(x))/x, x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)*(1/x - 1/x^2), x)), "exp(x)/x")
  expect_equal(mi_fmt(risch_integrate(log(x), x)), "x*log(x) - x")
  expect_equal(mi_fmt(risch_integrate(x*log(x), x)), "x^2*log(x)/2 - x^2/4")
  expect_equal(mi_fmt(risch_integrate(log(x)^2, x)), "x*log(x)^2 - 2*x*log(x) + 2*x")
  expect_equal(mi_fmt(risch_integrate(log(x)/x, x)), "log(x)^2/2")
  expect_equal(mi_fmt(risch_integrate(1/(x*log(x)), x)), "log(log(x))")
  expect_equal(mi_fmt(risch_integrate(1/log(x), x)), "Integral(1/log(x), x)")
  expect_equal(mi_fmt(risch_integrate(log(log(x))/x, x)), "log(x)*log(log(x)) - log(x)")
  expect_equal(mi_fmt(risch_integrate(log(x)^3, x)), "x*log(x)^3 - 3*x*log(x)^2 + 6*x*log(x) - 6*x")
  expect_equal(mi_fmt(risch_integrate(x^2*log(x), x)), "x^3*log(x)/3 - x^3/9")
  expect_equal(mi_fmt(risch_integrate(log(x + 1), x)), "x*log(x + 1) - x + log(x + 1)")
  expect_equal(mi_fmt(risch_integrate(log(x^2 + 1), x)), "x*log(x^2 + 1) - 2*x + 2*atan(x)")
  expect_equal(mi_fmt(risch_integrate(1/(x*log(x)^2), x)), "-1/log(x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)*log(x), x)), "Integral(exp(x)*log(x), x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)*log(x) + exp(x)/x, x)), "exp(x)*log(x)")
  expect_equal(mi_fmt(risch_integrate((exp(x) + 1)/(exp(x) - 1), x)), "-x + 2*log(exp(x) - 1)")
  expect_equal(mi_fmt(risch_integrate(exp(3*x)/(exp(x) + 1), x)), "exp(2*x)/2 - exp(x) + log(exp(x) + 1)")
  expect_equal(mi_fmt(risch_integrate(exp(2*x)/(exp(x) + 1)^2, x)), "log(exp(x) + 1) + 1/(exp(x) + 1)")
  expect_equal(mi_fmt(risch_integrate(exp(exp(x))*exp(x), x)), "exp(exp(x))")
  expect_equal(mi_fmt(risch_integrate(exp(exp(x)), x)), "Integral(exp(exp(x)), x)")
  expect_equal(mi_fmt(risch_integrate(log(x)/(x*(1 + log(x))), x)), "log(x) - log(log(x) + 1)")
  expect_equal(mi_fmt(risch_integrate(1/(x*(1 + log(x)^2)), x)), "RootSum(4*w^2 + 1, Lambda(w, w*log(2*w + log(x))))")
  expect_equal(mi_fmt(risch_integrate(x*exp(x)*log(x), x)), "Integral(x*exp(x)*log(x), x)")
  expect_equal(mi_fmt(risch_integrate(exp(a*x), x)), "Piecewise((exp(a*x)/a, Ne(a, 0)), (x, True))")
  expect_equal(mi_fmt(risch_integrate(exp(a*x)*x, x)), "Piecewise(((a*x - 1)*exp(a*x)/a^2, Ne(a^2, 0)), (x^2/2, True))")
  expect_equal(mi_fmt(risch_integrate(log(a*x), x)), "x*log(a*x) - x")
  expect_equal(mi_fmt(risch_integrate(2^x, x)), "2^x/log(2)")
  expect_equal(mi_fmt(risch_integrate(x*2^x, x)), "2^x*(x*log(2) - 1)/log(2)^2")
  expect_equal(mi_fmt(risch_integrate(1/x + exp(x), x)), "exp(x) + log(x)")
  expect_equal(mi_fmt(risch_integrate((x + 1)*exp(x)/x^2, x)), "Integral((x*exp(x) + exp(x))/x^2, x)")
  expect_equal(mi_fmt(risch_integrate(log(x)^2/x^2, x)), "-log(x)^2/x - 2*log(x)/x - 2/x")
  expect_equal(mi_fmt(risch_integrate(exp(-x)*x^3, x)), "(-x^3 - 3*x^2 - 6*x - 6)*exp(-x)")
  expect_equal(mi_fmt(risch_integrate(exp(x)/(exp(x) + 2)^2, x)), "-1/(exp(x) + 2)")
})
