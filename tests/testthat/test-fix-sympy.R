# SymPy 1.15 str() output for each case (with ** shown as ^), compared
# with the same formatting the battery uses.
.fix_fmt <- function(v) {
  if (is.null(v)) return("None")
  if (isTRUE(attr(v, "pytuple"))) return(paste0("(", paste(vapply(v, .fix_fmt, ""), collapse = ", "), if (length(v) == 1L) ",", ")"))
  if (inherits(v, "sym") || inherits(v, "symmatrix")) return(sstr(v))
  if (is.character(v) && length(v) == 1L) return(v)
  if (inherits(v, "bigz") || inherits(v, "bigq")) return(if (length(v) == 1L) as.character(v) else paste0("[", paste(as.character(v), collapse = ", "), "]"))
  if (is.logical(v) && !is.null(names(v))) { o <- order(names(v)); return(paste0("{", paste0(names(v)[o], ": ", ifelse(v[o], "True", "False"), collapse = ", "), "}")) }
  if (is.numeric(v) && length(v) == 1L) return(format(v, digits = 15))
  if (is.numeric(v)) return(paste0("[", paste(format(v, digits = 15, trim = TRUE), collapse = ", "), "]"))
  if (is.character(v)) return(paste(v, collapse = "\n"))
  if (is.logical(v) && length(v) == 1L) return(if (is.na(v)) "None" else if (v) "True" else "False")
  if (is.list(v) && !is.object(v) && length(v) && !is.null(names(v)) && all(vapply(v, function(x) is.logical(x) && length(x) == 1L, TRUE))) return(.fix_fmt(unlist(v)))
  if (is.list(v) && !is.object(v)) return(paste0("[", paste(vapply(v, .fix_fmt, ""), collapse = ", "), "]"))
  if (is.object(v)) return(paste(format(v), collapse = "\n"))
  paste(utils::capture.output(print(v)), collapse = "\n")
}
.fix_run <- function(code) {
  env <- new.env(parent = asNamespace("symcompR"))
  for (s in c("x", "y", "z", "t", "a", "b", "c", "n", "p", "q", "r", "w", "A", "B", "C", "D", "k", "m"))
    assign(s, Symbol(s), envir = env)
  assign("th", Symbol("theta"), envir = env)
  assign("f", Function("f"), envir = env)
  assign("g", Function("g"), envir = env)
  tryCatch(gsub("**", "^", .fix_fmt(suppressWarnings(eval(parse(text = code), envir = env))), fixed = TRUE),
           error = function(e) {
             cl <- setdiff(class(e), c("simpleError", "error", "condition", "sympy_error"))
             paste0("ERR ", if (length(cl)) cl[1L] else "Error", ": ", conditionMessage(e))
           })
}
.fix_check <- function(cases) {
  for (cs in cases) expect_identical(.fix_run(cs[[2L]]), cs[[3L]], info = cs[[1L]])
}

