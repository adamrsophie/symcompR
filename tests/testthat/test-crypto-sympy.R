# Expected values are SymPy's outputs for the same calls (crypto).

fmt <- function(r) {
  if (is.logical(r)) return(if (isTRUE(r)) "True" else "False")
  if (inherits(r, "symmatrix")) {
    rows <- lapply(seq_len(r$nrow), function(i) paste0("[", paste(vapply(seq_len(r$ncol), function(j) sstr(.mget(r, i, j)), ""), collapse = ", "), "]"))
    return(paste0("Matrix([", paste(rows, collapse = ", "), "])"))
  }
  if (inherits(r, "bigz")) return(if (length(r) == 1L) as.character(r) else paste0("(", paste(as.character(r), collapse = ", "), ")"))
  if (is.list(r) && !is_sym(r)) return(paste0("(", paste(vapply(r, fmt, ""), collapse = ", "), ")"))
  if (is.numeric(r)) return(if (length(r) == 1L) format(r, scientific = FALSE) else paste0("(", paste(format(r, scientific = FALSE, trim = TRUE), collapse = ", "), ")"))
  if (is.character(r)) return(r)
  sstr(r)
}

