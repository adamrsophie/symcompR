# Expected values are SymPy's outputs for the same calls (limit_seq and difference_delta).

skip_unless_full_tests()

skip_on_cran()

n <- Symbol("n", integer = TRUE); m <- Symbol("m", integer = TRUE); k <- Symbol("k", integer = TRUE)
x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z")
kp <- Symbol("k", positive = TRUE); np_ <- Symbol("n", positive = TRUE)

test_that("limit_seq and difference_delta match SymPy", {
  expect_equal(sstr(difference_delta(n*(n + 1))), "2*n + 2")
  expect_equal(sstr(difference_delta(n*(n + 1)*k, n, 2)), "k*(4*n + 6)")
  expect_equal(sstr(difference_delta(Sum(1/k, list(k, 1, n)), n)), "1/(n + 1)")
  expect_equal(sstr(difference_delta(Sum(1/k, list(k, 1, n)), n, 5)), "1/(n + 5) + 1/(n + 4) + 1/(n + 3) + 1/(n + 2) + 1/(n + 1)")
  expect_equal(sstr(difference_delta(Sum(1/k, list(k, 1, 3*n)), n)), "1/(3*n + 3) + 1/(3*n + 2) + 1/(3*n + 1)")
  expect_equal(sstr(difference_delta(n * Sum(1/k, list(k, 1, n)), n)), "Sum(1/k, (k, 1, n)) + 1")
  expect_equal(sstr(difference_delta(Sum(1/k, list(k, 1, n), list(m, 1, n)), n)), "harmonic(n)")
  expect_equal(sstr(difference_delta(n + n*(n + 1), n)), "2*n + 3")
  expect_equal(sstr(difference_delta(n + n*(n + 1), n, 2)), "4*n + 8")
  expect_equal(sstr(difference_delta(n + Sum(1/k, list(k, 1, n)), n)), "1 + 1/(n + 1)")
  expect_equal(sstr(difference_delta(n + Sum(1/k, list(k, 1, n)), n, 5)), "5 + 1/(n + 5) + 1/(n + 4) + 1/(n + 3) + 1/(n + 2) + 1/(n + 1)")
  expect_equal(sstr(difference_delta(4^n, n)), "3*4^n")
  expect_equal(sstr(difference_delta(4^n, n, 2)), "15*4^n")
  expect_equal(sstr(difference_delta(4^(2*n), n)), "15*4^(2*n)")
  expect_equal(sstr(difference_delta(4^(2*n), n, 2)), "255*4^(2*n)")
  expect_equal(sstr(difference_delta(n^4, n)), "-n^4 + (n + 1)^4")
  expect_equal(sstr(difference_delta(n^n, n)), "-n^n + (n + 1)^(n + 1)")
  expect_equal(sstr(limit_seq(sym_binomial(2*n, n) / Sum(sym_binomial(2*k, k), list(k, 1, n)))), "3/4")
  expect_equal(sstr(limit_seq((5*n^3 + 3*n^2 + 4) / (3*n^3 + 4*n - 5), n)), "5/3")
  expect_equal(sstr(limit_seq((harmonic(n) * Sum(harmonic(k), list(k, 1, n))) / (n * harmonic(2*n)^2), n)), "1")
  expect_equal(sstr(limit_seq(Sum(k^2 * Sum(2^m/m, list(m, 1, k)), list(k, 1, n)) / (2^n*n), n)), "4")
  expect_equal(sstr(limit_seq((Sum(sym_binomial(3*k, k) * sym_binomial(5*k, k), list(k, 1, n)) / (sym_binomial(3*n, n) * sym_binomial(5*n, n))), n)), "84375/83351")
  expect_equal(sstr(limit_seq(Sum(harmonic(k)^2/k, list(k, 1, 2*n)) / harmonic(n)^3, n)), "1/3")
  expect_equal(sstr(limit_seq((-1)^n/n^2, n)), "0")
  expect_equal(sstr(limit_seq((-2)^(n+1)/(n + 3^n), n)), "0")
  expect_equal(sstr(limit_seq((2*n + (-1)^n)/(n + 1), n)), "2")
  expect_equal(sstr(limit_seq(sin(sym_pi*n), n)), "0")
  expect_equal(sstr(limit_seq(cos(2*sym_pi*n), n)), "1")
  expect_equal(sstr(limit_seq((Integer(-1)/5)^n, n)), "0")
  expect_equal(sstr(limit_seq((sym_I/3)^n, n)), "0")
  expect_equal(sstr(limit_seq(sqrt(n)*(sym_I/2)^n, n)), "0")
  expect_equal(sstr(limit_seq(n/(n + 1) + (sym_I/2)^n, n)), "1")
  expect_equal(sstr(limit_seq((-1)^n, n)), "AccumBounds(-1, 1)")
  expect_equal(sstr(limit_seq(cos(sym_pi*n), n)), "AccumBounds(-1, 1)")
  expect_equal(sstr(limit_seq(sin(sym_pi*n/2)^2, n)), "AccumBounds(0, 1)")
  expect_equal(sstr(limit_seq(2*(-3)^n/(n + 3^n), n)), "AccumBounds(-2, 2)")
  expect_equal(sstr(limit_seq(3*n/(n + 1) + 2*(-1)^n, n)), "AccumBounds(1, 5)")
  expect_equal(sstr(limit_seq(Sum(1/x, list(x, 1, y)) - log(y), y)), "EulerGamma")
  expect_equal(sstr(limit_seq(Sum(1/x, list(x, 1, y)) - 1/y, y)), "oo")
  expect_equal(sstr(limit_seq(sym_binomial(2*x, x) / Sum(sym_binomial(2*y, y), list(y, 1, x)), x)), "3/4")
  expect_equal(sstr(limit_seq(Sum(y^2 * Sum(2^z/z, list(z, 1, y)), list(y, 1, x)) / (2^x*x), x)), "4")
  expect_equal(sstr(limit_seq(Rational(-1, 2)^n, n)), "0")
  expect_equal(sstr(limit_seq(doit(Sum(m^kp, list(m, 1, np_)))/(np_^(kp + 1)), np_)), "1/(k + 1)")
  expect_equal(sstr(limit_seq(5^n/sym_factorial(n), n)), "0")
  expect_equal(sstr(limit_seq(1/gamma(n + Rational(1, 2)), n)), "0")
  expect_equal(sstr(limit_seq(n/(n+1), n)), "1")
  expect_equal(sstr(limit_seq(n^2/(n+1), n)), "oo")
  expect_equal(sstr(limit_seq(sym_factorial(n)/n^n, n)), "0")
  expect_equal(sstr(limit_seq(n^(1/n), n)), "1")
  expect_equal(sstr(dominant(5*n^3 + 4*n^2 + n + 1, n)), "5*n^3")
  expect_equal(sstr(dominant(2^n + sym_factorial(n) + n^2, n)), "factorial(n)")
  expect_equal(sstr(dominant(n + (-1)^n, n)), "n")
})
