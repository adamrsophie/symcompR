# Expected values are SymPy's outputs for the same calls (heurisch).

skip_unless_full_tests()

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z")
mi_fmt <- function(v) if (is.null(v)) "None" else gsub("\n", " ", sstr(v))

test_that("heurisch match SymPy", {
  expect_equal(mi_fmt(heurisch(-1/x^5, x)), "1/(4*x^4)")
  expect_equal(mi_fmt(heurisch(1, x)), "x")
  expect_equal(mi_fmt(heurisch(1/(2 + x), x)), "log(x + 2)")
  expect_equal(mi_fmt(heurisch(1/(x * (1 + log(x)^2)), x)), "atan(log(x))")
  expect_equal(mi_fmt(heurisch(1/(x + sin(y)), x)), "log(x + sin(y))")
  expect_equal(mi_fmt(heurisch(1/(x + sqrt(Integer(2))), x)), "log(x + sqrt(2))")
  expect_equal(mi_fmt(heurisch(1/(x + y), x)), "log(x + y)")
  expect_equal(mi_fmt(heurisch(1/S_Pi/4 * x^2*cos(x), x)), "(x^2*sin(x) + 2*x*cos(x) - 2*sin(x))/(4*pi)")
  expect_equal(mi_fmt(heurisch(1/sqrt(x), x)), "2*sqrt(x)")
  expect_equal(mi_fmt(heurisch(1/sqrt(x)^3, x)), "-2/sqrt(x)")
  expect_equal(mi_fmt(heurisch(1/x, x)), "log(x)")
  expect_equal(mi_fmt(heurisch(1/x^2, x)), "-1/x")
  expect_equal(mi_fmt(heurisch(2^x, x)), "2^x/log(2)")
  expect_equal(mi_fmt(heurisch(2*sin(x)*cos(x)/(sin(x)^4 + 1), x)), "atan(sqrt(2)*sin(x) - 1) - atan(sqrt(2)*sin(x) + 1)")
  expect_equal(mi_fmt(heurisch(5*x^5/(2*x^6 + 5), x)), "5*log(2*x^6 + 5)/12")
  expect_equal(mi_fmt(heurisch(acos(x/4) * asin(x/4), x)), "x*acos(x/4)*asin(x/4) + 2*x + sqrt(16 - x^2)*acos(x/4) - sqrt(16 - x^2)*asin(x/4)")
  expect_equal(mi_fmt(heurisch(cos(x), x)), "sin(x)")
  expect_equal(mi_fmt(heurisch(cos(x)/sin(x), x)), "log(sin(x))")
  expect_equal(mi_fmt(heurisch(cosh(x), x)), "sinh(x)")
  expect_equal(mi_fmt(heurisch(exp(-x), x)), "-exp(-x)")
  expect_equal(mi_fmt(heurisch(exp(-x^2), x)), "None")
  expect_equal(mi_fmt(heurisch(exp(17*x), x)), "exp(17*x)/17")
  expect_equal(mi_fmt(heurisch(exp(x), x)), "exp(x)")
  expect_equal(mi_fmt(heurisch(log(3*x), x)), "x*log(x) - x + x*log(3)")
  expect_equal(mi_fmt(heurisch(log(x), x)), "x*log(x) - x")
  expect_equal(mi_fmt(heurisch(log(x^2), x)), "x*log(x^2) - 2*x")
  expect_equal(mi_fmt(heurisch(S_Pi*sin(x) + 1, x)), "x - pi*cos(x)")
  expect_equal(mi_fmt(heurisch(sin(x), x)), "-cos(x)")
  expect_equal(mi_fmt(heurisch(sin(x)*cos(x), x)), "-cos(x)^2/2")
  expect_equal(mi_fmt(heurisch(sin(x)*exp(x), x)), "exp(x)*sin(x)/2 - exp(x)*cos(x)/2")
  expect_equal(mi_fmt(heurisch(sin(x)*sin(y), x)), "-sin(y)*cos(x)")
  expect_equal(mi_fmt(heurisch(sin(x)*sqrt(cos(x)), x)), "-2*cos(x)^(3/2)/3")
  expect_equal(mi_fmt(heurisch(sin(x)/(cos(x)^2+1), x)), "-atan(cos(x))")
  expect_equal(mi_fmt(heurisch(sin(y*sqrt(x)), x)), "-2*sqrt(x)*cos(sqrt(x)*y)/y + 2*sin(sqrt(x)*y)/y^2")
  expect_equal(mi_fmt(heurisch(sinh(x), x)), "cosh(x)")
  expect_equal(mi_fmt(heurisch(sqrt(x)^3, x)), "2*x^(5/2)/5")
  expect_equal(mi_fmt(heurisch(tan(x), x)), "log(tan(x)^2 + 1)/2")
  expect_equal(mi_fmt(heurisch(x, x)), "x^2/2")
  expect_equal(mi_fmt(heurisch(x^17, x)), "x^18/18")
  expect_equal(mi_fmt(heurisch(x*2^x, x)), "2^x*x/log(2) - 2^x/log(2)^2")
  expect_equal(mi_fmt(heurisch(x*cosh(x), x)), "x*sinh(x) - cosh(x)")
  expect_equal(mi_fmt(heurisch(x*exp(x), x)), "x*exp(x) - exp(x)")
  expect_equal(mi_fmt(heurisch(x*exp(x^2), x)), "exp(x^2)/2")
  expect_equal(mi_fmt(heurisch(x*sin(7*x), x)), "-x*cos(7*x)/7 + sin(7*x)/49")
  expect_equal(mi_fmt(heurisch(x*sinh(x), x)), "x*cosh(x) - sinh(x)")
  expect_equal(mi_fmt(heurisch(x*cos(x), x)), "x*sin(x) + cos(x)")
  expect_equal(mi_fmt(heurisch(sin(x)^2, x)), "x*sin(x)^2/2 + x*cos(x)^2/2 - sin(x)*cos(x)/2")
  expect_equal(mi_fmt(heurisch(1/(1 + x^2), x)), "atan(x)")
  expect_equal(mi_fmt(heurisch(x/sqrt(1 - x^2), x)), "-sqrt(1 - x^2)")
  expect_equal(mi_fmt(heurisch(cos(x)^3, x)), "2*sin(x)^3/3 + sin(x)*cos(x)^2")
  expect_equal(mi_fmt(heurisch(exp(x)*cos(x), x)), "exp(x)*sin(x)/2 + exp(x)*cos(x)/2")
  expect_equal(mi_fmt(heurisch(x^2*exp(x), x)), "x^2*exp(x) - 2*x*exp(x) + 2*exp(x)")
  expect_equal(mi_fmt(heurisch(x*log(x), x)), "x^2*log(x)/2 - x^2/4")
  expect_equal(mi_fmt(heurisch(log(x)^2, x)), "x*log(x)^2 - 2*x*log(x) + 2*x")
  expect_equal(mi_fmt(heurisch(atan(x), x)), "x*atan(x) - log(x^2 + 1)/2")
  expect_equal(mi_fmt(heurisch(asin(x), x)), "x*asin(x) + sqrt(1 - x^2)")
  expect_equal(mi_fmt(heurisch(sqrt(1 - x^2), x)), "None")
  expect_equal(mi_fmt(heurisch(1/(x^2 - 1), x)), "log(x - 1)/2 - log(x + 1)/2")
  expect_equal(mi_fmt(heurisch(x*sin(x)^2, x)), "x^2*sin(x)^2/4 + x^2*cos(x)^2/4 - x*sin(x)*cos(x)/2 + sin(x)^2/4")
})
