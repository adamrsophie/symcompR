# Python set(): CPython orders by hash, which varies per run; sort by str here.
set <- function(x = list()) {
  if (is_sym(x)) x <- x$args
  if (!length(x)) return("set()")
  s <- unique(vapply(x, function(z) if (is_sym(z)) sstr(z) else as.character(z), ""))
  paste0("{", paste(sort(s), collapse = ", "), "}")
}
# Python type() of a symbolic probability object
type <- function(x) {
  mods <- c(Probability = "symbolic_probability", Expectation = "symbolic_probability", Variance = "symbolic_probability",
            Covariance = "symbolic_probability", Moment = "symbolic_probability", CentralMoment = "symbolic_probability")
  m <- mods[x$type]
  paste0("<class 'sympy.stats.", if (is.na(m)) "rv" else m, ".", x$type, "'>")
}
# sympy.core.expr.unchanged(func, *args)
unchanged <- function(f, ...) {
  r <- f(...)
  args <- lapply(list(...), as_sym)
  is_sym(r) && length(r$args) == length(args) && all(mapply(function(a, b) identical(a$key, b$key), r$args, args))
}
# Python .args is a tuple
sym_args <- function(e) {
  if (exists("rv_attr") && inherits(e, "sym") && (!is.null(e$extra$rv_matrix) || (!is.null(e$extra$rv_class) && e$type == "Symbol")))
    return(rv_attr(e, "args"))
  do.call(Tuple, as_sym(e)$args)
}
# Expr.round(n) of SymPy: a Float with mag + n significant digits
round_sym <- function(x, n = 0) {
  x <- as_sym(x)
  if (x$type == "Integer") return(x)
  v <- as.numeric(N(x))
  if (v == 0) return(x)
  l <- log10(abs(v)); m <- ceiling(l)
  mag <- if (abs(v) / 10^m < 1) m else m + 1
  allow <- min(mag + n, 15)
  r <- round(v, n)
  if (r == round(r)) return(Float(format(r, nsmall = 0), dps = 15))
  if (allow == 0 && r > v) allow <- allow + 1
  Float(formatC(r, format = "f", digits = max(n, 0)), dps = max(allow, 1))
}
