# Harness helpers shared by every battery file (not package code).
py_len <- function(x) {
  if (inherits(x, "symmatrix")) return(length(x$data))
  if (is_sym(x)) return(length(x$args))
  length(x)
}
py_in <- function(a, b) {
  a <- as_sym(a)
  if (is.list(b) && !is_sym(b)) return(any(vapply(b, function(z) identical(as_sym(z)$key, a$key), NA)))
  # SingleFiniteDistribution.__contains__: membership in its dict
  if (is_sym(b) && grepl("Distribution$", b$type)) b <- rv_attr(b, "dict")
  if (b$type %in% c("Dict", "FiniteDensity")) return(any(vapply(b$args, function(t) identical(t$args[[1L]]$key, a$key), NA)))
  if (b$type %in% c("Tuple", "FiniteSet")) return(any(vapply(b$args, function(z) identical(z$key, a$key), NA)))
  r <- Contains(a, b)
  if (is.logical(r)) return(r)
  if (is_sym(r) && r$type == "BooleanAtom") return(r$name == "true")
  stop(structure(class = c("TypeError", "error", "condition"), list(message = "did not evaluate to a bool", call = NULL)))
}
