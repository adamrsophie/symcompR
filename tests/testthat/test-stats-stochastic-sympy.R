# a Python tuple: "(a, b)" with "(a,)" for one element
py_tuple <- function(l) {
  s <- vapply(l, function(z) pyfmt0(z), "")
  if (length(s) == 1L) paste0("(", s, ",)") else paste0("(", paste(s, collapse = ", "), ")")
}
pyfmt0 <- function(v) {
  if (is.list(v) && !is.object(v)) return(paste0("[", paste(vapply(v, pyfmt0, ""), collapse = ", "), "]"))
  # repr() inside a tuple: a matrix prints one row per line
  if (inherits(v, "symmatrix")) return(gsub("\n", "\\n", .ns$.mat_format_str(v$nrow, v$ncol, v$data), fixed = TRUE))
  if (inherits(v, c("sym", "symmatrix"))) return(gsub("\n", "\\n", sstr(v), fixed = TRUE))
  if (is.logical(v)) return(if (v) "True" else "False")
  as.character(v)
}
