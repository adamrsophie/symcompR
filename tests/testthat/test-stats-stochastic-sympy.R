# Python range(): a list of Integers (base R range() is the min and max)
py_range <- function(a, b = NULL, step = 1L) {
  if (is.null(b)) { b <- a; a <- 0L }
  if ((b - a) * step <= 0) return(list())
  v <- seq(a, b, by = step)
  v <- v[if (step > 0) v < b else v > b]
  lapply(v, function(i) Integer(as.integer(i)))
}
