test_that("symbolic_multivariate: test_multivariate_variance", {
  mv_setup()
  expect_equal(res(Variance(A)), "ERR ShapeError: Expression is not a vector")
  expr <- Variance(a)
  expect_equal(res(expr), "VarianceMatrix(a)")
  expect_equal(res(Variance(a)), "VarianceMatrix(a)")
  expect_equal(res(expand(expr)), "0")
  expr <- Variance(rv_attr(a, "T"))
  expect_equal(res(expr), "VarianceMatrix(a.T)")
  expect_equal(res(Variance(rv_attr(a, "T"))), "VarianceMatrix(a.T)")
  expect_equal(res(expand(expr)), "0")
  expr <- Variance(X)
  expect_equal(res(expr), "VarianceMatrix(X)")
  expect_equal(res(Variance(X)), "VarianceMatrix(X)")
  expect_equal(res(rv_attr(expr, "shape")), "(k, k)")
  expect_equal(res(rv_attr(expr, "rows")), "k")
  expect_equal(res(rv_attr(expr, "cols")), "k")
  expect_equal(res(isinstance(expr, VarianceMatrix)), "True")
  expr <- Variance(A * X)
  expect_equal(res(expr), "VarianceMatrix(A*X)")
  expect_equal(res(expand(expr)), "A*VarianceMatrix(X)*A.T")
  expect_equal(res(isinstance(expr, VarianceMatrix)), "True")
  expect_equal(res(rv_attr(expr, "shape")), "(k, k)")
  expr <- Variance((A * B) * X)
  expect_equal(res(expand(expr)), "A*B*VarianceMatrix(X)*B.T*A.T")
  expr <- Variance(m1 * X2)
  expect_equal(res(expand(expr)), "VarianceMatrix(Matrix([\\n[     1, j*normal2],\\n[normal,         0]])*X2)")
  expr <- Variance(((A2 * m1) * B2) * X2)
  expect_equal(res(sym_args(py_item(sym_args(expr), 1))), "(A2, Matrix([\\n[     1, j*normal2],\\n[normal,         0]]), B2, X2)")
  expect_equal(res(expand(expr)), "VarianceMatrix(A2*Matrix([\\n[     1, j*normal2],\\n[normal,         0]])*B2*X2)")
  expr <- Variance((A * X) + (B * Y))
  expect_equal(res(expand(expr)), "2*A*CrossCovarianceMatrix(X, Y)*B.T + A*VarianceMatrix(X)*A.T + B*VarianceMatrix(Y)*B.T")
})

test_that("symbolic_multivariate: test_multivariate_crosscovariance", {
  mv_setup()
  expect_equal(res(Covariance(X, rv_attr(Y, "T"))), "ERR ShapeError: Expression is not a vector")
  expect_equal(res(Covariance(X, A)), "ERR ShapeError: Expression is not a vector")
  expr <- Covariance(rv_attr(a, "T"), rv_attr(b, "T"))
  expect_equal(res(rv_attr(expr, "shape")), "(1, 1)")
  expect_equal(res(expand(expr)), "0")
  expr <- Covariance(a, b)
  expect_equal(res(expr), "CrossCovarianceMatrix(a, b)")
  expect_equal(res(Covariance(a, b)), "CrossCovarianceMatrix(a, b)")
  expect_equal(res(expand(expr)), "0")
  expect_equal(res(rv_attr(expr, "shape")), "(k, k)")
  expect_equal(res(rv_attr(expr, "rows")), "k")
  expect_equal(res(rv_attr(expr, "cols")), "k")
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expr <- Covariance((A * X) + a, b)
  expect_equal(res(expand(expr)), "0")
  expr <- Covariance(X, Y)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "CrossCovarianceMatrix(X, Y)")
  expr <- Covariance(X, X)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "VarianceMatrix(X)")
  expr <- Covariance(X + Y, Z)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "CrossCovarianceMatrix(X, Z) + CrossCovarianceMatrix(Y, Z)")
  expr <- Covariance(A * X, Y)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "A*CrossCovarianceMatrix(X, Y)")
  expr <- Covariance(X, B * Y)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "CrossCovarianceMatrix(X, Y)*B.T")
  expr <- Covariance((A * X) + a, (rv_attr(B, "T") * Y) + b)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "A*CrossCovarianceMatrix(X, Y)*B")
  expr <- Covariance(((A * X) + (B * Y)) + a, ((rv_attr(C, "T") * Z) + (rv_attr(D, "T") * W)) + b)
  expect_equal(res(isinstance(expr, CrossCovarianceMatrix)), "True")
  expect_equal(res(expand(expr)), "A*CrossCovarianceMatrix(X, W)*D + A*CrossCovarianceMatrix(X, Z)*C + B*CrossCovarianceMatrix(Y, W)*D + B*CrossCovarianceMatrix(Y, Z)*C")
})
