test_that("Kane's method forms the equations of a mass on a spring", {
  q <- dynamicsymbols("q"); u <- dynamicsymbols("u")
  m <- Symbol("m"); k <- Symbol("k")
  N <- ReferenceFrame("N")
  P <- PhysPoint("P")
  P$set_vel(N, u * N$x)
  km <- KanesMethod(N, list(q), list(u), kd_eqs = list(dynamicsymbols("q", 1) - u))
  km$kanes_equations(list(Particle("p", P, m)), list(Force(P, -k * q * N$x)))
  expect_equal(sstr(km$mass_matrix), "Matrix([[m]])")
  expect_equal(sstr(km$forcing), "Matrix([[-k*q(t)]])")
})

test_that("bodies, inertia and loads print as in SymPy", {
  N <- ReferenceFrame("N")
  expect_equal(format(inertia(N, 1, 2, 3)), "(N.x|N.x) + 2*(N.y|N.y) + 3*(N.z|N.z)")
  P <- PhysPoint("P")
  expect_equal(format(Force(P, N$x)), "Force(point=P, force=N.x)")
  expect_error(Inertia(1, P), "Inertia value should be expressed as a Dyadic")
  B <- RigidBody("B")
  expect_equal(format(B), "B")
  expect_equal(format(B$mass), "B_mass")
})

test_that("a pin joint orients the child frame and a system collects it", {
  P <- RigidBody("P"); C <- RigidBody("C")
  J <- PinJoint("J", P, C)
  expect_equal(format(J), "PinJoint: J  parent: P  child: C")
  expect_equal(sstr(J$kdes), "Matrix([[u_J(t) - Derivative(q_J(t), t)]])")
  sys <- System_from_newtonian(P)
  sys$add_joints(J)
  expect_equal(sstr(sys$q), "Matrix([[q_J(t)]])")
  expect_equal(length(sys$bodies), 2L)
  expect_error(sys$add_joints(J), "have already been added to the system")
})

test_that("pathways and actuators give loads", {
  N <- ReferenceFrame("N")
  pA <- PhysPoint("pA"); pB <- PhysPoint("pB")
  q <- Symbol("q", positive = TRUE)
  pB$set_pos(pA, q * N$x)
  spring <- LinearSpring(Symbol("k"), LinearPathway(pA, pB))
  expect_equal(sstr(spring$force), "-k*q")
  expect_length(spring$to_loads(), 2L)
  expect_error(LinearPathway(pA), "must be an iterable of length 2")
})
