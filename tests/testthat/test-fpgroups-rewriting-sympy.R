# Expected values are SymPy's outputs for the same calls (Finitely presented groups (rewriting)).

skip_unless_full_tests()

skip_on_cran()

.bt <- new.env(parent = asNamespace("symcompR"))
eval(parse(text = r"---(NULL
)---"), envir = .bt)
.run <- function(code) {
  e <- .bt
  NULL
  gsub("\n", " ", get("fp_str", envir = .bt)(eval(parse(text = code), envir = e)), fixed = TRUE)
}
.setup <- function(code) invisible(eval(parse(text = code), envir = .bt))
.err <- function(code) tryCatch({ .run(code); "no error" }, error = function(e) gsub("\n", " ", conditionMessage(e), fixed = TRUE))

test_that("Finitely presented groups (rewriting) match SymPy", {
  .setup(".g <- free_group(\"a, b\"); F <- .g[[1]]; a <- .g[[2]]; b <- .g[[3]]; G <- FpGroup(F, list(a*b*a^-1*b^-1)); R <- fp_rewriting_system(G)")
  expect_equal(.run("rws_rules(R)"), "[(b*a, a*b), (b^-1*a^-1, a^-1*b^-1), (b*a^-1, a^-1*b), (b^-1*a, a*b^-1)]")
  expect_equal(.run("rws_is_confluent(R)"), "True")
  expect_equal(.run("fp_reduce(G, b^-1*a)"), "a*b^-1")
  expect_equal(.run("fp_reduce(G, b^3*a^4*b^-2*a)"), "a^5*b")
  expect_equal(.run("fp_equals(G, b^2*a^-1*b, b^4*a^-1*b^-1)"), "True")
  expect_equal(.run("fp_equals(G, b^2*a^-1*b, b^3*a^-1*b^-1)"), "False")
  expect_equal(.run("rws_reduce_using_automaton(R, b*a*a^2*b^-1)"), "a^3")
  expect_equal(.run("rws_reduce_using_automaton(R, b^3*a^4*b^-2*a)"), "a^5*b")
  expect_equal(.run("rws_reduce_using_automaton(R, b^-1*a)"), "a*b^-1")
  .setup("G <- FpGroup(F, list(a^3, b^3, (a*b)^2)); R <- fp_rewriting_system(G)")
  expect_equal(.run("rws_rules(R)"), "[(a^-2, a), (b^-2, b), (b^-1*a^-1, a*b), (b*a, a^-1*b^-1), (a^2, a^-1), (b^2, b^-1)]")
  expect_equal(.run("rws_is_confluent(R)"), "False")
  expect_equal(.run("fp_reduce(G, b*a^-1*b^-1*a^3*b^4*a^-1*b^-15)"), "a^-1*b^-1")
  expect_equal(.run("fp_equals(G, a*b, b^-1*a^-1)"), "True")
  expect_equal(.run("rws_make_confluent(R)"), "True")
  expect_equal(.run("rws_is_confluent(R)"), "True")
  expect_equal(.run(".rws_check_confluence(R)"), "True")
  expect_equal(.run("length(R$rules$k)"), "10")
  expect_equal(.run("{.r <- rws_rules(R); .r[order(vapply(.r, function(p) paste(.fw_sort_key(p[[1]]), .fw_sort_key(p[[2]])), \"\"), method = \"radix\")]}"), "[(a^2, a^-1), (b^-1*a^-1, a*b), (b*a, a^-1*b^-1), (b^2, b^-1), (a^-1*b^-1*a, b*a^-1), (a*b^-1*a, a^-1*b*a^-1), (a*b*a^-1, b^-1*a), (b^-1*a*b^-1, a^-1*b*a^-1), (b^-1*a*b, b*a^-1), (b*a^-1*b^-1, b^-1*a)]")
  expect_equal(.run("fp_reduce(G, b*a^-1*b^-1*a^3*b^4*a^-1*b^-15)"), "a^-1*b^-1")
  expect_equal(.run("rws_reduce_using_automaton(R, b*a^-1*b^-1*a^3*b^4*a^-1*b^-15)"), "a^-1*b^-1")
  expect_equal(.run("fp_reduce(G, a*b*a*b*a)"), "a")
  expect_equal(.run("fp_reduce(G, b^2*a^2*b^2)"), "a")
  expect_equal(.run("fp_equals(G, a*b, b^-1*a^-1)"), "True")
  expect_equal(.run("fp_equals(G, a*b, b*a)"), "False")
  .setup("G <- FpGroup(F, list(a^2, b^3, (a*b)^4)); R <- fp_rewriting_system(G)")
  expect_equal(.run("rws_rules(R)"), "[(a, a^-1), (a^-2, <identity>), (b^-2, b), (b^-1*a^-1*b^-1*a^-1, a^-1*b*a^-1*b), (a^-1*b*a^-1*b*a^-1, b^-1*a^-1*b^-1), (b*a^-1*b*a^-1*b, a^-1*b^-1*a^-1), (b*a^-1*b*a^-1, a^-1*b^-1*a^-1*b^-1), (a^2, <identity>), (b^2, b^-1), (b^-1*a*b^-1*a, a*b*a*b), (a*b^-1*a*b^-1*a, b*a*b), (b^-1*a*b^-1*a*b^-1, a*b*a), (b*a*b*a, a*b^-1*a*b^-1)]")
  expect_equal(.run("fp_reduce(G, a^2*b^-2*a^2*b)"), "b^-1")
  expect_equal(.run("rws_reduce_using_automaton(R, a^2*b^-2*a^2*b)"), "b^-1")
  expect_equal(.run("fp_reduce(G, a^3*b^-2*a^2*b)"), "a^-1*b^-1")
  expect_equal(.run("rws_reduce_using_automaton(R, a^3*b^-2*a^2*b)"), "a^-1*b^-1")
  expect_equal(.run(".fw_sort(rws_add_rule(R, a^2, b))"), "[a^-1*b, b*a^-1]")
  expect_equal(.run("rws_rules(R)"), "[(a, a^-1), (a^-2, <identity>), (b^-2, b), (b^-1*a^-1*b^-1*a^-1, a^-1*b*a^-1*b), (a^-1*b*a^-1*b*a^-1, b^-1*a^-1*b^-1), (b*a^-1*b*a^-1*b, a^-1*b^-1*a^-1), (b*a^-1*b*a^-1, a^-1*b^-1*a^-1*b^-1), (a^2, <identity>), (b^2, b^-1), (b^-1*a*b^-1*a, a*b*a*b), (a*b^-1*a*b^-1*a, b*a*b), (b^-1*a*b^-1*a*b^-1, a*b*a), (b*a*b*a, a*b^-1*a*b^-1), (b*a^-1, a), (a^-1*b, a)]")
  expect_equal(.run("rws_reduce_using_automaton(R, a^2*b^-2*a^2*b)"), "b^-1")
  expect_equal(.run("rws_reduce_using_automaton(R, a^4*b^-2*a^2*b^3)"), "b")
  expect_equal(.run("fp_reduce(G, a^4*b^-2*a^2*b^3)"), "b")
  expect_equal(.err("{rws_set_max(R, 15); rws_add_rule(R, a^-3, b)}"), "Too many rules were defined.")
  expect_equal(.run("{rws_set_max(R, 20); .fw_sort(rws_add_rule(R, a^-3, b))}"), "[]")
  expect_equal(.run("rws_add_rule(R, a, a)"), "set()")
  expect_equal(.run("length(R$rules$k)"), "15")
  .setup("G <- FpGroup(F, list(a^2, b^2, (a*b)^3)); R <- fp_rewriting_system(G); fp_make_confluent(G)")
  expect_equal(.run("rws_is_confluent(R)"), "True")
  expect_equal(.run("{.r <- rws_rules(R); .r[order(vapply(.r, function(p) paste(.fw_sort_key(p[[1]]), .fw_sort_key(p[[2]])), \"\"), method = \"radix\")]}"), "[(a, a^-1), (b, b^-1), (a^-2, <identity>), (b^-2, <identity>), (b^-1*a^-1*b^-1, a^-1*b^-1*a^-1)]")
  expect_equal(.run("lapply(list(a*b*a, b*a*b*a, (a*b)^5, a*b^-1*a^3*b, b^7*a*b^-3), function(w) fp_reduce(G, w))"), "[a^-1*b^-1*a^-1, a^-1*b^-1, b^-1*a^-1, b^-1*a^-1, a^-1*b^-1*a^-1]")
  expect_equal(.run("lapply(list(a*b*a, b*a*b*a, (a*b)^5, a*b^-1*a^3*b, b^7*a*b^-3), function(w) rws_reduce_using_automaton(R, w))"), "[a^-1*b^-1*a^-1, a^-1*b^-1, b^-1*a^-1, b^-1*a^-1, a^-1*b^-1*a^-1]")
  .setup("G <- FpGroup(F, list(a^4, b^2, a*b*a*b)); R <- fp_rewriting_system(G)")
  expect_equal(.run("rws_rules(R)"), "[(a^2, a^-2), (a^-3, a), (b, b^-1), (b^-2, <identity>), (b^-1*a^-1, a*b^-1), (a*b^-1*a, b^-1), (b^-1*a*b^-1, a^-1), (b^-1*a, a^-1*b^-1), (a^3, a^-1), (b^2, <identity>), (b*a^-1, a*b), (a^-1*b*a^-1, b), (b*a^-1*b, a), (b*a, a^-1*b)]")
  expect_equal(.run("rws_is_confluent(R)"), "True")
  expect_equal(.run("{rws_make_confluent(R); length(R$rules$k)}"), "5")
  expect_equal(.run("lapply(list(a^3*b, b*a^2*b*a, (a*b^-1)^3, a^-5*b^3), function(w) fp_reduce(G, w))"), "[a^-1*b^-1, a^-1, a*b^-1, a^-5*b^-1]")
  expect_equal(.run("lapply(list(a^3*b, b*a^2*b*a, (a*b^-1)^3, a^-5*b^3), function(w) rws_reduce_using_automaton(R, w))"), "[a^-1*b, a^-1, a*b^-1, a^-1*b]")
  .setup(".g3 <- free_group(\"x, y, z\"); F3 <- .g3[[1]]; x <- .g3[[2]]; y <- .g3[[3]]; z <- .g3[[4]]; G <- FpGroup(F3, list(x^2, y^2, z^2, (x*y)^3, (y*z)^3, (x*z)^2)); R <- fp_rewriting_system(G)")
  expect_equal(.run("length(R$rules$k)"), "15")
  expect_equal(.run("{fp_make_confluent(G); rws_is_confluent(R)}"), "True")
  expect_equal(.run("length(R$rules$k)"), "10")
  expect_equal(.run("lapply(list(x*y*x, y*x*y*z*y, (x*y*z)^4, z*x*z*y*x*y), function(w) fp_reduce(G, w))"), "[x^-1*y^-1*x^-1, x^-1*y^-1*x^-1*z^-1*y^-1, <identity>, y^-1*x^-1]")
  expect_equal(.run("fp_equals(G, x*y*x, y*x*y)"), "True")
  expect_equal(.run("fp_equals(G, x*z, y*z)"), "False")
})
