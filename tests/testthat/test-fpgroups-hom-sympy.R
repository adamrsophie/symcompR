# Expected values are SymPy's outputs for the same calls (Finitely presented groups (hom)).

skip_unless_full_tests()

skip_on_cran()

.bt <- new.env(parent = asNamespace("symcompR"))
eval(parse(text = r"---(NULL
)---"), envir = .bt)
.run <- function(code) {
  e <- .bt
  NULL
  gsub("\n", " ", get("fp_str", envir = .bt)(eval(parse(text = code), envir = e)), fixed = TRUE)
}
.setup <- function(code) invisible(eval(parse(text = code), envir = .bt))
.err <- function(code) tryCatch({ .run(code); "no error" }, error = function(e) gsub("\n", " ", conditionMessage(e), fixed = TRUE))

test_that("Finitely presented groups (hom) match SymPy", {
  .setup(".g <- free_group(\"a, b\"); F <- .g[[1]]; a <- .g[[2]]; b <- .g[[3]]; G <- FpGroup(F, list(a^3, b^3, (a*b)^2)); c <- Permutation(list(c(0, 1, 2)), size = 4); d <- Permutation(list(c(1, 2, 3)), size = 4); A <- AlternatingGroup(4); T <- homomorphism(G, A, list(a, b), list(c, d))")
  expect_equal(.run("hom_apply(T, a*b^2*a^-1)"), "(0 3 1)")
  expect_equal(.run(".fpp_eq(hom_apply(T, a*b^2*a^-1), c*d^2*perm_inverse(c))"), "True")
  expect_equal(.run("hom_is_isomorphism(T)"), "True")
  expect_equal(.run("hom_apply(T, hom_invert(T, Permutation(list(c(0, 2, 3)), size = 4)))"), "(0 2 3)")
  expect_equal(.run("hom_invert(T, c)"), "a")
  expect_equal(.run("hom_apply(T, list(a, b, a*b, b*a^-1))"), "[Permutation(3)(0, 1, 2), Permutation(1, 2, 3), Permutation(0, 2)(1, 3), Permutation(0, 2, 3)]")
  expect_equal(.run("hom_apply(T, F$identity)"), "(3)")
  expect_equal(.err("hom_apply(T, Permutation(list(c(1, 2))))"), "The supplied element does not belong to the domain")
  expect_equal(.run(".ppg_order(hom_image(T))"), "12")
  expect_equal(.run("hom_is_injective(T)"), "True")
  expect_equal(.run("hom_is_surjective(T)"), "True")
  expect_equal(.run("hom_is_trivial(T)"), "False")
  expect_equal(.run("fps_order(hom_kernel(T))"), "1")
  .setup("T0 <- homomorphism(G, AlternatingGroup(4), G$generators)")
  expect_equal(.run("hom_is_trivial(T0)"), "True")
  expect_equal(.run("fps_order(hom_kernel(T0))"), "12")
  expect_equal(.run(".is_one(fps_order(hom_kernel(T0)) / fp_order(G))"), "True")
  expect_equal(.run("hom_apply(T0, a*b)"), "(3)")
  .setup(".ge <- free_group(\"e\"); E <- .ge[[1]]; e <- .ge[[2]]; GE <- FpGroup(E, list(e^8)); P <- PermutationGroup(list(Permutation(list(c(0, 1, 2, 3))), Permutation(list(c(0, 2))))); TE <- homomorphism(GE, P, list(e), list(Permutation(list(c(0, 1, 2, 3)))))")
  expect_equal(.run(".ppg_order(hom_image(TE))"), "4")
  expect_equal(.run("hom_apply(TE, hom_invert(TE, Permutation(list(c(0, 2), c(1, 3)))))"), "(0 2)(1 3)")
  expect_equal(.run("hom_invert(TE, Permutation(list(c(0, 2), c(1, 3))))"), "e^2")
  expect_equal(.run("hom_invert(TE, Permutation(list(c(0, 3, 2, 1))))"), "e^-1")
  expect_equal(.err("hom_invert(TE, Permutation(list(c(0, 2)), size = 4))"), "Given element is not in the image of the homomorphism.")
  expect_equal(.run("hom_is_injective(TE)"), "False")
  expect_equal(.run("hom_is_surjective(TE)"), "False")
  expect_equal(.run("hom_kernel(TE)"), "<fp subgroup on the generators [e^4]>")
  expect_equal(.run("fps_contains(hom_kernel(TE), e^4)"), "True")
  expect_equal(.run("fps_contains(hom_kernel(TE), e^2)"), "False")
  .setup("TC <- homomorphism(E, AlternatingGroup(4), E$generators, list(c))")
  expect_equal(.run("hom_invert(TC, c^2)"), "e^-1")
  expect_equal(.run("hom_invert(TC, c)"), "e")
  expect_equal(.run("hom_apply(TC, e^5)"), "(3)(0 2 1)")
  expect_equal(.run("hom_is_injective(TC)"), "False")
  expect_equal(.run("fps_contains(hom_kernel(TC), e^3)"), "True")
  expect_equal(.run("fps_contains(hom_kernel(TC), e^2)"), "False")
  expect_equal(.run("hom_apply(homomorphism(F, E, list(a), list(e)), a^-2*b^4*a^2)"), "<identity>")
  expect_equal(.run("hom_apply(homomorphism(F, E, list(a), list(e)), a^-2*b^4*a^3)"), "e")
  expect_equal(.run("hom_apply(homomorphism(F, E, list(a, b), list(e, e^-2)), a*b^3*a)"), "e^-4")
  .setup("Gab <- FpGroup(F, list(a*b*a^-1*b^-1)); Tab <- homomorphism(F, Gab, F$generators, Gab$generators)")
  expect_equal(.run("hom_invert(Tab, a^-1*b^-1*a^2)"), "a*b^-1")
  expect_equal(.run("hom_invert(Tab, b^3*a^-1*b)"), "a^-1*b^4")
  expect_equal(.run("hom_apply(Tab, a*b*a^-1)"), "a*b*a^-1")
  .setup("D <- DihedralGroup(8); p <- Permutation(list(0:7)); P8 <- PermutationGroup(list(p)); TP <- homomorphism(P8, D, list(p), list(p))")
  expect_equal(.run("hom_is_injective(TP)"), "True")
  expect_equal(.run("hom_is_isomorphism(TP)"), "False")
  expect_equal(.run("hom_invert(TP, p^3)"), "(0 3 6 1 4 7 2 5)")
  expect_equal(.run("hom_invert(TP, p^-3)"), "(0 5 2 7 4 1 6 3)")
  expect_equal(.run("hom_invert(TP, group_identity(hom_image(TP)))"), "(7)")
  expect_equal(.run("hom_apply(TP, hom_invert(TP, group_identity(hom_image(TP))))"), "(7)")
  expect_equal(.run("hom_apply(TP, p^5)"), "(0 5 2 7 4 1 6 3)")
  expect_equal(.err("hom_invert(TP, D$gens[[2]])"), "Given element is not in the image of the homomorphism.")
  .setup("T2 <- homomorphism(F, P8, list(F$generators[[1]]), P8$gens); TT <- hom_compose(TP, T2)")
  expect_equal(.run("identical(TT$domain, F)"), "True")
  expect_equal(.run("hom_apply(TT, a*b)"), "(0 1 2 3 4 5 6 7)")
  expect_equal(.run("hom_apply(TT, a^3*b*a)"), "(0 4)(1 5)(2 6)(3 7)")
  .setup("D3 <- DihedralGroup(3); T3 <- homomorphism(D3, D3, D3$gens, D3$gens)")
  expect_equal(.run("hom_is_isomorphism(T3)"), "True")
  expect_equal(.run("hom_apply(T3, D3$gens[[1]]*D3$gens[[2]])"), "(2)(0 1)")
  expect_equal(.run("fp_order(perm_group_presentation(D3))"), "6")
  expect_equal(.err("homomorphism(D3, D3, D3$gens, list(D3$gens[[1]], D3$gens[[1]]))"), "The given images do not define a homomorphism")
  expect_equal(.run("hom_is_surjective(homomorphism(D3, CyclicGroup(2), D3$gens, list(Permutation(c(0, 1)), Permutation(c(1, 0)))))"), "True")
  expect_equal(.run(".ppg_order(hom_kernel(homomorphism(D3, CyclicGroup(2), D3$gens, list(Permutation(c(0, 1)), Permutation(c(1, 0))))))"), "3")
  .setup(".gc <- free_group(\"c, d\"); Fc <- .gc[[1]]; cc <- .gc[[2]]; dd <- .gc[[3]]; Gi <- FpGroup(F, list(a^2, b^3)); Hi <- FpGroup(F, list(b^3, a^2))")
  expect_equal(.run("is_isomorphic(Gi, Hi)"), "True")
  .setup("H2 <- FpGroup(F, list(a^3, b^3, (a*b)^2)); G2 <- FpGroup(Fc, list(cc^3, dd^3, (cc*dd)^2)); .gi <- group_isomorphism(G2, H2); check <- .gi[[1]]; Ti <- .gi[[2]]")
  expect_equal(.run("check"), "True")
  expect_equal(.run("hom_apply(Ti, cc^3*dd^2)"), "a^3*b^2")
  expect_equal(.run("hom_apply(Ti, cc)"), "a")
  expect_equal(.run("hom_apply(Ti, dd)"), "b")
  .setup(".gi <- group_isomorphism(G, AlternatingGroup(4)); check2 <- .gi[[1]]; T4 <- .gi[[2]]")
  expect_equal(.run("check2"), "True")
  expect_equal(.run("hom_apply(T4, b*a*b^-1*a^-1*b^-1)"), "(0 2 3)")
  expect_equal(.run("hom_apply(T4, b*a*b*a^-1*b^-1)"), "(0 3 2)")
  expect_equal(.run("hom_apply(T4, a)"), "(3)(0 1 2)")
  expect_equal(.run("hom_apply(T4, b)"), "(1 2 3)")
  expect_equal(.run("is_isomorphic(DihedralGroup(8), PermutationGroup(list(Permutation(list(0:7)))))"), "False")
  expect_equal(.run("group_isomorphism(DihedralGroup(8), PermutationGroup(list(Permutation(list(0:7)))))"), "(False, None)")
  expect_equal(.run("is_isomorphic(CyclicGroup(5), CyclicGroup(7))"), "False")
  expect_equal(.run("fp_order(FpGroup(F, list(a, b^5)))"), "5")
  expect_equal(.run("is_isomorphic(FpGroup(F, list(a, b^5)), CyclicGroup(5))"), "True")
  expect_equal(.run("is_isomorphic(SymmetricGroup(3), PermutationGroup(list(Permutation(list(c(0, 1), c(2, 4), c(3, 5))), Permutation(list(c(0, 2), c(1, 3), c(4, 5))))))"), "True")
  expect_equal(.run("group_isomorphism(SymmetricGroup(3), PermutationGroup(list(Permutation(list(c(0, 1), c(2, 4), c(3, 5))), Permutation(list(c(0, 2), c(1, 3), c(4, 5))))))[[2]] |> hom_images()"), "{Permutation(0, 1, 2): Permutation(0, 3, 4)(1, 2, 5), Permutation(2)(0, 1): Permutation(0, 1)(2, 4)(3, 5)}")
  expect_equal(.run("is_isomorphic(CyclicGroup(6), PermutationGroup(list(Permutation(list(c(0, 1, 2)), size = 5), Permutation(list(c(3, 4)))))) "), "True")
  expect_equal(.run("is_isomorphic(CyclicGroup(4), PermutationGroup(list(Permutation(list(c(0, 1)), size = 4), Permutation(list(c(2, 3))))))"), "False")
  expect_equal(.err("group_isomorphism(FpGroup(F, list(a^2)), CyclicGroup(2))"), "Isomorphism methods are not implemented for infinite groups.")
  expect_equal(.err("group_isomorphism(F, CyclicGroup(2))"), "The group must be a PermutationGroup or an FpGroup")
  expect_equal(.err("{G4 <- PermutationGroup(list(Permutation(list(c(1, 2, 3, 4))), Permutation(list(c(1, 3)), size = 5))); homomorphism(G4, G4, list(G4$gens[[1]]), list(G4$gens[[1]]))}"), "The given images do not define a homomorphism")
  expect_equal(.err("homomorphism(F, E, list(a, e), list(e, e))"), "The supplied generators must be a subset of the domain's generators")
  expect_equal(.err("homomorphism(F, E, list(a), list(a))"), "The images must be elements of the codomain")
  expect_equal(.err("homomorphism(F, E, list(a, b), list(e))"), "The number of images must be equal to the number of generators")
  expect_equal(.err("homomorphism(1, E, list(a), list(e))"), "The domain must be a group")
  expect_equal(.err("homomorphism(F, 1, list(a), list(e))"), "The codomain must be a group")
  expect_equal(.err("homomorphism(GE, E, list(e), list(e^3))"), "The given images do not define a homomorphism")
  expect_equal(.run("hom_apply(homomorphism(GE, FpGroup(E, list(e^4)), list(e), list(e^3)), e^5)"), "e^15")
  expect_equal(.err("homomorphism(FpGroup(E, list(e^6)), FpGroup(E, list(e^4)), list(e), list(e^3))"), "The given images do not define a homomorphism")
  .setup(".g1 <- free_group(\"x\"); F1 <- .g1[[1]]; x <- .g1[[2]]; G1 <- FpGroup(F1, list())")
  expect_equal(.run("hom_is_surjective(homomorphism(G1, G1, list(x), list(x)))"), "True")
  expect_equal(.run("hom_is_surjective(homomorphism(G1, G1, list(x), list(x^2)))"), "False")
  expect_equal(.run("hom_is_surjective(homomorphism(G1, G1, list(x), list(x^-1)))"), "True")
  expect_equal(.run("hom_invert(homomorphism(G1, G1, list(x), list(x^-1)), x^3)"), "x^-3")
  expect_equal(.run("hom_invert(homomorphism(G1, G1, list(x), list(x^2)), x^6)"), "x^3")
  expect_equal(.err("hom_invert(homomorphism(G1, G1, list(x), list(x^2)), x^3)"), "Given element is not in the image of the homomorphism.")
  .setup("Gk <- FpGroup(F, list(a^2)); Hk <- FpGroup(F, list(a^2, b^3, (a*b)^2)); Tk <- homomorphism(Gk, Hk, Gk$generators, Hk$generators); kk <- hom_kernel(Tk)")
  expect_equal(.run("kk$normal"), "True")
  expect_equal(.run("fps_contains(kk, b^3)"), "True")
  expect_equal(.run("fps_contains(kk, (a*b)^2)"), "True")
  expect_equal(.run("fps_contains(kk, b)"), "False")
  expect_equal(.run("fps_contains(kk, a*b)"), "False")
  expect_equal(.run(".fw_sort(kk$generators)"), "[a^-2, a^2, b^3, a^-1*b*a^-1*b]")
  .setup(".gz <- free_group(\"c\"); Z <- .gz[[1]]; cz <- .gz[[2]]; GZ <- FpGroup(Z, list()); TZ <- homomorphism(F, GZ, list(a, b), list(cz, cz)); kz <- hom_kernel(TZ)")
  expect_equal(.run("kz$normal"), "True")
  expect_equal(.run("fps_contains(kz, b*a^-1)"), "True")
  expect_equal(.run("fps_contains(kz, a)"), "False")
  expect_equal(.run("kz"), "<fp subgroup on the generators [b*a^-1]>")
  .setup("TF <- homomorphism(F, Hk, F$generators, Hk$generators); kf <- hom_kernel(TF)")
  expect_equal(.run("kf$normal"), "True")
  expect_equal(.run("fps_contains(kf, a^2)"), "True")
  expect_equal(.run("fps_contains(kf, b^3)"), "True")
  expect_equal(.run("fps_contains(kf, (a*b)^2)"), "True")
  expect_equal(.run("fps_contains(kf, a*b)"), "False")
  .setup(".gxy <- free_group(\"x, y\"); Exy <- .gxy[[1]]; xx <- .gxy[[2]]; yy <- .gxy[[3]]; Hxy <- FpGroup(Exy, list(yy^2, yy*xx*yy*xx)); Txy <- homomorphism(F, Hxy, list(a, b), list(xx, xx))")
  expect_equal(.run("hom_is_surjective(Txy)"), "False")
  expect_equal(.run("hom_kernel(Txy)$normal"), "True")
  expect_equal(.run("fps_contains(hom_kernel(Txy), b*a^-1)"), "True")
  expect_equal(.run("fps_contains(hom_kernel(Txy), a)"), "False")
  .setup("c3 <- Permutation(list(c(0, 1, 2))); C3 <- PermutationGroup(list(c3)); T3c <- homomorphism(F, C3, list(a, b), list(c3, c3)); k3 <- hom_kernel(T3c)")
  expect_equal(.run("k3$normal"), "True")
  expect_equal(.run("fps_contains(k3, b*a^-1)"), "True")
  expect_equal(.run("fps_contains(k3, a^3)"), "True")
  expect_equal(.run("fps_contains(k3, a^2)"), "False")
  .setup("Gc <- FpGroup(F, list(a*b*a^-1*b^-1)); Tgc <- homomorphism(Gc, C3, Gc$generators, list(c3, c3)); kgc <- hom_kernel(Tgc)")
  expect_equal(.run("kgc$normal"), "True")
  expect_equal(.run("fps_contains(kgc, b*a^-1)"), "True")
  expect_equal(.run("fps_contains(kgc, a^3)"), "True")
  expect_equal(.run("fps_contains(kgc, a*b)"), "False")
  .setup("D4p <- PermutationGroup(list(Permutation(list(c(0, 1, 2, 3))), Permutation(list(c(0, 3), c(1, 2))))); TD <- homomorphism(F, D4p, list(a), list(Permutation(list(c(0, 1, 2, 3))))); kd <- hom_kernel(TD)")
  expect_equal(.run("kd$normal"), "True")
  expect_equal(.run("fps_contains(kd, b)"), "True")
  expect_equal(.run("fps_contains(kd, a^4)"), "True")
  expect_equal(.run("fps_contains(kd, a^2)"), "False")
  .setup("Hf <- FpGroup(F, list(a^2, b^2, (a*b)^2)); Tf <- homomorphism(F, Hf, list(a, b), list(a, a)); .sf <- hom_factor(Tf); surj <- .sf[[1]]; inj <- .sf[[2]]")
  expect_equal(.run("hom_is_surjective(surj)"), "True")
  expect_equal(.run("hom_is_injective(inj)"), "True")
  expect_equal(.run("fp_equals(Hf, hom_apply(inj, hom_apply(surj, a*b*a^-1)), hom_apply(Tf, a*b*a^-1))"), "True")
  expect_equal(.run("hom_apply(surj, a*b*a^-1)"), "a_0^-1")
  expect_equal(.run("surj$codomain"), "<fp group on the generators (a_0,)>")
  expect_equal(.run("surj$codomain$relators"), "(a_0^2,)")
  .setup(".gf <- free_group(\"x, y\"); Ef <- .gf[[1]]; xf <- .gf[[2]]; yf <- .gf[[3]]; Tf2 <- homomorphism(F, Ef, list(a, b), list(xf, yf)); .sf2 <- hom_factor(Tf2); surj2 <- .sf2[[1]]; inj2 <- .sf2[[2]]")
  expect_equal(.run("hom_is_surjective(surj2)"), "True")
  expect_equal(.run("hom_apply(inj2, hom_apply(surj2, a*b^2*a^-1)) == hom_apply(Tf2, a*b^2*a^-1)"), "True")
  expect_equal(.run("hom_apply(inj2, hom_apply(surj2, a*b^2*a^-1))"), "x*y^2*x^-1")
  expect_equal(.run("hom_apply(surj2, a*b^2*a^-1)"), "x_0*y_0^2*x_0^-1")
  .setup(".gr <- free_group(\"r, s\"); Fr <- .gr[[1]]; r <- .gr[[2]]; s <- .gr[[3]]; Fab <- F; aa <- a; bb <- b")
  expect_equal(.run("is_isomorphic(FpGroup(Fr, list(r^3, s^2, s*r*s*r)), FpGroup(Fab, list(aa^2, bb^2, (aa*bb)^3)))"), "True")
  expect_equal(.run("is_isomorphic(FpGroup(Fr, list(r^4, s^2, s*r*s*r)), FpGroup(Fab, list(aa^2, bb^2, (aa*bb)^4)))"), "True")
  .setup(".gij <- free_group(\"i, j\"); Fij <- .gij[[1]]; i <- .gij[[2]]; j <- .gij[[3]]; Q8 <- FpGroup(Fij, list(i^4, i^2 * j^-2, j^-1 * i * j * i))")
  expect_equal(.run("is_isomorphic(Q8, FpGroup(Exy, list(xx^4, xx^2 * yy^-2, yy^-1 * xx * yy * xx)))"), "True")
  .setup(".gstu <- free_group(\"s, t, u\"); Fstu <- .gstu[[1]]; s1 <- .gstu[[2]]; t1 <- .gstu[[3]]; u1 <- .gstu[[4]]")
  expect_equal(.run("is_isomorphic(FpGroup(Fab, list(aa^4, bb^2, (aa*bb)^3)), FpGroup(Fstu, list(s1^2, t1^2, u1^2, (s1*t1)^3, (t1*u1)^3, (s1*u1)^2)))"), "True")
  .setup(".gabc <- free_group(\"a, b, c\"); Fabc <- .gabc[[1]]; a3 <- .gabc[[2]]; b3 <- .gabc[[3]]; c3w <- .gabc[[4]]")
  expect_equal(.run("is_isomorphic(FpGroup(Fabc, list(a3^2, b3^2, c3w^2, a3*b3*a3^-1*b3^-1, a3*c3w*a3^-1*c3w^-1, b3*c3w*b3^-1*c3w^-1)), FpGroup(Exy, list(xx^4, yy^4, xx^2*yy^-2, xx*yy*(yy*xx)^-1)))"), "False")
  expect_equal(.run("is_isomorphic(Q8, FpGroup(Fr, list(r^4, s^2, (r*s)^2)))"), "False")
  expect_equal(.err("is_isomorphic(FpGroup(Fstu, list(s1^2, t1^3, (s1*t1)^3)), FpGroup(Exy, list(xx^2, yy^3, (xx*yy)^3)))"), "Isomorphism methods are not implemented for infinite groups.")
  .setup("S4 <- SymmetricGroup(4); To <- orbit_homomorphism(S4, list(0, 1, 2, 3))")
  expect_equal(.run("hom_apply(To, S4$gens[[1]])"), "(0 1 2 3)")
  expect_equal(.run(".ppg_order(hom_kernel(To))"), "1")
  expect_equal(.run("hom_is_injective(To)"), "True")
  .setup("Tob <- orbit_homomorphism(PermutationGroup(list(Permutation(list(c(0, 1)), size = 5), Permutation(list(c(2, 3, 4))))), list(2, 3, 4))")
  expect_equal(.run("lapply(Tob$domain$gens, function(g) hom_apply(Tob, g))"), "[Permutation(2), Permutation(0, 1, 2)]")
  expect_equal(.run("hom_kernel(Tob)"), "PermutationGroup([     (4)(0 1)])")
  .setup("Tb <- block_homomorphism(DihedralGroup(4), c(0, 1, 0, 1))")
  expect_equal(.run("lapply(DihedralGroup(4)$gens, function(g) hom_apply(Tb, g))"), "[Permutation(0, 1), Permutation(0, 1)]")
  expect_equal(.run(".ppg_order(Tb$codomain)"), "2")
  expect_equal(.run(".ppg_order(hom_image(Tb))"), "2")
  expect_equal(.run(".ppg_order(hom_kernel(Tb))"), "4")
  expect_equal(.run("hom_is_surjective(Tb)"), "True")
  .setup("Tr <- homomorphism(DihedralGroup(4), SymmetricGroup(4), DihedralGroup(4)$gens, DihedralGroup(4)$gens)")
  expect_equal(.run("hom_images(hom_restrict_to(Tr, PermutationGroup(list(Permutation(list(c(0, 2), c(1, 3)))))))"), "{Permutation(0, 2)(1, 3): Permutation(0, 2)(1, 3)}")
  expect_equal(.run(".ppg_order(hom_invert_subgroup(Tr, PermutationGroup(list(Permutation(list(c(0, 2), c(1, 3)))))))"), "2")
  expect_equal(.run("hom_is_isomorphism(Tr)"), "False")
  expect_equal(.run("hom_is_injective(Tr)"), "True")
})
