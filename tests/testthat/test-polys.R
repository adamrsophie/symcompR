x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); a <- Symbol("a")
s <- function(e) sstr(e)

test_that("expand works like SymPy", {
  expect_equal(s(expand((x + y)^3)), "x^3 + 3*x^2*y + 3*x*y^2 + y^3")
  expect_equal(s(expand((x + 1) * (x - 1))), "x^2 - 1")
  expect_equal(length(expand((x + y + z)^20)$args), 231L)
  expect_equal(s(expand_trig(sin(x + y))), "sin(x)*cos(y) + sin(y)*cos(x)")
  expect_equal(s(expand(exp(x + y))), "exp(x)*exp(y)")
})

test_that("factor matches SymPy", {
  expect_equal(s(sym_factor(x^4 - 1)), "(x - 1)*(x + 1)*(x^2 + 1)")
  expect_equal(s(sym_factor(x^4 + 3*x^2 + 2)), "(x^2 + 1)*(x^2 + 2)")
  expect_equal(s(sym_factor(x^2*y - y^3)), "y*(x - y)*(x + y)")
  expect_equal(s(sym_factor(2*x^3 - 2*x)), "2*x*(x - 1)*(x + 1)")
  expect_equal(s(sym_factor(x^8 - 1)), "(x - 1)*(x + 1)*(x^2 + 1)*(x^4 + 1)")
  expect_equal(s(sym_factor(x^3 - y^3)), "(x - y)*(x^2 + x*y + y^2)")
  expect_equal(s(sym_factor(x*y + x + y + 1)), "(x + 1)*(y + 1)")
  expect_equal(s(sym_factor(x^4 - 10*x^2 + 1)), "x^4 - 10*x^2 + 1")
  big <- expand((x^5 + x + 1) * (x^4 - 3*x + 7) * (2*x - 3)^2)
  expect_equal(s(sym_factor(big)), "(2*x - 3)^2*(x^2 + x + 1)*(x^3 - x^2 + 1)*(x^4 - 3*x + 7)")
  expect_equal(s(sym_factor((x^2 - 1) / (x^2 + 2*x + 1))), "(x - 1)/(x + 1)")
})

test_that("gcd, cancel, apart, together", {
  expect_equal(s(gcd(x^2 - 1, x^2 + 2*x + 1)), "x + 1")
  expect_equal(s(gcd(x^2*y - y, x*y^2 + y^2)), "x*y + y")
  expect_equal(s(sym_lcm(x^2 - 1, x - 1)), "x^2 - 1")
  expect_equal(s(gcd(S(12), S(18))), "6")
  expect_equal(s(cancel((x^2 - 1) / (x - 1))), "x + 1")
  expect_equal(s(cancel((x^2 - y^2) / (x - y))), "x + y")
  expect_equal(s(together(1/x + 1/y)), "(x + y)/(x*y)")
  expect_equal(s(apart(1 / (x^2 - 1), x)), "-1/(2*(x + 1)) + 1/(2*(x - 1))")
  expect_equal(s(apart((x^2 + 1) / (x^3 - x), x)), "1/(x + 1) + 1/(x - 1) - 1/x")
})

test_that("polynomial utilities", {
  d <- div(x^3 + 2*x + 1, x - 1)
  expect_equal(s(d$q), "x^2 + x + 3")
  expect_equal(s(d$r), "4")
  expect_equal(degree(x^3 + x*y^4, x), 3)
  expect_equal(s(LC(3*x^2*y + x, x)), "3*y")
  expect_equal(s(resultant(x^2 - 1, x - 2, x)), "3")
  expect_equal(s(discriminant(a*x^2 + y*x + z, x)), "-4*a*z + y^2")
  expect_equal(s(sqf((x - 1)^2 * (x + 2))), "(x - 1)^2*(x + 2)")
  expect_equal(s(horner(x^3 + 2*x^2 + 3*x + 4, x)), "x*(x*(x + 2) + 3) + 4")
  expect_equal(s(interpolate(list(c(1, 1), c(2, 4), c(3, 9)), x)), "x^2")
  expect_equal(count_roots(x^3 - 2*x, x), 3L)
})

test_that("Groebner bases", {
  G <- groebner(list(x^2 + y^2 - 1, x - y), x, y)
  expect_equal(vapply(G, sstr, ""), c("x - y", "2*y^2 - 1"))
  G2 <- groebner(list(x*y - 1, x^2 - y), x, y)
  expect_equal(vapply(G2, sstr, ""), c("x - y^2", "y^3 - 1"))
})

test_that("roots and solve", {
  r <- roots(x^2 - 3*x + 2, x)
  expect_equal(vapply(r, sstr, ""), c("2", "1"))  # SymPy: {2: 1, 1: 1}
  r2 <- roots((x - 1)^2 * (x + 3), x)
  expect_equal(vapply(r2, sstr, ""), c("-3", "1"))
  expect_equal(attr(r2, "multiplicity"), c(1L, 2L))
  expect_equal(length(roots(x^3 - 1, x)), 3L)
  expect_equal(vapply(solve(x^2 - 4, x), sstr, ""), c("-2", "2"))
  expect_equal(vapply(solve(Eq(exp(x), 3), x), sstr, ""), "log(3)")
  sol <- solve(list(x + y - 3, x - y - 1), list(x, y))
  # SymPy returns a dict for a linear system: {x: 2, y: 1}
  expect_equal(s(sol$x), "2")
  expect_equal(s(sol$y), "1")
  sol2 <- solve(list(x^2 + y^2 - 5, x - y + 1), list(x, y))
  expect_length(sol2, 2L)
  expect_equal(vapply(solve(sin(x), x), sstr, ""), c("0", "pi"))
})

test_that("polys review regressions stay fixed", {
  expect_equal(s(expand(sqf((x + 1) * (y + 1)))), "x*y + x + y + 1")
  expect_length(solve(S(10)^20 * (x^5 - x + 1), x), 5L)
  expect_length(solve(list(x / y, y), list(x, y)), 0L)
  expect_equal(s(powdenest(sqrt(exp(x)))), "sqrt(exp(x))")
  expect_equal(s(nroots(x - sym_I, x)[[1]]), "1.0*I")
  expect_equal(s(sqrtdenest(sqrt(-3 + 2 * sqrt(S(2))))), "sqrt(-3 + 2*sqrt(2))")
  expect_equal(vapply(solve(sinh(x), x), sstr, ""), c("0", "I*pi"))
  expect_true(is_zero_dimensional(list(x^2 - y, y^2 - x), x, y))
})

test_that("algebra review fixes", {
  x <- Symbol("x"); y <- Symbol("y"); p <- Symbol("p", positive = TRUE); f <- Function("f")
  A <- Symbol("A", commutative = FALSE); B <- Symbol("B", commutative = FALSE)
  expect_equal(sstr(gammasimp(gamma(x + 1) * gamma(x + 2) / gamma(x) / gamma(x + 3))), "x/(x + 2)")
  expect_equal(sstr(powdenest(sqrt(p^(3 * sym_pi * sym_I)))), "sqrt(p^(3*I*pi))")
  expect_length(solve(list(exp(x) - 1, exp(x) - 2), x), 0)
  expect_equal(sstr(dsolve(Derivative(f(x), x) - f(x)^2, f(x), ics = list(list(0, 0, 1)))), "Eq(f(x), -1/(x - 1))")
  expect_equal(sstr(nsolve(list(x + sym_I), list(x), list(0))$x), "-1.0*I")
  g <- gcdex(x * y + 1, x + 1, x)
  expect_equal(vapply(g, sstr, ""), c(s = "-1/(y - 1)", t = "y/(y - 1)", h = "1"))
  expect_equal(sstr(expand((A + B)^2)), "A*B + A^2 + B*A + B^2")
  expect_equal(sstr(expand_power_exp(A^(x + y))), "A^x*A^y")
  expect_length(nroots(x^2, x), 2)
  expect_equal(count_roots(x, x, as_bigq(Rational("-1e-400")), 1), 1L)
  expect_equal(vapply(solve(p^2 - 1, p), sstr, ""), "1")
  expect_error(nsolve(exp(x), x, 0, maxit = 2), "did not converge")
  d <- div(x^2, y * x + 1, x)
  expect_equal(vapply(d, sstr, ""), c(q = "x/y - 1/y^2", r = "y^(-2)"))
  expect_equal(sstr(expand_power_exp(S(0)^(x + y))), "0^(x + y)")
  expect_equal(sstr(coeff(x + 2, x, 0)), "2")
})

test_that("second algebra review fixes", {
  x <- Symbol("x"); y <- Symbol("y"); f <- Function("f")
  A <- Symbol("A", commutative = FALSE); B <- Symbol("B", commutative = FALSE)
  expect_equal(sstr(dsolve(Derivative(f(x), x) - Symbol("C1") * f(x), f(x), ics = list(list(0, 0, 2)))),
               "Eq(f(x), 2*exp(C1*x))")
  expect_equal(sstr(sqf_part(S(0), x)), "0")
  expect_equal(sstr(expand_power_base((A * B)^2)), "A*B*A*B")
  expect_equal(vapply(nroots(x^2 + Rational("1e-24"), x), function(z) Im(as.complex(z)), 0), c(-1e-12, 1e-12))
  expect_equal(vapply(nroots((x - 1)^2 * (x + 2), x), sstr, ""), c("-2.00000000000000", "1.00000000000000", "1.00000000000000"))
  expect_equal(vapply(gcdex(y * x, x + 1, x), sstr, ""), c(s = "-1/y", t = "1", h = "1"))
  expect_length(solve(list(sin(x), cos(x)), list(x)), 0)
})
