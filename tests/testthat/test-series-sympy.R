test_that("series(n = NULL) is the lazy series and errors carry SymPy's classes", {
  lz <- function(g, k) paste(vapply(take(g, k), mi_fmt, ""), collapse = ", ")
  expect_equal(lz(series(cos(x), x, 1, n = NULL), 4), "cos(1), -(x - 1)*sin(1), -(x - 1)^2*cos(1)/2, (x - 1)^3*sin(1)/6")
  expect_equal(lz(series(exp(x) / x, x, n = NULL), 4), "1/x, 1, x/2, x^2/6")
  expect_equal(lz(series(x^2 + x, x, n = NULL), 4), "x, x^2")
  expect_error(series(cos(x + y)), "x must be given for multivariate functions.", fixed = TRUE, class = "ValueError")
  expect_error(Order(exp(x), x, x), "unique symbols, got [x, x]", fixed = TRUE, class = "ValueError")
  expect_error(Order(x, 2 - x), "not symbols, got [2 - x]", fixed = TRUE, class = "TypeError")
  expect_error(series((1 / sin(x))^oo), class = "PoleError")
})
