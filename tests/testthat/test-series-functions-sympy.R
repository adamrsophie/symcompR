# Expected values are SymPy's outputs for the same calls (Series of special functions).

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); a <- Symbol("a"); b <- Symbol("b"); w <- Symbol("w"); n <- Symbol("n", integer = TRUE)
mi_fmt <- function(v) if (is.null(v)) "None" else gsub("\n", " ", sstr(v))

test_that("Series of special functions match SymPy", {
  expect_equal(mi_fmt(series(Abs(x), x)), "x")
  expect_equal(mi_fmt(series(sign(x), x)), "1")
  expect_equal(mi_fmt(series(gamma(x), x, 0, 3)), "1/x - EulerGamma + x*(EulerGamma^2/2 + pi^2/12) + x^2*(-EulerGamma*pi^2/12 - zeta(3)/3 - EulerGamma^3/6) + O(x^3)")
  expect_equal(mi_fmt(series(erf(x), x, 0, 4)), "2*x/sqrt(pi) - 2*x^3/(3*sqrt(pi)) + O(x^4)")
  expect_equal(mi_fmt(series(Si(x), x, 0, 6)), "x - x^3/18 + x^5/600 + O(x^6)")
  expect_equal(mi_fmt(series(Ci(x), x, 0, 4)), "EulerGamma + log(x) - x^2/4 + O(x^4)")
  expect_equal(mi_fmt(series(floor(x+1), x)), "1")
  expect_equal(mi_fmt(series(Mod(x,3), x)), "x")
  expect_equal(mi_fmt(series(LambertW(x), x, 0, 4)), "x - x^2 + 3*x^3/2 + O(x^4)")
  expect_equal(mi_fmt(series(loggamma(x), x, 0, 3)), "-log(x) - EulerGamma*x + pi^2*x^2/12 + O(x^3)")
  expect_equal(mi_fmt(series(factorial(x), x, 0, 3)), "1 - EulerGamma*x + x^2*(EulerGamma^2/2 + pi^2/12) + O(x^3)")
  expect_equal(mi_fmt(as_leading_term(gamma(x), x)), "1/x")
  expect_equal(mi_fmt(series(erf(1/x), x, 0, 3)), "-(x + O(x^3))*exp(-1/x^2)/sqrt(pi) + 1")
  expect_equal(mi_fmt(series(loggamma(1/x), x, 0, 3)), "(-log(x) - 1)/x + log(2*pi)/2 + log(x)/2 + x/12 + O(x^3)")
  expect_equal(mi_fmt(series(Ei(x), x, 0, 3)), "EulerGamma + log(x) + x + x^2/4 + O(x^3)")
  expect_equal(mi_fmt(series(fresnels(x), x, 0, 8)), "pi*x^3/6 - pi^3*x^7/336 + O(x^8)")
  expect_equal(mi_fmt(series(fresnelc(x), x, 0, 6)), "x - pi^2*x^5/40 + O(x^6)")
  expect_equal(mi_fmt(series(erfc(x), x, 0, 4)), "1 - 2*x/sqrt(pi) + 2*x^3/(3*sqrt(pi)) + O(x^4)")
  expect_equal(mi_fmt(series(erfi(x), x, 0, 4)), "2*x/sqrt(pi) + 2*x^3/(3*sqrt(pi)) + O(x^4)")
  expect_equal(mi_fmt(series(sinh(x), x, 0, 6)), "x + x^3/6 + x^5/120 + O(x^6)")
  expect_equal(mi_fmt(series(tanh(x), x, 0, 6)), "x - x^3/3 + 2*x^5/15 + O(x^6)")
  expect_equal(mi_fmt(series(asin(x), x, 0, 6)), "x + x^3/6 + 3*x^5/40 + O(x^6)")
  expect_equal(mi_fmt(series(atan(x), x, 0, 6)), "x - x^3/3 + x^5/5 + O(x^6)")
  expect_equal(mi_fmt(series(acos(x), x, 0, 4)), "pi/2 - x - x^3/6 + O(x^4)")
  expect_equal(mi_fmt(series(tan(x), x, 0, 8)), "x + x^3/3 + 2*x^5/15 + 17*x^7/315 + O(x^8)")
  expect_equal(mi_fmt(series(cot(x), x, 0, 4)), "1/x - x/3 - x^3/45 + O(x^4)")
  expect_equal(mi_fmt(series(sec(x), x, 0, 6)), "1 + x^2/2 + 5*x^4/24 + O(x^6)")
  expect_equal(mi_fmt(series(csc(x), x, 0, 4)), "1/x + x/6 + 7*x^3/360 + O(x^4)")
  expect_equal(mi_fmt(series(asinh(x), x, 0, 6)), "x - x^3/6 + 3*x^5/40 + O(x^6)")
  expect_equal(mi_fmt(series(atanh(x), x, 0, 6)), "x + x^3/3 + x^5/5 + O(x^6)")
  expect_equal(mi_fmt(series(acosh(x), x, 0, 3)), "I*pi/2 - I*x + O(x^3)")
  expect_equal(mi_fmt(series(asin(x), x, 1, 3)), "pi/2 - sqrt(2)*I*sqrt(x - 1) + sqrt(2)*I*(x - 1)^(3/2)/12 - 3*sqrt(2)*I*(x - 1)^(5/2)/160 + O((x - 1)^3, (x, 1))")
  expect_equal(mi_fmt(series(exp(x), x, oo)), "exp(x)")
  expect_equal(mi_fmt(series(1/(1-x), x, oo, 4)), "-1/x^3 - 1/x^2 - 1/x + O(x^(-4), (x, oo))")
  expect_equal(mi_fmt(series(sin(x), x, S_Pi/2, 4)), "1 - (x - pi/2)^2/2 + O((x - pi/2)^4, (x, pi/2))")
  expect_equal(mi_fmt(series(x^x, x, 0, 3)), "1 + x*log(x) + x^2*log(x)^2/2 + O(x^3*log(x)^3)")
  expect_equal(mi_fmt(series(sin(x)/x, x, 0, 5)), "1 - x^2/6 + x^4/120 + O(x^5)")
  expect_equal(mi_fmt(series(1/sin(x), x, 0, 3)), "1/x + x/6 + O(x^3)")
  expect_equal(mi_fmt(series(log(sin(x)), x, 0, 4)), "log(x) - x^2/6 + O(x^4)")
  expect_equal(mi_fmt(series(sqrt(1+x), x, 0, 4)), "1 + x/2 - x^2/8 + x^3/16 + O(x^4)")
  expect_equal(mi_fmt(series(exp(x)/(1-x), x, 0, 4)), "1 + 2*x + 5*x^2/2 + 8*x^3/3 + O(x^4)")
  expect_equal(mi_fmt(series(cos(x), x, 0, 1)), "1 + O(x)")
  expect_equal(mi_fmt(series(sin(x), x, 0, 0)), "O(1)")
  expect_equal(mi_fmt(series(x^2+x, x, 0, 10)), "x^2 + x")
  expect_equal(mi_fmt(series(1/x + x, x, 0, 3)), "x + 1/x")
  expect_equal(mi_fmt(series(exp(1/x), x, oo, 3)), "1/(2*x^2) + 1/x + 1 + O(x^(-3), (x, oo))")
  expect_equal(mi_fmt(series(sin(x), x, 0, 6, dir = "-")), "x - x^3/6 + x^5/120 + O(x^6)")
  expect_equal(mi_fmt(series(log(x), x, 1, 4)), "-1 - (x - 1)^2/2 + (x - 1)^3/3 + x + O((x - 1)^4, (x, 1))")
  expect_equal(mi_fmt(series(1/(x*(1+x)), x, 0, 3)), "1/x - 1 + x - x^2 + O(x^3)")
  expect_equal(mi_fmt(O(x^2) + x^3), "O(x^2)")
  expect_equal(mi_fmt(O(x) * x), "O(x^2)")
  expect_equal(mi_fmt(O(x)^2), "O(x^2)")
  expect_equal(mi_fmt(subs(x + O(x^2), x, 2*x)), "2*x + O(x^2)")
  expect_equal(mi_fmt(subs(O(x), x, y)), "O(y)")
  expect_equal(mi_fmt(diff(O(x^2), x)), "O(x)")
  expect_equal(mi_fmt(removeO(O(x^3))), "0")
  expect_equal(mi_fmt(getO(x + O(x^2))), "O(x^2)")
  expect_equal(mi_fmt(O(1/x, list(x, oo)) + 1/x^2), "O(1/x, (x, oo))")
  expect_equal(mi_fmt(O(x*y) + x), "x + O(x*y, x, y)")
  expect_equal(mi_fmt(.so_contains(O(x^2, x), x^3)), "True")
  expect_equal(mi_fmt(series(besselj(0,x),x,0,6)), "1 - x^2/4 + x^4/64 + O(x^6)")
  expect_equal(mi_fmt(series(besselj(1,x),x,0,6)), "x/2 - x^3/16 + x^5/384 + O(x^6)")
  expect_equal(mi_fmt(series(besseli(2,x),x,0,5)), "x^2/8 + x^4/96 + O(x^5)")
  expect_equal(mi_fmt(series(besselk(0,x),x,0,4)), "log(2) - EulerGamma - log(x) + x^2*(-log(x)/4 - EulerGamma/4 + log(2)/4 + 1/4) + O(x^4*log(x))")
  expect_equal(mi_fmt(series(bessely(1,x),x,0,4)), "-2/(pi*x) + x*(log(x)/pi - log(2)/pi - (1 - 2*EulerGamma)/(2*pi)) + x^3*(-log(x)/(8*pi) + (5/2 - 2*EulerGamma)/(16*pi) + log(2)/(8*pi)) + O(x^4*log(x))")
  expect_equal(mi_fmt(series(hyper(list(1,2), list(3), x), x, 0, 4)), "1 + 2*x/3 + x^2/2 + 2*x^3/5 + O(x^4)")
  expect_equal(mi_fmt(series(fcall("elliptic_k", list(x)), x, 0, 3)), "pi/2 + pi*x/8 + 9*pi*x^2/128 + O(x^3)")
  expect_equal(mi_fmt(series(fcall("polylog", list(as_sym(2), x)), x, 0, 4)), "x + x^2/4 + x^3/9 + O(x^4)")
  expect_equal(mi_fmt(series(fcall("elliptic_e", list(x)), x, 0, 3)), "pi/2 - pi*x/8 - 3*pi*x^2/128 + O(x^3)")
  expect_equal(mi_fmt(series(asec(x), x, 2, 3)), "pi/3 + sqrt(3)*(x - 2)/6 - 7*sqrt(3)*(x - 2)^2/72 + O((x - 2)^3, (x, 2))")
  expect_equal(mi_fmt(series(acsc(x), x, 2, 3)), "pi/6 - sqrt(3)*(x - 2)/6 + 7*sqrt(3)*(x - 2)^2/72 + O((x - 2)^3, (x, 2))")
  expect_equal(mi_fmt(series(acoth(x), x, 0, 4)), "-I*pi/2 + x + x^3/3 + O(x^4)")
  expect_equal(mi_fmt(series(asech(x), x, 1, 2)), "sqrt(2)*I*sqrt(x - 1) - 5*sqrt(2)*I*(x - 1)^(3/2)/12 + O((x - 1)^2, (x, 1))")
  expect_equal(mi_fmt(series(acsch(x), x, 0, 3)), "log(2) - log(x) + x^2/4 + O(x^3)")
  expect_equal(mi_fmt(residue(1/sin(x), x, 0)), "1")
  expect_equal(mi_fmt(residue(1/(x^2+1), x, sym_I)), "-I/2")
  expect_equal(mi_fmt(integrate(x + O(x^2), x)), "x^2/2 + O(x^3)")
})
