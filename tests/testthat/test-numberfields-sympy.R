# Expected values are SymPy's outputs for the same calls (Integral bases, prime decomposition and valuations).

skip_unless_full_tests()

skip_on_cran()

x <- Symbol("x")
nf_fmt <- function(v) if (is.character(v)) v else format(v)
pvals <- function(p, f) {
  P <- prime_decomp(p, f)
  v <- vapply(unclass(P), function(Pi) symcompR:::.nf_prime_valuation(symcompR:::.nf_sub_mul(Pi$ZK, p), Pi), 0L)
  paste0("[", paste(v, collapse = ", "), "]")
}

