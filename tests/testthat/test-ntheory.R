test_that("elliptic curves", {
  e3 <- EllipticCurve(-1, 9)
  p <- e3$point(0, 3)
  q <- e3$point(-1, 3)
  r <- p + q
  expect_true(r$x == 1 && r$y == -3)
  r <- 2 * p + q
  expect_true(r$x == 35 && r$y == 207)
  r <- -p + q
  expect_true(r$x == 37 && r$y == 225)
  expect_equal(e3$discriminant, -34928)
  expect_equal(EllipticCurve(-2731, -55146, 1, 0, 1)$discriminant, 25088)
  expect_length(EllipticCurve(0, 1)$torsion_points(), 6L)
  O <- e3$point_at_infinity()
  expect_equal(format(-O), "O")
  cv <- EllipticCurve(0, 0, 0, 1, 1, 0)
  expect_equal(format(cv$point(0, 0, 1) + -cv$point(0, 0, 1)), "O")
  f <- EllipticCurve(1, 0, modulus = 19)
  expect_equal(f$order(), 20)
  expect_equal(point_order(f$point(3, 7)), 20)
  expect_equal(point_order(EllipticCurve(0, 0, a3 = 1)$point(0, 0)), 3)
})

