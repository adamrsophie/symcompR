  expect_equal(s(bernoulli(10)), "5/66")
  expect_equal(s(fibonacci(100)), "354224848179261915075")
  expect_equal(s(partition(100)), "190569292")
  expect_equal(s(diff(erf(x), x)), "2*exp(-x^2)/sqrt(pi)")
})

test_that("sets, inequalities and logic", {
  expect_equal(s(Union(Interval(0, 1), Interval(2, 3), Interval(1, 2))), "Interval(0, 3)")
  expect_equal(s(Intersection(Interval(0, 5), Interval(3, 10))), "Interval(3, 5)")
  expect_true(contains(Interval(0, 1), Rational(1, 2)))
  expect_equal(s(solveset(x^2 - 1, x, Reals)), "{-1, 1}")
  expect_equal(s(solveset(x^2 > 1, x, Reals)), "Union(Interval.open(-oo, -1), Interval.open(1, oo))")
  expect_equal(s(simplify_logic(Or(And(x, y), And(x, Not(y))))), "x")
  expect_identical(satisfiable(And(x, Not(x))), FALSE)
  expect_true(valid(Or(x, Not(x))))
})

test_that("calculus review regressions stay fixed", {
  expect_equal(s(sym_integrate(1 / x^2, list(x, 1, -1))), "-oo")
  expect_equal(s(solve_univariate_inequality(log(x) < 0, x)), "(0 < x) & (x < 1)")
  expect_equal(s(solve_univariate_inequality(sqrt(x) < 2, x)), "(0 <= x) & (x < 4)")
  expect_equal(s(series(sin(x)^20, x, 0, 22)), "x^20 + O(x^22)")
  i <- Symbol("i", integer = TRUE); m <- Symbol("m", integer = TRUE, positive = TRUE)
  expect_equal(s(summation(i^2, list(i, 1, m))), "m^3/3 + m^2/2 + m/6")
  expect_equal(s(summation(1 / (i * (i + 1)), list(i, 1, oo))), "1")
  expect_equal(s(product(i, list(i, 1, m))), "factorial(m)")
})

test_that("second calculus review regressions stay fixed", {
  a <- Symbol("a", positive = TRUE)
  expect_equal(s(sym_integrate(tan(x), list(x, 0, sym_pi))), "nan")
  expect_equal(s(sym_integrate(1 / (sym_I * x - 1), list(x, -1, 1))), "-I*(log(sqrt(2)) + I*pi/4) + I*(log(sqrt(2)) + 3*I*pi/4)")
  expect_equal(s(limit(log(-1 - sym_I * x), x, 0)), "-I*pi")
  expect_equal(s(limit(sqrt(-1 - sym_I * x), x, 0)), "-I")
  expect_equal(s(solve_univariate_inequality(sqrt(x) <= -1, x, relational = FALSE)), "EmptySet")
  expect_equal(s(solve_univariate_inequality(sqrt(x) <= 0, x, relational = FALSE)), "{0}")
  expect_equal(s(solve_univariate_inequality(tan(x) > 0, x, relational = FALSE)), "Interval.open(0, pi/2)")
  expect_equal(s(Union(Interval(0, 1), Interval(0, a))), "Union(Interval(0, 1), Interval(0, a))")
  expect_equal(s(limit(frac(x), x, 1, "-")), "1")
  expect_equal(s(limit(floor(cos(x)), x, 0)), "0")
  expect_equal(s(x * log(x) + O(x)), "x*log(x) + O(x)")
  expect_true(.contains_key(series(x * log(x), x, 0, 1), (x * log(x))$key))
})

test_that("review fixes in calculus, sets and matrices", {
  x <- Symbol("x"); i <- Symbol("i", integer = TRUE); B <- Integer("9007199254740993")
  expect_equal(sstr(product(i, list(i, 1, oo))), "Product(i, (i, 1, oo))")
  expect_equal(sstr(1 + O(1)), "O(1)")
  expect_equal(sstr(diff(Integral(x, list(x, 0, x)), x)), "x")
  expect_equal(sstr(limit(sign(sin(x)), x, 0)), "1")
  expect_equal(sstr(limit(sign(sin(x)), x, 0, "-")), "-1")
  expect_equal(sstr(summation(i, list(i, B, B))), "9007199254740993")
  expect_equal(sstr((Matrix(list(-1)) %^% B)$data[[1]]), "-1")
  expect_equal(as.character(perm_rank(Permutation(18:0))), "121645100408831999")
  U <- Uniform("U", 0, 1)
  expect_equal(sstr(rv_cdf(U, 2)), "1")
  expect_equal(sstr(rv_density(U, 2)), "0")
  expect_equal(sstr(Union(Interval_Lopen(0, 1), Interval(0, 1))), "Interval(0, 1)")
  expect_equal(sstr(LDLdecomposition(Matrix(list(list(2, S_I), list(-S_I, 2))))$D$data[[4]]), "3/2")
  expect_equal(sstr(leadterm(x^20, x)$exponent), "20")
  expect_equal(Array(list(x))$shape, 1L)
  expect_equal(sstr(derive_by_array(x^2, x)), "2*x")
  expect_equal(sstr(distance(Point(2, 0), Segment(Point(0, 0), Point(1, 0)))), "1")
})

test_that("second calculus review fixes", {
  x <- Symbol("x"); i <- Symbol("i", integer = TRUE); n <- Symbol("n", integer = TRUE, positive = TRUE)
  expect_equal(sstr(diff(Derivative(zeta(x), x), x)), "Derivative(zeta(x), (x, 2))")
  expect_equal(sstr(limit(sign(x^2 - x / Integer(10000000)), x, 0)), "-1")
  expect_equal(sstr(doit(subs(product(sqrt(-i), list(i, 1, n)), n, 2))), "-sqrt(2)")
  expect_equal(sstr(sym_integrate(exp(sym_I * x) * sin(x), x)), "I*x/2 - exp(2*I*x)/4")
  G <- PermutationGroup(lapply(0:33, function(k) Permutation(list(3 * k + 0:2), size = 102)))
  expect_equal(as.character(group_order(G)), "16677181699666569")
  expect_length(intersection(Circle(Point(0, 0), 1), Line(Point(0, 2), Point(1, 2))), 0)
  set.seed(1)
  expect_true(abs(rv_sample(Normal("X", 1000, 1), 1) - 1000) < 10)
  expect_equal(sstr(arr_get(Array(1:4), 2)), "2")
  expect_equal(dim(rref(zeros(2, 0))$matrix), c(2L, 0L))
  expect_false(Permutation(c(0, 1)) == Permutation(0))
  expect_length(intersection(Line(Point(0, 0), Point(1, 1)), Line(Point(2, 2), Point(3, 3))), 1)
  expect_equal(sstr(boundary(Integers)), "Integers")
  expect_equal(derive_by_array(Array(list(x, x^2)), x)$shape, 2L)
  expect_equal(dim(QRdecomposition(zeros(2))$Q), c(2L, 0L))
  expect_length(combinations_with_replacement(integer(), 1), 0)
})
