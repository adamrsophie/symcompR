x <- Symbol("x"); y <- Symbol("y"); n <- Symbol("n")
s <- function(e) sstr(e)

test_that("diff matches SymPy", {
  expect_equal(s(diff(sin(x) * exp(x), x)), "exp(x)*sin(x) + exp(x)*cos(x)")
  expect_equal(s(diff(x^3 * y^2, x, 2, y)), "12*x*y")
  f <- Function("f")
  expect_equal(s(diff(f(x)^2, x)), "2*f(x)*Derivative(f(x), x)")
  expect_equal(s(diff(x^x, x)), "x^x*(log(x) + 1)")
  expect_equal(s(diff(atan(x), x)), "1/(x^2 + 1)")
})

test_that("series match SymPy", {
  expect_equal(s(series(sin(x), x, 0, 8)), "x - x^3/6 + x^5/120 - x^7/5040 + O(x^8)")
  expect_equal(s(series(exp(x) / x, x, 0, 3)), "1/x + 1 + x/2 + x^2/6 + O(x^3)")
  expect_equal(s(series(tan(x), x, 0, 8)), "x + x^3/3 + 2*x^5/15 + 17*x^7/315 + O(x^8)")
  expect_equal(s(series(cot(x), x, 0, 4)), "1/x - x/3 - x^3/45 + O(x^4)")
  expect_equal(s(removeO(series(x^x, x, 0, 3))), "x^2*log(x)^2/2 + x*log(x) + 1")
  expect_equal(s(series(gamma(x), x, 0, 2)), "1/x - EulerGamma + x*(EulerGamma^2/2 + pi^2/12) + O(x^2)")
  expect_equal(s(x^2 + O(x^3) + x^5), "x^2 + O(x^3)")
})

test_that("limits match SymPy", {
  expect_equal(s(limit(sin(x) / x, x, 0)), "1")
  expect_equal(s(limit((1 + 1/x)^x, x, oo)), "E")
  expect_equal(s(limit(1 / x, x, 0, "-")), "-oo")
  expect_equal(s(limit(x^2 * exp(-x), x, oo)), "0")
  expect_equal(s(limit(log(x) / x, x, oo)), "0")
  expect_equal(s(limit(x * log(x), x, 0)), "0")
  expect_equal(s(limit((cos(x) - 1) / x^2, x, 0)), "-1/2")
  expect_equal(s(limit(sqrt(x^2 + x) - x, x, oo)), "1/2")
  # SymPy: both one sided limits infinite gives zoo
  expect_equal(s(limit(1 / x, x, 0, "+-")), "zoo")
  expect_error(limit(abs(x) / x, x, 0, "+-"), "does not exist")
})

test_that("integrals match SymPy", {
  expect_equal(s(sym_integrate(x^2 * exp(x), x)), "(x^2 - 2*x + 2)*exp(x)")
  expect_equal(s(sym_integrate(1 / (x^2 + 1), list(x, 0, 1))), "pi/4")
  expect_equal(s(sym_integrate(exp(-x^2), list(x, -oo, oo))), "sqrt(pi)")
  expect_equal(s(sym_integrate(sin(x)^2, x)), "x/2 - sin(x)*cos(x)/2")
  expect_equal(s(sym_integrate(x * log(x), x)), "x^2*log(x)/2 - x^2/4")
  expect_equal(s(sym_integrate(sin(x) / x, list(x, 0, oo))), "pi/2")
  expect_equal(s(sym_integrate(x * exp(-x), list(x, 0, oo))), "1")
  expect_equal(s(sym_integrate(atan(x), x)), "x*atan(x) - log(x^2 + 1)/2")
  expect_equal(s(sym_integrate(exp(2*x) / (1 + exp(x)), x)), "exp(x) - log(exp(x) + 1)")
  expect_equal(s(sym_integrate(x * y, list(x, 0, 1), list(y, 0, 2))), "1")
  expect_equal(s(sym_integrate(exp(x^3), x)), "exp(-I*pi/3)*gamma(1/3)*lowergamma(1/3, x^3*exp_polar(I*pi))/(9*gamma(4/3))")
  expect_equal(sym_integrate(function(t) t^2, 0, 1)$value, 1/3)
  for (f in list(1 / (x^3 - 1), x^3 * cos(x), 1 / (x^2 + 1)^2, sqrt(1 - x^2), exp(x) * sin(x))) {
    F <- sym_integrate(f, x)
    expect_true(is_zero_num(simplify(diff(F, x) - f)) ||
                  abs(as.numeric(N(subs(diff(F, x) - f, x, Rational(3, 10))))) < 1e-10)
  }
})

test_that("simplification functions", {
  expect_equal(s(simplify(sin(x)^2 + cos(x)^2)), "1")
  expect_equal(s(simplify((x^3 + x^2 - x - 1) / (x^2 + 2*x + 1))), "x - 1")
  expect_equal(s(trigsimp(sin(x) / cos(x))), "tan(x)")
  expect_equal(s(radsimp(1 / (1 + sqrt(S(2))))), "-1 + sqrt(2)")
  expect_equal(s(sqrtdenest(sqrt(5 + 2 * sqrt(S(6))))), "sqrt(2) + sqrt(3)")
  expect_equal(s(collect(Symbol("a")*x^2 + Symbol("b")*x^2 + Symbol("a")*x - Symbol("b")*x + 1, x)),
               "x^2*(a + b) + x*(a - b) + 1")
  expect_equal(s(nsimplify(Float(0.333333333333))), "1/3")
  expect_equal(s(nsimplify(Float(6.283185307179586), constants = list(sym_pi))), "2*pi")
  expect_equal(s(rewrite(sym_factorial(n), "gamma")), "gamma(n + 1)")
})

test_that("special functions", {
  expect_equal(s(sym_factorial(S(20))), "2432902008176640000")
  expect_equal(sym_factorial(5), 120)
  expect_equal(s(zeta(S(2))), "pi^2/6")
  expect_equal(s(zeta(S(-1))), "-1/12")
  expect_equal(s(gamma(S(1)/2)), "sqrt(pi)")
