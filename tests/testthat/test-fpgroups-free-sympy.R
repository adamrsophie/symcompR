# Expected values are SymPy's outputs for the same calls (Finitely presented groups (free)).

skip_unless_full_tests()

skip_on_cran()

.bt <- new.env(parent = asNamespace("symcompR"))
eval(parse(text = r"---(NULL
)---"), envir = .bt)
.run <- function(code) {
  e <- .bt
  NULL
  gsub("\n", " ", get("fp_str", envir = .bt)(eval(parse(text = code), envir = e)), fixed = TRUE)
}
.setup <- function(code) invisible(eval(parse(text = code), envir = .bt))
.err <- function(code) tryCatch({ .run(code); "no error" }, error = function(e) gsub("\n", " ", conditionMessage(e), fixed = TRUE))

test_that("Finitely presented groups (free) match SymPy", {
  .setup(".g <- free_group(\"x, y, z\"); F <- .g[[1]]; x <- .g[[2]]; y <- .g[[3]]; z <- .g[[4]]")
  expect_equal(.run("length(FreeGroup(\"x, y, z\")$generators)"), "3")
  expect_equal(.run("length(FreeGroup(Symbol(\"x\"))$generators)"), "1")
  expect_equal(.run("FreeGroup(c(\"x\", \"y\", \"z\"))$rank"), "3")
  expect_equal(.run("length(FreeGroup(list(Symbol(\"x\"), Symbol(\"y\"), Symbol(\"z\")))$generators)"), "3")
  expect_equal(.run(".py_tuple(list(.py_tuple(lapply(FreeGroup(\"x, y, z\")$symbols, Symbol))))"), "((x, y, z),)")
  expect_equal(.run("F$generators"), "(x, y, z)")
  expect_equal(.run("fp_contains(F, x*z^2)"), "True")
  expect_equal(.run("fp_contains(F, x)"), "True")
  expect_equal(.run("fp_contains(F, y*z^-1)"), "True")
  expect_equal(.run("fp_contains(F, (y*z)^0)"), "True")
  expect_equal(.run("fp_contains(F, free_group(\"a, b, c\")[[2]])"), "False")
  expect_equal(.run("fp_contains(F, free_group(\"a, b, c\")[[2]]^0)"), "False")
  expect_equal(.run("F$rank"), "3")
  expect_equal(.run("fp_str(F)"), "<free group on the generators (x, y, z)>")
  expect_equal(.run("identical(F, free_group(\"a, b, c\")[[1]])"), "False")
  expect_equal(.run("fp_order(F)"), "oo")
  expect_equal(.run("fp_is_abelian(F)"), "False")
  expect_equal(.run("fp_center(F)"), "{<identity>}")
  expect_equal(.run("fp_order(free_group(\"\")[[1]])"), "1")
  expect_equal(.run("free_group(\"\")[[1]]$generators"), "()")
  expect_equal(.run("fp_elements(free_group(\"\")[[1]])"), "{<identity>}")
  expect_equal(.run("fp_is_abelian(free_group(\"\")[[1]])"), "True")
  expect_equal(.err("fp_elements(F)"), "Group contains infinitely many elements, hence cannot be represented")
  expect_equal(.run("identical(free_group(\"x, y, z\")[[1]], free_group(\"x, y, z\")[[1]])"), "True")
  expect_equal(.run("identical(free_group(\"x, y, z\")[[1]], free_group(\"a, x, y\")[[1]])"), "False")
  expect_equal(.run("identical(free_group(\"x, y\")[[1]], free_group(\"x, y, z\")[[1]])"), "False")
  expect_equal(.run("fg_slice(F, 0)"), "<free group on the generators (x, y, z)>")
  expect_equal(.run("fg_slice(F, 1)"), "<free group on the generators (y, z)>")
  expect_equal(.run("fg_slice(F, 2)"), "<free group on the generators (z,)>")
  expect_equal(.run("identical(fg_slice(F, 1), FreeGroup(\"y, z\"))"), "True")
  expect_equal(.run("fg_index(F, y)"), "1")
  expect_equal(.err("fg_index(F, y^2)"), "tuple.index(x): x not in tuple")
  expect_equal(.err("fg_index(F, free_group(\"a\")[[2]])"), "expected a generator of Free Group <free group on the generators (x, y, z)>, got a")
  expect_equal(.run("x*y*z"), "x*y*z")
  expect_equal(.run("x*y == y*x"), "False")
  expect_equal(.run("x^2*y == x*x*y"), "True")
  expect_equal(.run("(x*y*z^3) == x*y*z^3"), "True")
  expect_equal(.run("x*y*z^3 != x*y*z^7"), "True")
  expect_equal(.run("word_inverse(x)"), "x^-1")
  expect_equal(.run("word_inverse(x*y)"), "y^-1*x^-1")
  expect_equal(.run("word_inverse(y*x*y^-1)"), "y*x^-1*y^-1")
  expect_equal(.run("word_inverse(y^2*x^-1)"), "x*y^-2")
  expect_equal(.err("2/x"), "only FreeGroup elements of same FreeGroup can be multiplied")
  expect_equal(.err("x^2 + y^2"), "unsupported operand type(s) for +: 'FreeGroupElement' and 'FreeGroupElement'")
  expect_equal(.err("x/2"), "only FreeGroup elements of same FreeGroup can be multiplied")
  expect_equal(.run("word_order(x^0)"), "1")
  expect_equal(.run("word_order(y^2)"), "oo")
  expect_equal(.run("word_commutator(x^-1*y, x)"), "y^-1*x^-1*y*x")
  expect_equal(.run("word_commutator(x, x)"), "<identity>")
  expect_equal(.run("word_len(x^2*y^-1)"), "3")
  expect_equal(.run("word_len(x^-1*y^3*z)"), "5")
  expect_equal(.run("eliminate_word(x^5*y*x^2*y^-4*x, x, x^2)"), "x^10*y*x^4*y^-4*x^2")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, x, x^2)"), "x^4*y^3*x^-2*y")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, x, y)"), "y^5")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, x, y^4)"), "y^8")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, y, x^-1)"), "x^-3")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, x, y*z)"), "y*z*y*z*y^3*z^-1")
  expect_equal(.run("eliminate_word(y^-3, y, x^-1*z^-1)"), "z*x*z*x*z*x")
  expect_equal(.err("eliminate_word(x^5*y*x^2*y^-4*x, F$identity, x)"), "gen must be a non-empty word")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, y*x, x)"), "x^2*y^3*x^-1*y")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, y^2, z, all = TRUE)"), "x^2*z*y*x^-1*y")
  expect_equal(.run("eliminate_word(x^2*y^3*x^-1*y, y, z, all = TRUE, inverse = FALSE)"), "x^2*z^3*x^-1*z")
  expect_equal(.run("eliminate_word(x^2*y^-3*x^-1*y, y, z, inverse = FALSE)"), "x^2*y^-3*x^-1*z")
  expect_equal(.run("eliminate_words(x^2*y^-3*x^-1*y, list(y, x^2))"), "x^-1")
  expect_equal(.run("eliminate_words(x^2*y^-3*x^-1*y, word_dict(list(y, x^2), list(z, y)))"), "z^-2*x^-1*z")
  expect_equal(.run("word_array_form(x*z)"), "((x, 1), (z, 1))")
  expect_equal(.run("word_array_form(x^2*z*y*x^-2)"), "((x, 2), (z, 1), (y, 1), (x, -2))")
  expect_equal(.run("word_array_form(x^-2*y^-1)"), "((x, -2), (y, -1))")
  expect_equal(.run("word_letter_form(x^3)"), "(x, x, x)")
  expect_equal(.run("word_letter_form(x^2*z^-2*x)"), "(x, x, -z, -z, x)")
  expect_equal(.run("word_ext_rep(x^2*z^-2*x)"), "(x, 2, z, -2, x, 1)")
  expect_equal(.run("word_ext_rep(x^-2*y^-1)"), "(x, -2, y, -1)")
  expect_equal(.run("word_ext_rep(x*z)"), "(x, 1, z, 1)")
  expect_equal(.run("word_letter_form_elm(x^2*z^-1)"), "[x, x, z^-1]")
  expect_equal(.run("x^2 == x*x"), "True")
  expect_equal(.run("(x^2*y*x^-2)^4"), "x^2*y^4*x^-2")
  expect_equal(.run("(x^2*y*x^-2)^-3"), "x^2*y^-3*x^-2")
  expect_equal(.run("(x*y*x)^3"), "x*y*x^2*y*x^2*y*x")
  expect_equal(.run("(x*y*x)^-2"), "x^-1*y^-1*x^-2*y^-1*x^-1")
  expect_equal(.run("(x^2)^2"), "x^4")
  expect_equal(.run("(x^-1)^-1"), "x")
  expect_equal(.run("(x^-1)^0"), "<identity>")
  expect_equal(.run("(y^2)^-2"), "y^-4")
  expect_equal(.run("(x*y*x^-1)^5"), "x*y^5*x^-1")
  expect_equal(.run("(x^2*y*z*x^-1)^3"), "x^2*y*z*x*y*z*x*y*z*x^-1")
  expect_equal(.run("(x*y*z*x)^3"), "x*y*z*x^2*y*z*x^2*y*z*x")
  expect_equal(.run("(x*y*z*x^-2)^-2"), "x^2*z^-1*y^-1*x*z^-1*y^-1*x^-1")
  expect_equal(.run("x^2*x^-1"), "x")
  expect_equal(.run("x^2*y^2*y^-1"), "x^2*y")
  expect_equal(.run("x*x^-1"), "<identity>")
  expect_equal(.run("x/x"), "<identity>")
  expect_equal(.run("x/x^2"), "x^-1")
  expect_equal(.run("(x^2*y)/(x^2*y^-1)"), "x^2*y^2*x^-2")
  expect_equal(.run("(x^2*y)/(y^-1*x^2)"), "x^2*y*x^-2*y")
  expect_equal(.run("x*(x^-1*y*z*y^-1)"), "y*z*y^-1")
  expect_equal(.run("x^2*(x^-2*y^-1*z^2*y)"), "y^-1*z^2*y")
  expect_equal(.err("x^2.5"), "2.5 is not an integer")
  expect_equal(.run("word_prod(F, list())"), "<identity>")
  expect_equal(.run("word_prod(F, list(F$identity, x, y, x^-1, F$identity))"), "x*y*x^-1")
  expect_equal(.run("word_prod(F, lapply(c(3, -1, 5, -2), function(k) x^k))"), "x^5")
  expect_equal(.run("word_prod(F, list(x^2*y*x^-2, x^2, y^-3, x^-2, y^3))"), "x^2*y^-2*x^-2*y^3")
  expect_equal(.run("word_prod(F, list(x*y, y^-1*x^-1, z))"), "z")
  expect_equal(.err("word_prod(F, list(x, 1))"), "only FreeGroup elements of same FreeGroup can be multiplied")
  expect_equal(.run("word_len(x^5*y*x^2*y^-4*x)"), "13")
  expect_equal(.run("word_len(x^17)"), "17")
  expect_equal(.run("word_len(y^0)"), "0")
  expect_equal(.run("x^0 == y^0"), "True")
  expect_equal(.run("x^2 < y^3"), "True")
  expect_equal(.run("x^3 < y^2"), "False")
  expect_equal(.run("x*y < x^2*y"), "True")
  expect_equal(.run("x^2*y^2 < y^4"), "True")
  expect_equal(.run("y^4 < y^-4"), "False")
  expect_equal(.run("y^4 < x^-4"), "False")
  expect_equal(.run("y^-2 < y^2"), "True")
  expect_equal(.run("x^2 <= y^2"), "True")
  expect_equal(.run("x^2 <= x^2"), "True")
  expect_equal(.run("y*z > z*y"), "False")
  expect_equal(.run("x > x^-1"), "True")
  expect_equal(.run("x^2 >= y^2"), "False")
  expect_equal(.run("x^-1*y < x*y^-1"), "True")
  expect_equal(.err("x < free_group(\"a\")[[2]]"), "only FreeGroup elements of same FreeGroup can be compared")
  expect_equal(.run("number_syllables(x^5*y*x^2*y^-4*x)"), "5")
  expect_equal(.run("exponent_syllable(x^5*y*x^2*y^-4*x, 2)"), "2")
  expect_equal(.run("generator_syllable(x^5*y*x^2*y^-4*x, 3)"), "y")
  expect_equal(.run("sub_syllables(x^5*y*x^2*y^-4*x, 1, 2)"), "y")
  expect_equal(.run("sub_syllables(x^5*y*x^2*y^-4*x, 3, 3)"), "<identity>")
  expect_equal(.run("sub_syllables(x^5*y*x^2*y^-4*x, 1, 4)"), "y*x^2*y^-4")
  expect_equal(.run("exponent_syllable(x^5*y*x^2*y^-4*x, -1)"), "1")
  expect_equal(.run("exponent_sum(x^2*y^3, x)"), "2")
  expect_equal(.run("exponent_sum(x^2*y^3, x^-1)"), "-2")
  expect_equal(.run("generator_count(x^2*y^3, x)"), "2")
  expect_equal(.run("exponent_sum(x^2*y^4*x^-3, x)"), "-1")
  expect_equal(.run("generator_count(x^2*y^4*x^-3, x)"), "5")
  expect_equal(.err("generator_count(x^2*y^4*x^-3, x^-1)"), "gen must be a generator")
  expect_equal(.err("exponent_sum(x^2*y^4*x^-3, x^2)"), "gen must be a generator or inverse of a generator")
  expect_equal(.run(".fw_sort(contains_generators(x^2*y^4*z^-1))"), "[x, y, z]")
  expect_equal(.run(".fw_sort(contains_generators(x^-1*y^3))"), "[x, y]")
  expect_equal(.run("subword(x^5*y*x^2*y^-4*x, 2, 6)"), "x^3*y")
  expect_equal(.run("subword(x^5*y*x^2*y^-4*x, 3, 2)"), "<identity>")
  expect_equal(.run("subword(x^5*y*x^2*y^-4*x, 6, 10)"), "x^2*y^-2")
  expect_equal(.err("subword(x^5*y*x^2*y^-4*x, 6, 20)"), "`from_i`, `to_j` must be positive and no greater than the length of associative word")
  expect_equal(.run("subword(x^5*y*x^2*y^-4*x, -2, 20, strict = FALSE)"), "x^5*y*x^2*y^-4*x")
  expect_equal(.run("substituted_word(x^5*y*x^2*y^-4*x, 0, 7, y^-1)"), "y^-1*x*y^-4*x")
  expect_equal(.run("substituted_word(x^5*y*x^2*y^-4*x, 0, 7, y^2*x)"), "y^2*x^2*y^-4*x")
  expect_equal(.run("substituted_word(x^5*y*x^2*y^-4*x, 3, 9, z)"), "x^3*z*y^-3*x")
  expect_equal(.run("substituted_word(x^5*y*x^2*y^-4*x, 9, 13, z)"), "x^5*y*x^2*y^-1*z")
  expect_equal(.err("substituted_word(x^5*y*x^2*y^-4*x, 9, 3, z)"), "values should be within bounds")
  expect_equal(.run("subword_index(x^2*y^-4*x, y^-2)"), "2")
  expect_equal(.run("subword_index(x^2*y^-4*x, y^-2, 4)"), "4")
  expect_equal(.err("subword_index(x^2*y^-4*x, y^2)"), "The given word is not a subword of self")
  expect_equal(.run("is_dependent(x^2*y^-4*x, y^2)"), "True")
  expect_equal(.run("is_independent(x^2*y^-4*x, z)"), "True")
  expect_equal(.run("cyclic_subword(x*y*x^-1, 1, 4)"), "y")
  expect_equal(.run("cyclic_subword(x*y*z, 2, 7)"), "z*x*y*z*x")
  expect_equal(.run("cyclic_subword(x*y*z, 4, 6)"), "y*z")
  expect_equal(.run("cyclic_subword(x*y*z^2, 5, 11)"), "y*z^2*x*y*z")
  expect_equal(.run("cyclic_subword(F$identity, 3, 7)"), "<identity>")
  expect_equal(.run(".fw_sort(cyclic_conjugates(F$identity))"), "[<identity>]")
  expect_equal(.run("is_cyclic_conjugate(x, F$identity)"), "False")
  expect_equal(.run("is_cyclic_conjugate(F$identity, x*x^-1)"), "True")
  expect_equal(.run(".fw_sort(cyclic_conjugates(x*y*x*y*x))"), "[x^2*y*x*y, x*y*x^2*y, x*y*x*y*x, y*x^2*y*x, y*x*y*x^2]")
  expect_equal(.run(".fw_sort(cyclic_conjugates(x*y^-1*z*x^-1))"), "[y^-1*z, z*y^-1, x*y^-1*z*x^-1]")
  expect_equal(.run("is_cyclic_conjugate(x*y*z, z*x*y)"), "True")
  expect_equal(.run("is_cyclic_conjugate(x*y*z, z*y*x)"), "False")
  expect_equal(.run("is_cyclic_conjugate(x*y*x^-1, y)"), "False")
  expect_equal(.run("is_cyclic_conjugate(x^2*y^-1, y^-1*x^2)"), "True")
  expect_equal(.run("is_cyclically_reduced(x*y*x^-1)"), "False")
  expect_equal(.run("is_cyclically_reduced(x*y*x)"), "True")
  expect_equal(.run("is_cyclically_reduced(F$identity)"), "True")
  expect_equal(.run("identity_cyclic_reduction(x^2*y*x^-1)"), "x*y")
  expect_equal(.run("identity_cyclic_reduction(x*y^2*x^-3)"), "x^-2*y^2")
  expect_equal(.run("identity_cyclic_reduction(x^-3*y*z^2*x^3)"), "y*z^2")
  expect_equal(.run("cyclic_reduction(x^2*y*x^-1)"), "x*y")
  expect_equal(.run("cyclic_reduction(x^2*y*x^-1, removed = TRUE)"), "(x*y, x)")
  expect_equal(.run("cyclic_reduction(x*y^2*x^-3, removed = TRUE)"), "(y^2*x^-2, x)")
  expect_equal(.run("cyclic_reduction(x^-3*y*z^2*x^3, removed = TRUE)"), "(y*z^2, x^-3)")
  expect_equal(.run("power_of((x*y)^2, x*y)"), "True")
  expect_equal(.run("power_of(x^-3*y^-2*x^3, x^-3*y*x^3)"), "True")
  expect_equal(.run("power_of(x*y*x, x*y)"), "False")
  expect_equal(.run("power_of(x^4, x^-1)"), "True")
  expect_equal(.run("power_of(x^4*y, x)"), "False")
  expect_equal(.run("power_of((x*y^-1)^-3, x*y^-1)"), "True")
  expect_equal(.run("word_index(x^2*y*x, y)"), "2")
  expect_equal(.err("word_index(x^2*y*x, z)"), "tuple.index(x): x not in tuple")
  try(.run("word_index(x^2*y*x, x^2)"), silent = TRUE)
  expect_equal(.run("word_contains(x^2*y*x, y)"), "True")
  expect_equal(.run("word_contains(x^2*y*x, z)"), "False")
  expect_equal(.run("is_identity_word(x^2*y*x)"), "False")
  expect_equal(.run("is_identity_word(F$identity)"), "True")
  expect_equal(.run("fp_str(F$identity)"), "<identity>")
  expect_equal(.run("free_group(\"x:3\")[[1]]"), "<free group on the generators (x0, x1, x2)>")
  expect_equal(.run("free_group(\"a_0, a_1\")[[3]]^-2"), "a_1^-2")
  expect_equal(.run("free_group(c(\"p\", \"q\"))[[2]]*free_group(c(\"p\", \"q\"))[[3]]"), "p*q")
  expect_equal(.run("fp_str(FreeGroup(paste0(\"g\", 0:30)))"), "<free group with 31 generators>")
  expect_equal(.err("FreeGroup(5)"), "The type of `symbols` must be one of the following: a str, Symbol/Expr or a sequence of one of these types")
})
