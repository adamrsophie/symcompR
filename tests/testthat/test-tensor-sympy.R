  .setup("A <- TensorHead('A', list(Lorentz), TensorSymmetry.no_symmetry(1))")
  expect_equal(.run("canon_bp(A(c)*A(b)*A(a))"), "A(a)*A(b)*A(c)")
  .setup("A <- TensorHead('A', list(Lorentz), TensorSymmetry.no_symmetry(1), 1)")
