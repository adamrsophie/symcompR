test_that("Tensors and partial derivatives match SymPy", {
  .setup("Lorentz <- TensorIndexType('Lorentz', dummy_name='L')")
  .setup("U(tensor_indices('a,b,d0,d1', Lorentz))")
  .setup("U(tensor_heads('A,B', list(Lorentz), TensorSymmetry.no_symmetry(1)))")
  expect_equal(.run("A(-d0)*B(d0)"), "A(-L_0)*B(L_0)")
  expect_equal(.run("canon_bp(A(-d0)*B(d0))"), "A(L_0)*B(-L_0)")
  expect_equal(.run("canon_bp(A(a)*B(b))"), "A(a)*B(b)")
  expect_equal(.run("canon_bp(B(b)*A(a))"), "A(a)*B(b)")
  .setup("A <- TensorHead('A', rep(list(Lorentz), 2), TensorSymmetry.fully_symmetric(2))")
  expect_equal(.run("canon_bp(A(b, -d0)*A(d0, a))"), "A(a, L_0)*A(b, -L_0)")
  .setup("U(tensor_heads('B,C', list(Lorentz), TensorSymmetry.no_symmetry(1)))")
  expect_equal(.run("canon_bp(A(d1, -d0)*B(d0)*C(-d1))"), "A(L_0, L_1)*B(-L_0)*C(-L_1)")
  .setup("A <- TensorHead('A', rep(list(Lorentz), 2), TensorSymmetry.no_symmetry(2))")
  expect_equal(.run("canon_bp(A(d1, -d0)*B(d0)*C(-d1))"), "A(L_0, L_1)*B(-L_1)*C(-L_0)")
  .setup("B <- TensorHead('B', rep(list(Lorentz), 2), TensorSymmetry.no_symmetry(2))")
  expect_equal(.run("canon_bp(A(d1, -d0)*B(-d1, d0))"), "A(L_0, L_1)*B(-L_0, -L_1)")
  expect_equal(.run("canon_bp(A(-d0, d1)*B(-d1, d0))"), "A(L_0, L_1)*B(-L_1, -L_0)")
  .setup("C <- TensorHead('C', rep(list(Lorentz), 2), TensorSymmetry.no_symmetry(2))")
  expect_equal(.run("canon_bp(A(d1, d0)*B(-a, -d0)*C(-d1, -b))"), "A(L_0, L_1)*B(-a, -L_1)*C(-L_0, -b)")
  .setup("A <- TensorHead('A', rep(list(Lorentz), 2), TensorSymmetry.fully_symmetric(2))")
