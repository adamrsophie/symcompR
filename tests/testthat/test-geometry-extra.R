# Reference values from SymPy.
x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); t <- Symbol("t")
F <- function(v) if (inherits(v, "GeoEntity")) format(v) else if (is_sym(v)) sstr(v) else
  paste0("[", paste(vapply(v, F, ""), collapse = ", "), "]")
Pt <- Point3D(1, 2, 3); Q <- Point3D(4, 6, 8); L <- Line3D(Pt, Q)

test_that("3D points, lines and rays", {
  expect_equal(format(Point(1, 2)), "Point2D(1, 2)")
  expect_equal(F(L), "Line3D(Point3D(1, 2, 3), Point3D(4, 6, 8))")
  expect_equal(F(direction_ratio(L)), "[3, 4, 5]")
  expect_equal(F(direction_cosine(L)), "[3*sqrt(2)/10, 2*sqrt(2)/5, sqrt(2)/2]")
  expect_equal(F(geo_length(Segment3D(Pt, Q))), "5*sqrt(2)")
  expect_equal(F(midpoint(Segment3D(Pt, Q))), "Point3D(5/2, 4, 11/2)")
  expect_equal(F(Ray(Point(0, 0), Point(1, 1))), "Ray2D(Point2D(0, 0), Point2D(1, 1))")
  expect_true(contains(Ray(Point(0, 0), Point(1, 1)), Point(2, 2)))
  expect_false(contains(Ray(Point(0, 0), Point(1, 1)), Point(-1, -1)))
  expect_equal(F(distance(L, Point3D(0, 0, 0))), "2*sqrt(3)/5")
  expect_true(contains(L, Point3D(7, 10, 13)))
  expect_equal(F(intersection(Line3D(Point3D(0, 0, 0), Point3D(1, 0, 0)), Line3D(Point3D(1, 1, 0), Point3D(1, -1, 0)))), "[Point3D(1, 0, 0)]")
  expect_equal(F(arbitrary_point(L, t)), "Point3D(3*t + 1, 4*t + 2, 5*t + 3)")
  expect_true(is_parallel(Line3D(Point3D(0, 0, 0), Point3D(1, 1, 1)), Line3D(Point3D(1, 0, 0), Point3D(2, 1, 1))))
})

test_that("planes", {
  pl <- Plane(Point3D(0, 0, 0), normal_vector = c(1, 1, 1))
  expect_equal(F(pl), "Plane(Point3D(0, 0, 0), (1, 1, 1))")
  expect_equal(F(equation(pl, x, y, z)), "x + y + z")
  expect_equal(F(distance(pl, Point3D(1, 1, 1))), "sqrt(3)")
  expect_equal(F(intersection(pl, Line3D(Point3D(0, 0, 5), Point3D(1, 1, 5)))), "[Point3D(-5/2, -5/2, 5)]")
  expect_equal(F(projection(pl, Point3D(1, 1, 1))), "Point3D(0, 0, 0)")
  expect_equal(F(Plane(Point3D(1, 0, 0), Point3D(0, 1, 0), Point3D(0, 0, 1))), "Plane(Point3D(1, 0, 0), (1, 1, 1))")
  expect_equal(F(angle_between(pl, Plane(Point3D(0, 0, 0), normal_vector = c(0, 0, 1)))), "acos(sqrt(3)/3)")
  expect_true(is_parallel(pl, Plane(Point3D(1, 1, 1), normal_vector = c(2, 2, 2))))
})

test_that("ellipses, parabolas, curves and similarity", {
  E <- Ellipse(Point(0, 0), 3, 2)
  expect_equal(F(area(E)), "6*pi")
  expect_equal(F(circumference(E)), "12*elliptic_e(5/9)")
  expect_equal(F(eccentricity(E)), "sqrt(5)/3")
  expect_equal(F(foci(E)), "[Point2D(-sqrt(5), 0), Point2D(sqrt(5), 0)]")
  expect_equal(F(equation(E, x, y)), "x^2/9 + y^2/4 - 1")
  expect_equal(F(intersection(E, Line(Point(0, 0), Point(1, 0)))), "[Point2D(-3, 0), Point2D(3, 0)]")
  expect_equal(F(minor(E)), "2")
  expect_true(encloses_point(E, Point(1, 1)))
  Pa <- Parabola(Point(0, 4), Line(Point(-1, 0), Point(1, 0)))
  expect_equal(F(vertex(Pa)), "Point2D(0, 2)")
  expect_equal(F(axis_of_symmetry(Pa)), "Line2D(Point2D(0, 4), Point2D(0, 5))")
  expect_equal(F(equation(Pa, x, y)), "-x^2 + 8*y - 16")
  C <- Curve(list(t, t^2), list(t, 0, 1))
  expect_equal(F(translate(C, 1, 2)), "Curve((t + 1, t^2 + 2), (t, 0, 1))")
  expect_equal(F(geo_length(C)), "asinh(2)/4 + sqrt(5)/2")
  expect_true(are_similar(Triangle(Point(0, 0), Point(1, 0), Point(0, 1)), Triangle(Point(0, 0), Point(2, 0), Point(0, 2))))
  expect_true(are_similar(Line(Point(0, 0), Point(1, 1)), Line(Point(1, 1), Point(2, 2))))
  expect_equal(F(sym_integrate(sqrt(1 - x^2), x)), "x*sqrt(1 - x^2)/2 + asin(x)/2")
})

test_that("p14 review fixes: distances, collinear intersections, plane angles, translate, circle foci", {
  P3 <- Point3D
  expect_equal(sstr(distance(P3(1, 0, 1), Segment3D(P3(0, 0, 0), P3(2, 0, 0)))), "1")
  expect_equal(sstr(distance(Point(-1, 0), Ray2D(Point(0, 0), Point(1, 0)))), "1")
  expect_equal(sstr(distance(Point(-1, 1), Ray2D(Point(0, 0), Point(1, 0)))), "sqrt(2)")
  expect_equal(sstr(distance(Point(2, 1), Ray2D(Point(0, 0), Point(1, 0)))), "1")
  expect_equal(sstr(distance(P3(-1, 0, 1), Ray3D(P3(0, 0, 0), P3(1, 0, 0)))), "sqrt(2)")
  fmt <- function(l) vapply(l, format, "")
  expect_length(intersection(Segment3D(P3(0, 0, 0), P3(1, 0, 0)), Segment3D(P3(2, 0, 0), P3(3, 0, 0))), 0L)
  expect_equal(fmt(intersection(Segment(Point(0, 0), Point(2, 0)), Segment(Point(1, 0), Point(3, 0)))), "Segment2D(Point2D(1, 0), Point2D(2, 0))")
  expect_length(intersection(Ray2D(Point(0, 0), Point(1, 0)), Ray2D(Point(-1, 0), Point(-2, 0))), 0L)
  expect_equal(fmt(intersection(Ray2D(Point(0, 0), Point(1, 0)), Ray2D(Point(1, 0), Point(2, 0)))), "Ray2D(Point2D(1, 0), Point2D(2, 0))")
  expect_equal(fmt(intersection(Ray2D(Point(0, 0), Point(1, 0)), Ray2D(Point(3, 0), Point(2, 0)))), "Segment2D(Point2D(0, 0), Point2D(3, 0))")
  expect_equal(fmt(intersection(Ray2D(Point(0, 0), Point(1, 0)), Segment(Point(-1, 0), Point(2, 0)))), "Segment2D(Point2D(0, 0), Point2D(2, 0))")
  expect_equal(fmt(intersection(Line(Point(0, 0), Point(1, 0)), Segment(Point(-1, 0), Point(2, 0)))), "Segment2D(Point2D(-1, 0), Point2D(2, 0))")
  pP <- Plane(P3(0, 0, 0), normal_vector = c(0, 0, 1))
  expect_equal(sstr(distance(pP, Plane(P3(0, 0, 3), normal_vector = c(0, 0, 1)))), "3")
  expect_equal(sstr(distance(pP, Plane(P3(0, 0, 3), normal_vector = c(0, 1, 1)))), "0")
  expect_equal(sstr(distance(pP, Line3D(P3(0, 0, 2), P3(1, 0, 2)))), "2")
  expect_equal(sstr(distance(pP, Segment3D(P3(0, 0, 2), P3(1, 0, 5)))), "2")
  expect_equal(sstr(distance(pP, Ray3D(P3(0, 0, 2), P3(1, 0, 5)))), "2")
  expect_equal(sstr(distance(pP, Ray3D(P3(0, 0, 2), P3(1, 0, 1)))), "0")
  expect_equal(sstr(angle_between(pP, Line3D(P3(0, 0, 0), P3(1, 0, 0)))), "0")
  expect_equal(sstr(angle_between(pP, Line3D(P3(0, 0, 0), P3(1, 0, 1)))), "pi/4")
  expect_false(contains(pP, P3(0, 0, Float(1e-13))))
  expect_equal(format(translate(P3(1, 2, 3), 10, 20)), "Point3D(11, 22, 3)")
  expect_equal(format(translate(P3(1, 2, 3), 10, 20, 30)), "Point3D(11, 22, 33)")
  expect_equal(fmt(foci(Ellipse(Point(0, 0), 2, 2))), c("Point2D(0, 0)", "Point2D(0, 0)"))
})

test_that("p15 review fixes: touching segments, 3D line distance", {
  fmt <- function(l) vapply(l, format, "")
  expect_equal(fmt(intersection(Segment(Point(0, 0), Point(1, 0)), Segment(Point(1, 0), Point(2, 0)))), "Point2D(1, 0)")
  expect_equal(fmt(intersection(Ray2D(Point(0, 0), Point(1, 0)), Segment(Point(-1, 0), Point(0, 0)))), "Point2D(0, 0)")
  expect_equal(sstr(distance(Line3D(Point(0, 0, 0), Point(0, 0, 1)), Line3D(Point(0, 1, 0), Point(1, 1, 1)))), "1")
  expect_equal(sstr(distance(Line3D(Point(0, 0, 0), Point(0, 0, 1)), Line3D(Point(1, 0, 0), Point(1, 0, 1)))), "1")
})
