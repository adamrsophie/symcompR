x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z")
s <- function(e) sstr(e)

test_that("geometry", {
  A <- Point(0, 0); B <- Point(3, 4)
  expect_equal(s(distance(A, B)), "5")
  T1 <- Triangle(Point(0, 0), Point(4, 0), Point(0, 3))
  expect_equal(s(area(T1)), "6")
  expect_equal(s(perimeter(T1)), "12")
  expect_equal(format(centroid(T1)), "Point2D(4/3, 1)")
  p <- intersection(Line(Point(0, 0), Point(1, 1)), Line(Point(0, 2), Point(2, 0)))
  expect_equal(format(p[[1]]), "Point2D(1, 1)")
  expect_length(intersection(Circle(Point(0, 0), 5), Line(Point(0, 0), Point(1, 0))), 2L)
  expect_length(intersection(Segment(Point(0, 0), Point(1, 1)), Segment(Point(2, 0), Point(3, 1))), 0L)
  expect_true(is_perpendicular(Line(A, Point(1, 0)), Line(A, Point(0, 1))))
  expect_true(is_collinear(Point(0, 0), Point(1, 1), Point(2, 2)))
})

test_that("vector calculus", {
  expect_equal(vapply(curl(list(-y, x, 0))$data, s, ""), c("0", "0", "2"))
  expect_equal(s(divergence(list(x, y, z))), "3")
  expect_equal(s(laplacian(x^2 + y^2 + z^2)), "6")
  expect_true(is_conservative(list(y * z, x * z, x * y)))
  expect_equal(s(scalar_potential(list(y * z, x * z, x * y))), "x*y*z")
})

test_that("quaternions, arrays, transforms, units", {
  expect_true(Quaternion(1, 2, 3, 4) * Quaternion(5, 6, 7, 8) == Quaternion(-60, 12, 30, 24))
  expect_equal(s(quat_norm(Quaternion(1, 2, 3, 4))), "sqrt(30)")
  expect_equal(s(tensorcontraction(Array(list(1, 2, 3, 4), c(2, 2)), c(1, 2))), "5")
  expect_equal(vapply(derive_by_array(x^2 * y, list(x, y))$data, s, ""), c("2*x*y", "x^2"))
  expect_equal(vapply(convolution(1:3, 4:5), s, ""), c("4", "13", "22", "15"))
  expect_equal(vapply(sym_fft(list(1, 2, 3, 4)), s, ""), c("10", "-2 - 2*I", "-2", "-2 + 2*I"))
  expect_equal(vapply(sym_ifft(sym_fft(list(1, 2, 3, 4))), s, ""), c("1", "2", "3", "4"))
  expect_equal(vapply(mobius_transform(list(1, 2, 3, 4)), s, ""), c("1", "3", "4", "10"))
  expect_equal(vapply(walsh_hadamard_transform(list(1, 2, 3, 4)), s, ""), c("10", "-2", "-4", "0"))
  u <- physics_units()
  expect_equal(s(convert_to(5 * u$kilometer, u$meter)), "5000*meter")
  expect_equal(s(convert_to(u$kilometer / u$hour, list(u$meter, u$second))), "5*meter/(18*second)")
})

test_that("stats matches SymPy", {
  mu <- Symbol("mu", real = TRUE); sg <- Symbol("s", positive = TRUE); l <- Symbol("l", positive = TRUE)
  X <- Normal("X", mu, sg); Z <- Normal("Z", 0, 1); Y <- Exponential("Y", l)
  expect_equal(s(E(X^2)), "mu^2 + s^2")
  expect_equal(s(variance(2 * X + 1)), "4*s^2")
  expect_equal(s(variance(Y)), "l^(-2)")
  expect_equal(s(P(Z > 0)), "1/2")
  expect_equal(s(P(Y > 1)), "exp(-l)")
  expect_equal(s(E(exp(-Y))), "l/(l + 1)")
  D <- Die("D", 6)
  expect_equal(s(E(D)), "7/2")
  expect_equal(s(variance(D)), "35/12")
  expect_equal(s(P(D > 4)), "1/3")
  Po <- Poisson("Po", l)
  expect_equal(s(E(Po)), "l")
  expect_equal(s(variance(Po)), "l")
  expect_equal(s(skewness(Y)), "2")
  expect_equal(s(kurtosis(Z)), "3")
})
