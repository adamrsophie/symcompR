# Expected strings are SymPy outputs for the same calls.

x <- Symbol("x"); s2 <- sqrt(Integer(2)); s3 <- sqrt(Integer(3)); I <- sym_I
cl <- function(v) if (is.null(v)) "None" else paste0("[", paste(vapply(v, sstr, ""), collapse = ", "), "]")
iv <- function(v) paste0("(", sstr(v[[1L]]), ", ", sstr(v[[2L]]), ")")
ivs <- function(l) paste0("[", paste(vapply(l, function(r) if (is_sym(r[[1L]])) iv(r) else paste0("(", iv(r[[1L]]), ", ", r[[2L]], ")"), ""), collapse = ", "), "]")

test_that("AlgebraicNumber", {
  a <- AlgebraicNumber(s2)
  expect_equal(sstr(a), "sqrt(2)")
  expect_equal(sstr(minimal_polynomial(a, x)), "x^2 - 2")
  expect_equal(cl(coeffs(a)), "[1, 0]")
  b <- AlgebraicNumber(s2, c(1, 1))
  expect_equal(sstr(b), "1 + sqrt(2)")
  expect_equal(cl(coeffs(b)), "[1, 1]")
  expect_equal(sstr(minpoly_of_element(b, x)), "x^2 - 2*x - 1")
  expect_equal(sstr(to_root(b)), "1 + sqrt(2)")
  th <- AlgebraicNumber(s2, alias = "theta")
  expect_equal(sstr(th), "theta")
  expect_equal(sstr(as_expr(th)), "sqrt(2)")
  expect_equal(latex(th), "\\theta")
  expect_equal(sstr(2 * a), "2*sqrt(2)")
  expect_equal(sstr(a^2), "sqrt(2)^2")
  expect_false(is_primitive_element(b))
  expect_equal(sstr(field_element(b, c(1, 2))), "sqrt(2) + 2")
  expect_equal(sstr(N(b, 30)), "2.41421356237309504880168872421")
})

test_that("subfields", {
  t <- to_number_field(s2, s2 + s3)
  expect_equal(sstr(t), "sqrt(2)")
  expect_equal(cl(coeffs(t)), "[1/2, 0, -9/2, 0]")
  t2 <- to_number_field(list(s2, s3))
  expect_equal(sstr(t2), "sqrt(2) + sqrt(3)")
  expect_equal(cl(field_isomorphism(s2, s2 + s3)), "[1/2, 0, -9/2, 0]")
  expect_equal(cl(field_isomorphism(s3, s2)), "None")
  expect_equal(cl(field_isomorphism(Integer(2)^Rational(1, 3), Integer(2)^Rational(1, 3) * (-1 + s3 * I) / 2)), "None")
  expect_error(to_number_field(s3, s2), class = "IsomorphismFailed")
})

test_that("real root isolation by continued fractions", {
  expect_equal(ivs(intervals(x^2 - 2)), "[((-2, -1), 1), ((1, 2), 1)]")
  expect_equal(ivs(intervals(x^2 - 2, eps = Rational(1, 100))), "[((-17/12, -24/17), 1), ((24/17, 17/12), 1)]")
  expect_equal(ivs(intervals(x^3 - x)), "[((-1, -1), 1), ((0, 0), 1), ((1, 1), 1)]")
  expect_equal(ivs(intervals((x - 1)^2 * (x + 2) * (x^2 - 3))), "[((-2, -2), 1), ((-2, -1), 1), ((1, 1), 2), ((1, 2), 1)]")
  expect_equal(ivs(intervals(x^4 - 10 * x^2 + 1, eps = Rational(1, 1000))),
               "[((-129/41, -151/48), 1), ((-7/22, -34/107), 1), ((34/107, 7/22), 1), ((151/48, 129/41), 1)]")
  expect_equal(ivs(intervals(x^2 - 2, sqf = TRUE)), "[(-2, -1), (1, 2)]")
  expect_equal(ivs(intervals(x^3 - 7 * x + 7)), "[((-4, -3), 1), ((1, 3/2), 1), ((3/2, 2), 1)]")
  expect_equal(ivs(intervals(x^2 - 2, inf = 0)), "[((1, 2), 1)]")
  expect_equal(ivs(intervals(x^4 + 1)), "[]")
  expect_equal(iv(refine_root(x^2 - 2, 1, 2, eps = Rational(1, 100))), "(24/17, 17/12)")
  expect_equal(iv(refine_root(x^2 - 2, 1, 2)), "(1, 3/2)")
  expect_equal(iv(refine_root(x^2 - 2, -2, -1, steps = 4)), "(-10/7, -7/5)")
  expect_equal(iv(isolate(s2)), "(1, 2)")
  expect_equal(iv(isolate(s2, eps = Rational(1, 100))), "(24/17, 17/12)")
  expect_equal(iv(isolate(-s3)), "(-2, -1)")
  expect_equal(iv(isolate(1 + sqrt(Integer(5)))), "(3, 4)")
  expect_equal(iv(isolate(Rational(3, 4))), "(3/4, 3/4)")
})
