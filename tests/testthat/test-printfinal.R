# Fast checks of the LaTeX, pretty, srepr, str and GLSL printers against
# outputs of SymPy.

test_that("printers follow SymPy", {
  x <- Symbol("x"); y <- Symbol("y"); n <- Symbol("n")
  theta <- Symbol("theta"); x1 <- Symbol("x1")
  expect_identical(pretty(theta + x1, use_unicode = TRUE), "\u03b8 + x\u2081")
  expect_identical(pretty(theta + x1, use_unicode = FALSE), "theta + x1")
  expect_identical(pretty(Piecewise(list(x, x < 1), list(x^2, TRUE)), use_unicode = FALSE), "/x   for x < 1\n|             \n< 2           \n|x   otherwise\n\\             ")
  expect_identical(pretty(Derivative(sin(x), x), use_unicode = TRUE), "d         \n\u2500\u2500(sin(x))\ndx        ")
  expect_identical(pretty(Limit(sin(x) / x, x, 0), use_unicode = FALSE), "     /sin(x)\\\n lim |------|\nx->0+\\  x   /")
  expect_identical(pretty(sym_factorial(x + 1), use_unicode = TRUE), "(x + 1)!")
  expect_identical(pretty(sym_binomial(x, y), use_unicode = FALSE), "/x\\\n| |\n\\y/")
  expect_identical(pretty(Eq(x, y), use_unicode = TRUE), "x = y")
  expect_identical(pretty(And(x, y), use_unicode = TRUE), "x \u2227 y")
  expect_identical(pretty(Or(x, Not(y)), use_unicode = FALSE), "Or(x, Not(y))")
  expect_identical(pretty(Interval(0, 1), use_unicode = TRUE), "[0, 1]")
  expect_identical(pretty(FiniteSet(1, 2, 3), use_unicode = TRUE), "{1, 2, 3}")
  expect_identical(pretty(Product(x, list(x, 1, n)), use_unicode = FALSE), "  n    \n_____  \n | |  x\n | |   \nx = 1  ")
  expect_identical(pretty(Sum(x^2, list(x, 0, n)), use_unicode = TRUE), "  n     \n ___    \n \u2572      \n  \u2572    2\n  \u2571   x \n \u2571      \n \u203e\u203e\u203e    \nx = 0   ")
  expect_identical(pretty(Integral(x^2, list(x, 0, 1)), use_unicode = FALSE), "  1      \n  /      \n |       \n |   2   \n |  x  dx\n |       \n/        \n0        ")
  expect_identical(pretty(sqrt(x^2 + 1), use_unicode = TRUE), "   ________\n  \u2571  2     \n\u2572\u2571  x  + 1 ")
  expect_identical(pretty(Matrix(list(list(1, x), list(y^2, 3))), use_unicode = TRUE), "\u23a11   x\u23a4\n\u23a2     \u23a5\n\u23a2 2   \u23a5\n\u23a3y   3\u23a6")
  expect_identical(pretty(hyper(list(2), list(1), x), use_unicode = TRUE), " \u250c\u2500  \u239b2 \u2502  \u239e\n \u251c\u2500  \u239c  \u2502 x\u239f\n1\u2575 1 \u239d1 \u2502  \u23a0")
  expect_identical(latex(Integral(x^2, list(x, 0, 1))), "\\int\\limits_{0}^{1} x^{2}\\, dx")
  expect_identical(latex(Derivative(sin(x), x)), "\\frac{d}{d x} \\sin{\\left(x \\right)}")
  expect_identical(srepr(Symbol("x", positive = TRUE, integer = TRUE)), "Symbol('x', positive=True, integer=True)")
  expect_identical(sstr(Float("1e20")), "100000000000000000000.")
  expect_identical(glsl_code(Matrix(list(list(1, 2), list(3, 4)))), "mat2(1, 2, 3, 4)")
})
