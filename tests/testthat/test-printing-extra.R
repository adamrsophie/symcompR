# Reference values from SymPy.
x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); f <- Function("f")

test_that("Rust, GLSL, Python and SMT-LIB printers", {
  expect_equal(rust_code(x^2 + sin(x)/3), "x.powi(2) + (1_f64/3.0)*x.sin()")
  expect_equal(rust_code(sqrt(x + 1)), "(x + 1).sqrt()")
  expect_equal(rust_code(x^Rational(3, 2)), "x.powf(3_f64/2.0)")
  expect_equal(rust_code(1/x), "x.recip()")
  expect_equal(rust_code(x^2, assign_to = "y"), "y = x.powi(2);")
  expect_equal(glsl_code(x^2 + sin(x)/3), "pow(x, 2.0) + (1.0/3.0)*sin(x)")
  expect_equal(glsl_code(x^Rational(3, 2)), "pow(x, 1.5)")
  expect_equal(glsl_code(S_Pi*x), "float pi = 3.14159265;\npi*x")
  expect_equal(python(y*exp(x)), "y = Symbol('y')\nx = Symbol('x')\ne = y*exp(x)")
  expect_equal(python(f(x) + Rational(1, 2)), "x = Symbol('x')\nf = Function('f')\ne = f(x) + Rational(1, 2)")
  expect_equal(python(x^Rational(3, 2)), "x = Symbol('x')\ne = x**Rational(3, 2)")
  expect_equal(smtlib_code(x^2 + 3*y), "(declare-const x Real)\n(declare-const y Real)\n(+ (pow x 2) (* 3 y))")
  expect_equal(smtlib_code(list(Eq(x + y, 3), x > 0), auto_declare = FALSE), "(assert (= (+ x y) 3))\n(assert (> x 0))")
  expect_equal(smtlib_code(-x - 2, auto_declare = FALSE), "(+ -2 (* -1 x))")
})

test_that("multiline_latex, MathML and dotprint", {
  expect_equal(multiline_latex(x, x^2 + y + 3), "\\begin{align*}\nx = & x^{2} \\\\\n& + y \\\\\n& + 3 \n\\end{align*}")
  expect_equal(multiline_latex(x, x^2 + y + z + 3, 2), "\\begin{align*}\nx = & x^{2} + y \\\\\n& + z + 3 \n\\end{align*}")
  expect_equal(mathml(x^2 + 1), "<apply><plus/><apply><power/><ci>x</ci><cn>2</cn></apply><cn>1</cn></apply>")
  expect_equal(mathml(x^2 + 1, printer = "presentation"), "<mrow><msup><mi>x</mi><mn>2</mn></msup><mo>+</mo><mn>1</mn></mrow>")
  expect_equal(mathml(-x + 2*y), "<apply><plus/><apply><minus/><ci>x</ci></apply><apply><times/><cn>2</cn><ci>y</ci></apply></apply>")
  expect_equal(mathml(sqrt(x)), "<apply><root/><ci>x</ci></apply>")
  expect_equal(mathml(x/y, printer = "presentation"), "<mrow><mfrac><mi>x</mi><mi>y</mi></mfrac></mrow>")
  d <- dotprint(x + 2)
  expect_match(d, "\"Add(Integer(2), Symbol('x'))_()\" -> \"Integer(2)_(0,)\";", fixed = TRUE)
})

test_that("p13 review fixes for printers and transforms", {
  t <- Symbol("t"); s <- Symbol("s"); r <- Symbol("r", positive = TRUE); k <- Symbol("k", positive = TRUE)
  F <- Function("F"); n <- Symbol("n", integer = TRUE)
  expect_equal(sstr(hankel_transform(1/r, r, k, -1)), "-1/k")
  expect_identical(hankel_transform(1/r^3, r, k, 0), S_Infinity)
  expect_equal(sstr(laplace_correspondence(LaplaceTransform(f(2*t), t, s), list(list(f, F)))), "LaplaceTransform(f(2*t), t, s)")
  expect_equal(smtlib_code(Eq(n^2, 2)), "(declare-const n Int)\n(assert (= (pow n 2) 2))")
  expect_equal(smtlib_code(And(x, y)), "(declare-const x Bool)\n(declare-const y Bool)\n(assert (and x y))")
  expect_equal(python(Rational(-1, 3)), "e = Rational(-1, 3)")
  expect_equal(python(sin(Rational(1, 3))), "e = sin(Rational(1, 3))")
  expect_equal(python(Integral(x, list(x, 0, 1))), "x = Symbol('x')\ne = Integral(x, (x, 0, 1))")
  expect_equal(python(x^Rational(3, 2)), "x = Symbol('x')\ne = x**Rational(3, 2)")
  expect_equal(rust_code(x - 1), "x - 1")
  expect_equal(glsl_code(x - 1), "x - 1")
  expect_equal(mathml(x - 1, printer = "presentation"), "<mrow><mi>x</mi><mo>-</mo><mn>1</mn></mrow>")
  expect_equal(sstr(singularityintegrate(SingularityFunction(x + 1, 0, 1), x)), "SingularityFunction(x + 1, 0, 2)/2")
  expect_equal(vapply(free_symbols(LaplaceTransform(f(t), t, t)), sstr, ""), "t")
  expect_equal(sstr(inverse_mellin_transform(gamma(1/s), s, x, list(0, 1))), "InverseMellinTransform(gamma(1/s), s, x, 0, 1)")
  expect_equal(rust_code(sqrt(Integer(2))), "1.4142135623731")
  expect_equal(rust_code(3^x), "3.0_f64.powf(x)")
  expect_equal(glsl_code(atan2(y, x)), "atan(y, x)")
  expect_equal(pretty(x^Rational(1, 1234567), use_unicode = FALSE), "1234567___\n     \\/ x ")
  expect_equal(pretty(f(), use_unicode = FALSE), "f()")
})

test_that("TableForm text and LaTeX output follow SymPy", {
  t1 <- TableForm(list(list(5, 7), list(4, 2), list(10, 3)))
  expect_equal(format(t1), "5  7\n4  2\n10 3")
  expect_equal(latex(t1), "\\begin{tabular}{l l}\n$5$ & $7$ \\\\\n$4$ & $2$ \\\\\n$10$ & $3$ \\\\\n\\end{tabular}")
  t2 <- TableForm(list(list(5, 7), list(4, 2), list(10, 3)), headings = "automatic")
  expect_equal(format(t2), "  | 1  2\n--------\n1 | 5  7\n2 | 4  2\n3 | 10 3")
  expect_equal(latex(t2), "\\begin{tabular}{r l l}\n & 1 & 2 \\\\\n\\hline\n1 & $5$ & $7$ \\\\\n2 & $4$ & $2$ \\\\\n3 & $10$ & $3$ \\\\\n\\end{tabular}")
  t3 <- TableForm(list(list("a", 0), list(x^2, 1/x)), headings = list(c("r1", "row2"), c("A", "B")), alignments = "right")
  expect_equal(latex(t3), "\\begin{tabular}{r r r}\n & A & B \\\\\n\\hline\nr1 & $a$ &   \\\\\nrow2 & $x^{2}$ & $\\frac{1}{x}$ \\\\\n\\end{tabular}")
  expect_equal(format(TableForm(list(list(1, 22, 333), list(4444, 5, 6)), alignments = "c")), " 1   22 333\n4444 5   6 ")
  expect_equal(format(TableForm(list(list(1, 22, 333), list(4444, 5, 0)), wipe_zeros = FALSE)), "1    22 333\n4444 5  0  ")
  expect_equal(format(TableForm(list(list(1, NULL), list(3)))), "1 None\n3     ")
  expect_equal(format(TableForm(list(list(1, NULL), list(3)), pad = "-")), "1 -\n3 -")
  expect_equal(latex(TableForm(list(list(Rational(1, 3), 2)), formats = list("%.2f", NULL))),
               "\\begin{tabular}{l l}\n0.33 & $2$ \\\\\n\\end{tabular}")
  expect_equal(format(TableForm(list(list(1, 2), list(3, 4)), headings = list(NULL, c("alpha", "b")), alignments = "r")),
               "alpha b\n-------\n    1 2\n    3 4")
  expect_error(TableForm(list(list(1, 2)), alignments = c("l", "r", "c")), "wrong number of alignments")
  expect_equal(capture.output(print(as.matrix(TableForm(list(list(1, 2), list(3, 4)))))),
               capture.output(print(Matrix(list(list(1, 2), list(3, 4))))))
})

test_that("p14 h2 fixes: smtlib booleans, python keywords, hankel divergence sign", {
  expect_equal(smtlib_code(Eq(x, TRUE, evaluate = FALSE)), "(declare-const x Bool)\n(assert (= x true))")
  expect_equal(smtlib_code(x), "(declare-const x Bool)\n(assert x)")
  expect_equal(python(Symbol("lambda") + 1), "lambda_ = Symbol('lambda')\ne = lambda_ + 1")
  r <- Symbol("r", positive = TRUE); k <- Symbol("k", positive = TRUE)
  expect_identical(hankel_transform(-1/r^3, r, k, 0), S_NegativeInfinity)
})

test_that("p15 review fixes: python names, smtlib order, TableForm formats, hankel sign", {
  expect_equal(python(Symbol("lambda") + Symbol("lambda_")), "lambda__ = Symbol('lambda')\nlambda_ = Symbol('lambda_')\ne = lambda_ + lambda__")
  expect_equal(python(Function("lambda")(x)), "x = Symbol('x')\nlambda_ = Function('lambda')\ne = lambda_(x)")
  expect_equal(smtlib_code(list(Eq(x, y, evaluate = FALSE), y)),
               "(declare-const x Bool)\n(declare-const y Bool)\n(assert (= x y))\n(assert y)")
  expect_equal(latex(TableForm(list(list(Integer("2147483648"))), formats = list("%d"))), "\\begin{tabular}{l}\n2147483648 \\\\\n\\end{tabular}")
  expect_equal(latex(TableForm(list(list(Integer("1234567890123456"))), formats = list("%.0f"))), "\\begin{tabular}{l}\n1234567890123456 \\\\\n\\end{tabular}")
  expect_equal(format(TableForm(list(list(1, 2, 3)), alignments = "rcl")), "1 2 3")
  expect_equal(latex(TableForm(list(list(NULL)), formats = list(function(e, i, j) "MISSING"))), "\\begin{tabular}{l}\nMISSING \\\\\n\\end{tabular}")
  r <- Symbol("r", positive = TRUE); k <- Symbol("k", positive = TRUE)
  expect_identical(hankel_transform(r^(-4), r, k, Rational(-3, 2)), S_NegativeInfinity)
})
