# Expected strings are SymPy outputs (mpmath arithmetic) for the same calls.

x <- Symbol("x"); EG <- sympify("EulerGamma"); CT <- sympify("Catalan")

test_that("arbitrary precision evaluation matches SymPy", {
  expect_equal(sstr(Float("0.1") + Float("0.2")), "0.300000000000000")
  expect_equal(sstr(N(exp(Integer(100)), 30)), "2.68811714181613544841262555158e+43")
  expect_equal(sstr(N(sym_pi, 5)), "3.1416")
  expect_equal(sstr(N(sym_pi, 2)), "3.1")
  expect_equal(sstr(N(1/Integer(3), 30)), "0.333333333333333333333333333333")
  expect_equal(sstr(N(exp(Integer(-100)), 20)), "3.7200759760208359630e-44")
  expect_equal(sstr(N(Integer(10)^30 * sym_pi, 20)), "3.1415926535897932385e+30")
  expect_equal(sstr(N(sin(Integer(10)^20), 20)), "-0.64525128526578084421")
  expect_equal(sstr(N(exp(sym_pi * sqrt(Integer(163))), 40)), "262537412640768743.9999999999992500725972")
  expect_equal(sstr(N(Integer(10)^25 + sym_pi, 30)), "10000000000000000000000003.1416")
  expect_equal(sstr(x + Float(0.5)), "x + 0.5")
  expect_equal(sstr(N(sym_pi + sym_I, 20)), "3.1415926535897932385 + 1.0*I")
  expect_equal(sstr(Float(123456789.123457, 10)), "123456789.1")
  expect_equal(sstr(Float(1e-07)), "1.00000000000000e-7")
  expect_equal(sstr(Float(1e+20)), "1.00000000000000e+20")
  expect_equal(sstr(Float(12345678901234569216)), "1.23456789012346e+19")
  expect_equal(sstr(N(sym_E, 30)), "2.71828182845904523536028747135")
  expect_equal(sstr(N(EG, 30)), "0.577215664901532860606512090082")
  expect_equal(sstr(N(CT, 30)), "0.915965594177219015054603514932")
  expect_equal(sstr(N(gamma(Rational(1, 3)), 30)), "2.67893853470774763365569294097")
  expect_equal(sstr(N(zeta(Integer(3)), 30)), "1.20205690315959428539973816151")
  expect_equal(sstr(N(erf(Integer(1)), 30)), "0.842700792949714869341220635083")
  expect_equal(sstr(N(loggamma(Integer(10)), 25)), "12.80182748008146961120772")
  expect_equal(sstr(N(zeta(Rational(1, 2)), 25)), "-1.460354508809586812889499")
  expect_equal(sstr(N(zeta(Rational(-1, 2)), 25)), "-0.2078862249773545660173067")
})

test_that("Float powers, functions and partial evaluation at the Floats' precision", {
  a <- Float("2", 50)
  expect_equal(sstr(a^Float("0.5", 50)), "1.4142135623730950488016887242096980785696718753769")
  expect_equal(sstr(a^Rational(1, 3)), "1.2599210498948731647672106072782283505702514647015")
  expect_equal(sstr(exp(a)), "7.3890560989306502272304274605750078131803155705518")
  expect_equal(sstr(sin(a)), "0.90929742682568169539601986591174484270225497144789")
  expect_equal(sstr(a^Integer(100)), "1267650600228229401496703205376.0000000000000000000")
  expect_equal(sstr(Float("-2", 30)^Float("0.5", 30)), "1.41421356237309504880168872421*I")
  expect_equal(sstr(Float(-2.0)^Float(0.5)), "1.4142135623731*I")
  expect_equal(sstr(Float(0)^Float(2)), "0.0")
  expect_equal(sstr(Float(0.0)^Integer(-1)), "zoo")
  expect_equal(sstr(Float(2.5)^Float(-1.5)), "0.252982212813470")
  expect_equal(sstr(N(x^2 + sym_pi * x, 30)), "x^2 + 3.14159265358979323846264338328*x")
  expect_equal(sstr(N(sym_pi * x + exp(Integer(1)), 30)), "3.14159265358979323846264338328*x + 2.71828182845904523536028747135")
  expect_equal(sstr(N(sin(x) + Rational(1, 3), 20)), "sin(x) + 0.33333333333333333333")
  expect_equal(sstr(N(x^Rational(1, 2) * sym_pi, 20)), "3.1415926535897932385*x^0.5")
})
