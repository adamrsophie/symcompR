# Expected values are SymPy's outputs for the same calls (Mod).

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); phi <- Symbol("phi"); t <- Symbol("t", real = TRUE); p <- Symbol("p", positive = TRUE)
k <- Symbol("k", integer = TRUE); m <- Symbol("m", integer = TRUE, positive = TRUE)
npos <- Symbol("npos", integer = TRUE, positive = TRUE); nprime <- Symbol("nprime", prime = TRUE)
ncomp <- Symbol("ncomp", composite = TRUE, odd = TRUE); neven <- Symbol("neven", even = TRUE); nodd <- Symbol("nodd", odd = TRUE)
x1 <- Symbol("x1", integer = TRUE); i <- Symbol("i", integer = TRUE); ip <- Symbol("ip", integer = TRUE, positive = TRUE); jp <- Symbol("jp", integer = TRUE, positive = TRUE)
j2 <- Symbol("j2", integer = TRUE)

test_that("Mod match SymPy", {
  expect_equal(sstr(Mod(x, 1)), "Mod(x, 1)")
  expect_equal(sstr(Mod(sym_pi, sym_pi)), "0")
  expect_equal(sstr(Mod(Integer(5), 3)), "2")
  expect_equal(sstr(Mod(Integer(-5), 3)), "1")
  expect_equal(sstr(Mod(Integer(5), -3)), "-1")
  expect_equal(sstr(Mod(Integer(-5), -3)), "-2")
  expect_equal(sstr(Mod(Integer(5), x)), "Mod(5, x)")
  expect_equal(sstr(subs(Mod(x, y), list(x = 5, y = 3))), "2")
  expect_equal(sstr(Mod(S_NaN, 1)), "nan")
  expect_equal(sstr(Mod(Integer(0), x)), "0")
  expect_equal(sstr(Mod(x^m, x)), "Mod(x^m, x)")
  expect_equal(sstr(Mod(k^(-m), k)), "Mod(k^(-m), k)")
  expect_equal(sstr(Mod(k^m, k)), "0")
  expect_equal(sstr(Mod((-2*k)^m, k)), "0")
  expect_equal(sstr(Mod(x - 3.3, 1)), "Mod(1.0*x + 0.7, 1)")
  expect_equal(sstr(Mod(Float(-3.3), 1)), "0.700000000000000")
  expect_equal(sstr(Mod(Float(0.7), 1)), "0.700000000000000")
  expect_equal(sstr(Mod(Float(1.3), 1)), "0.300000000000000")
  expect_equal(sstr(Mod(Float(1.3), Float(0.7))), "0.600000000000000")
  expect_equal(sstr(Mod(Float(1.3), Rational(7, 10))), "0.600000000000000")
  expect_equal(sstr(Mod(Rational(13, 10), Float(0.7))), "0.600000000000000")
  expect_equal(sstr(Mod(Rational(13, 10), Rational(7, 10))), "3/5")
  expect_equal(sstr(Mod(-sqrt(Integer(3)), sqrt(Integer(2)))), "-sqrt(3) + 2*sqrt(2)")
  expect_equal(sstr(Mod(sqrt(Integer(3)), -sqrt(Integer(2)))), "-2*sqrt(2) + sqrt(3)")
  expect_equal(sstr(Mod(sqrt(Integer(2)), sqrt(Integer(3)))), "sqrt(2)")
  expect_equal(sstr(Mod(-sqrt(Integer(2)), -sqrt(Integer(3)))), "-sqrt(2)")
  expect_equal(sstr(Mod(3*x + y, 9)), "Mod(3*x + y, 9)")
  expect_equal(sstr(Mod(Mod(x, t), t)), "Mod(x, t)")
  expect_equal(sstr(Mod(-Mod(x, t), t)), "Mod(-x, t)")
  expect_equal(sstr(Mod(Mod(x, 2*t), t)), "Mod(x, t)")
  expect_equal(sstr(Mod(-Mod(x, 2*t), t)), "Mod(-x, t)")
  expect_equal(sstr(Mod(Mod(x, t), 2*t)), "Mod(x, t)")
  expect_equal(sstr(Mod(-Mod(x, t), -2*t)), "-Mod(x, t)")
  expect_equal(sstr(Mod(Mod(x, -4), 2)), "Mod(x, 2)")
  expect_equal(sstr(Mod(-Mod(x, 4), -2)), "-Mod(x, 2)")
  expect_equal(sstr(Mod(5*sqrt(Integer(2)), sqrt(Integer(5)))), "-3*sqrt(5) + 5*sqrt(2)")
  expect_equal(sstr(Mod(Integer(2), p + 3)), "2")
  expect_equal(sstr(Mod(Integer(-2), p + 3)), "p + 1")
  expect_equal(sstr(Mod(Integer(2), -p - 3)), "-p - 1")
  expect_equal(sstr(Mod(Integer(-2), -p - 3)), "-2")
  expect_equal(sstr(Mod(p + 5, p + 3)), "2")
  expect_equal(sstr(Mod(-p - 5, p + 3)), "p + 1")
  expect_equal(sstr(Mod(p + 5, -p - 3)), "-p - 1")
  expect_equal(sstr(Mod(-p - 5, -p - 3)), "-2")
  expect_equal(sstr(Mod(p + 1, p - 1)), "Mod(p + 1, p - 1)")
  expect_equal(sstr(Mod(Integer(1), npos)), "Mod(1, npos)")
  expect_equal(sstr(Mod(Integer(1), nprime)), "1")
  expect_equal(sstr(Mod(x + 3, 1)), "Mod(x, 1)")
  expect_equal(sstr(Mod(x + Float(3), 1)), "Mod(1.0*x, 1)")
  expect_equal(sstr(Mod(x - Rational(33, 10), 1)), "Mod(x + 7/10, 1)")
  expect_equal(sstr(Mod(0.6*x + y, 0.3*y)), "Mod(0.6*x + 0.1*y, 0.3*y)")
  expect_equal(sstr(Mod(x + 1, x)), "Mod(1, x)")
  expect_equal(sstr(Mod(x + y, x)), "Mod(y, x)")
  expect_equal(sstr(Mod(x + y + 2, x)), "Mod(y + 2, x)")
  expect_equal(sstr(Mod(12*x + 18*y, 3*x)), "3*(Mod(6*y, x))")
  expect_equal(sstr(Mod(-3*x, -2*y)), "-Mod(3*x, 2*y)")
  expect_equal(sstr(Mod(0.6*sym_pi, 0.3*x*sym_pi)), "0.3*pi*(Mod(2, x))")
  expect_equal(sstr(Mod(0.6*sym_pi, 0.31*x*sym_pi)), "pi*(Mod(0.6, 0.31*x))")
  expect_equal(sstr(Mod(6*sym_pi, 0.3*x*sym_pi)), "0.3*pi*(Mod(20, x))")
  expect_equal(sstr(Mod(6*sym_pi, 0.31*x*sym_pi)), "pi*(Mod(6.0, 0.31*x))")
  expect_equal(sstr(Mod(12*x, 2*y)), "2*(Mod(6*x, y))")
  expect_equal(sstr(Mod(12*x, 15*y)), "3*(Mod(4*x, 5*y))")
  expect_equal(sstr(Mod(12*x, 15*x*y)), "3*x*(Mod(4, 5*y))")
  expect_equal(sstr(Mod(-2*sym_pi, 3*sym_pi)), "pi")
  expect_equal(sstr(Mod(2*x + 2, x + 1)), "0")
  expect_equal(sstr(Mod(x*(x + 1), x + 1)), "(x + 1)*(Mod(x, 1))")
  expect_equal(sstr(Mod(5.0*x, 0.1*y)), "0.1*(Mod(50*x, y))")
  expect_equal(sstr(Mod(3*i*x, 2*i*y)), "i*(Mod(3*x, 2*y))")
  expect_equal(sstr(Mod(4*i, 4)), "0")
  expect_equal(sstr(Mod(sym_factorial(npos), npos)), "0")
  expect_equal(sstr(Mod(sym_factorial(npos + 2), npos)), "0")
  expect_equal(sstr(Mod(sym_factorial(npos + 4), npos + 5)), "Mod(factorial(npos + 4), npos + 5)")
  expect_equal(sstr(Mod(sym_factorial(nprime - 1), nprime)), "nprime - 1")
  expect_equal(sstr(Mod(sym_factorial(nprime - 1), -nprime)), "-1")
  expect_equal(sstr(Mod(sym_factorial(ncomp - 1), ncomp)), "0")
  expect_equal(sstr(Mod(neven, 2)), "0")
  expect_equal(sstr(Mod(nodd, 2)), "1")
  expect_equal(sstr(Mod(Mod(x + 1, 2) + 1, 2)), "Mod(x, 2)")
  expect_equal(sstr(Mod(Mod(x1 + 2, 4)*(x1 + 4), 4)), "Mod(x1*(x1 + 2), 4)")
  expect_equal(sstr(Mod(Mod(x1 + 2, 4)*4, 4)), "0")
  expect_equal(sstr(Mod(3*ip, 2)), "Mod(ip, 2)")
  expect_equal(sstr(Mod(8*ip/jp, 4)), "4*(Mod(2*ip/jp, 1))")
  expect_equal(sstr(Mod(8*ip, 4)), "0")
  expect_equal(sstr(Mod(Float(4)*Mod(phi, 1), 2)), "2.0*(Mod(2*(Mod(phi, 1)), 1))")
  expect_equal(sstr(Mod(3*x1, 2)), "Mod(x1, 2)")
  expect_equal(sstr(Mod(3*x, 2)), "Mod(3*x, 2)")
  expect_equal(sstr(Mod(2*Mod(x, 3), 5)), "Mod(2*(Mod(x, 3)), 5)")
  expect_equal(sstr(8*Mod(floor(x/64), 4)), "8*(Mod(floor(x/64), 4))")
  expect_equal(sstr(Mod(3*Mod(x1, 7), 7)), "Mod(3*x1, 7)")
  expect_equal(sstr(Mod(5*Mod(x1, 3), 3)), "Mod(2*x1, 3)")
  expect_equal(sstr(Mod(i, Rational(1, 2))), "0")
  expect_equal(sstr(Mod(i + Rational(1, 3), Rational(1, 2))), "1/3")
  expect_equal(sstr(Mod(-i, Rational(1, 2))), "0")
  expect_equal(sstr(Mod(2*i + 1, 2)), "1")
  expect_equal(sstr(Mod(sym_pi, 3)), "-3 + pi")
  expect_equal(sstr(Mod(-sym_pi, 3)), "6 - pi")
  expect_equal(sstr(Mod(sym_E, 1)), "-2 + E")
  expect_equal(sstr(Mod(x^2, 3)), "Mod(x^2, 3)")
  expect_equal(sstr(Mod(Integer(3)^100, 7)), "4")
  expect_equal(sstr(Mod(x, Inf)), "nan")
  expect_equal(sstr(Mod(2*x, 4)), "2*(Mod(x, 2))")
  expect_equal(sstr(Mod(2*i, 4)), "2*(Mod(i, 2))")
  expect_equal(sstr(Mod(i*j2, j2)), "0")
  expect_equal(sstr(Mod(x + Rational(1,2), Rational(1,3))), "Mod(x + 1/6, 1/3)")
})
