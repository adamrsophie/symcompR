test_that("test_secondquant: test_PermutationOperator", {
  e <- .new(character(), 'test_secondquant')
  .do(e, r"---(.tmp <- sym_symbols("p,q,r,s"))---")
  .do(e, r"---(p <- .tmp[[1]])---")
  .do(e, r"---(v_q <- .tmp[[2]])---")
  .do(e, r"---(r <- .tmp[[3]])---")
  .do(e, r"---(s <- .tmp[[4]])---")
  .do(e, r"---(.tmp <- lapply(.qlist("fghi"), function(.v) .qcallobj("Function", .v)))---")
  .do(e, r"---(f <- .tmp[[1]])---")
  .do(e, r"---(g <- .tmp[[2]])---")
  .do(e, r"---(h <- .tmp[[3]])---")
