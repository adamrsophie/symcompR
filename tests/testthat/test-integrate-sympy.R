# Expected values are SymPy's outputs for the same calls (integrate).

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); a <- Symbol("a"); b <- Symbol("b"); c <- Symbol("c"); d <- Symbol("d"); e <- Symbol("e"); s <- Symbol("s"); t <- Symbol("t")
mi_fmt <- function(v) if (is.null(v)) "None" else gsub("\n", " ", sstr(v))

test_that("integrate match SymPy", {
  expect_equal(mi_fmt(integrate((-60 * exp(x) - 19.2 * exp(4 * x)) * exp(4 * x), x)), "-2.4*exp(8*x) - 12.0*exp(5*x)")
  expect_equal(mi_fmt(integrate((1 + sin(x)) / x, x)), "log(x) + Si(x)")
  expect_equal(mi_fmt(integrate((3 * t * x) ^ 5, x)), "81*t^5*x^6/2")
  expect_equal(mi_fmt(integrate((cos(x) + 2) / x, x)), "2*log(x) + Ci(x)")
  expect_equal(mi_fmt(integrate((d + e * x) / sqrt(a + b * x + c * x ^ 2), x)), "Piecewise((e*sqrt(a + b*x + c*x^2)/c + (-b*e/(2*c) + d)*log(b + 2*sqrt(c)*sqrt(a + b*x + c*x^2) + 2*c*x)/sqrt(c), Ne(c, 0) & Ne(a - b^2/(4*c), 0)), ((b/(2*c) + x)*(-b*e/(2*c) + d)*log(b/(2*c) + x)/sqrt(c*(b/(2*c) + x)^2) + e*sqrt(a + b*x + c*x^2)/c, Ne(c, 0)), ((d*x + e*x^2/2)/sqrt(a), Eq(b, 0)), (2*(d*sqrt(a + b*x) - e*(a*sqrt(a + b*x) - (a + b*x)^(3/2)/3)/b)/b, True))")
  expect_equal(mi_fmt(integrate((sqrt(x) - x ^ 3) / x ^ Rational(1, 3), x)), "6*x^(7/6)/7 - 3*x^(11/3)/11")
  expect_equal(mi_fmt(integrate(-a / (a ^ 2 + x ^ 2), x)), "I*log(-I*a + x)/2 - I*log(I*a + x)/2")
  expect_equal(mi_fmt(integrate(1 / (1 + sym_I * x ^ 2), x)), "-I*(sqrt(-I)*log(x - I*sqrt(-I))/2 - sqrt(-I)*log(x + I*sqrt(-I))/2)")
  expect_equal(mi_fmt(integrate(1 / (1 + x ^ 2), x)), "atan(x)")
  expect_equal(mi_fmt(integrate(1 / (x * sqrt(1 - x ^ 2)), x)), "Piecewise((-acosh(1/x), 1/Abs(x^2) > 1), (I*asin(1/x), True))")
  expect_equal(mi_fmt(integrate(1 / (x ^ 2 + y ^ 2) ^ Rational(3, 2), x)), "x/(y^3*sqrt(x^2/y^2 + 1))")
  expect_equal(mi_fmt(integrate(1 / (x ^ 5 + 1), x)), "log(x + 1)/5 + (-1/20 + sqrt(5)/20)*log(x^2 + x*(-1/2 + sqrt(5)/2) + 1) + (-sqrt(5)/20 - 1/20)*log(x^2 + x*(-sqrt(5)/2 - 1/2) + 1) - 2*sqrt(5/8 - sqrt(5)/8)*atan(-2*sqrt(2)*x/sqrt(5 - sqrt(5)) + sqrt(2)/(2*sqrt(5 - sqrt(5))) + sqrt(10)/(2*sqrt(5 - sqrt(5))))/5 + 2*sqrt(sqrt(5)/8 + 5/8)*atan(2*sqrt(2)*x/sqrt(sqrt(5) + 5) - sqrt(2)/(2*sqrt(sqrt(5) + 5)) + sqrt(10)/(2*sqrt(sqrt(5) + 5)))/5")
  expect_equal(mi_fmt(integrate(1 / (x + 3) / (1 + x) ^ 3, x)), "x/(4*x^2 + 8*x + 4) + log(x + 1)/8 - log(x + 3)/8")
  expect_equal(mi_fmt(integrate(1 / sqrt(16 + 4 * x ^ 2), x)), "asinh(x/2)/2")
  expect_equal(mi_fmt(integrate(1 / sqrt(a + b * x + c * x ^ 2), x)), "Piecewise((log(b + 2*sqrt(c)*sqrt(a + b*x + c*x^2) + 2*c*x)/sqrt(c), Ne(c, 0) & Ne(a - b^2/(4*c), 0)), ((b/(2*c) + x)*log(b/(2*c) + x)/sqrt(c*(b/(2*c) + x)^2), Ne(c, 0)), (x/sqrt(a), Eq(b, 0)), (2*sqrt(a + b*x)/b, True))")
  expect_equal(mi_fmt(integrate(1 / sqrt(exp(x) + 1), x)), "log(sqrt(exp(x) + 1) - 1) - log(sqrt(exp(x) + 1) + 1)")
  expect_equal(mi_fmt(integrate(1 / sqrt(x) ^ 3, x)), "-2/sqrt(x)")
  expect_equal(mi_fmt(integrate(2 ^ x + 3 ^ x, x)), "2^x/log(2) + 3^x/log(3)")
  expect_equal(mi_fmt(integrate(2 ^ x - 2 * x, x)), "2^x/log(2) - x^2")
  expect_equal(mi_fmt(integrate(cos(asin(x)), x)), "x*sqrt(1 - x^2)/2 + asin(x)/2")
  expect_equal(mi_fmt(integrate(cos(x) ^ 2 / x ^ 2, x)), "-Si(2*x) - cos(2*x)/(2*x) - 1/(2*x)")
  expect_equal(mi_fmt(integrate(cosh(x) ^ (-2), x)), "2*tanh(x/2)/(tanh(x/2)^2 + 1)")
  expect_equal(mi_fmt(integrate(csch(x), x)), "log(tanh(x/2))")
  expect_equal(mi_fmt(integrate(exp(-sym_I * x ^ 2), x)), "-I^(3/2)*sqrt(pi)*erf(sqrt(I)*x)/2")
  expect_equal(mi_fmt(integrate(exp(-log(x) ^ 2), x)), "sqrt(pi)*exp(1/4)*erf(log(x) - 1/2)/2")
  expect_equal(mi_fmt(integrate(exp(-x ^ 2 + sym_I * c * x), x)), "-sqrt(pi)*exp(-c^2/4)*erf(I*c/2 - x)/2")
  expect_equal(mi_fmt(integrate(exp(-x) * x ^ y, x)), "y*gamma(y + 1)*lowergamma(y + 1, x)/gamma(y + 2) + gamma(y + 1)*lowergamma(y + 1, x)/gamma(y + 2)")
  expect_equal(mi_fmt(integrate(exp(-z * log(x) ^ 2), x)), "Integral(exp(-z*log(x)^2), x)")
  expect_equal(mi_fmt(integrate(exp(sym_I * x) * log(x), x)), "-I*exp(I*x)*log(x) + I*Ei(I*x)")
  expect_equal(mi_fmt(integrate(exp(a * x ^ 2 + b * x + c), x)), "Piecewise((sqrt(pi)*exp(c - b^2/(4*a))*erfi((2*a*x + b)/(2*sqrt(a)))/(2*sqrt(a)), Ne(a, 0)), (x*exp(c), Eq(b, 0)), (exp(b*x + c)/b, True))")
  expect_equal(mi_fmt(integrate(exp(log(x) ^ 2), x)), "sqrt(pi)*exp(-1/4)*erfi(log(x) + 1/2)/2")
  expect_equal(mi_fmt(integrate(exp(x) / (1 + x) ^ 2, x)), "-exp(-1)*expint(2, -x - 1)/(x + 1)")
  expect_equal(mi_fmt(integrate(log(x) * exp(-x), x)), "Ei(-x) - exp(-x)*log(x)")
  expect_equal(mi_fmt(integrate(S_Pi * sqrt(x) + S_E * sqrt(x) ^ 3, x)), "2*E*x^(5/2)/5 + 2*pi*x^(3/2)/3")
  expect_equal(mi_fmt(integrate(S_Pi * sqrt(x), x)), "2*pi*x^(3/2)/3")
  expect_equal(mi_fmt(integrate(sin(2 * x) / sin(x), x)), "2*sin(x)")
  expect_equal(mi_fmt(integrate(sin(acos(x)), x)), "x*sqrt(1 - x^2)/2 + asin(x)/2")
  expect_equal(mi_fmt(integrate(sin(x ^ 2), x)), "3*sqrt(2)*sqrt(pi)*fresnels(sqrt(2)*x/sqrt(pi))*gamma(3/4)/(8*gamma(7/4))")
  expect_equal(mi_fmt(integrate(sin(x) / x, x)), "Si(x)")
  expect_equal(mi_fmt(integrate(sqrt(-x ^ 2 - 4), x)), "x*sqrt(-x^2 - 4)/2 - 2*atan(x/sqrt(-x^2 - 4))")
  expect_equal(mi_fmt(integrate(sqrt(a + b * x + c * x ^ 2), x)), "Piecewise(((b/(4*c) + x/2)*sqrt(a + b*x + c*x^2) + (a/2 - b^2/(8*c))*log(b + 2*sqrt(c)*sqrt(a + b*x + c*x^2) + 2*c*x)/sqrt(c), Ne(c, 0) & Ne(a - b^2/(4*c), 0)), ((b/(4*c) + x/2)*sqrt(a + b*x + c*x^2) + (a/2 - b^2/(8*c))*(b/(2*c) + x)*log(b/(2*c) + x)/sqrt(c*(b/(2*c) + x)^2), Ne(c, 0)), (sqrt(a)*x, Eq(b, 0)), (2*(a + b*x)^(3/2)/(3*b), True))")
  expect_equal(mi_fmt(integrate(sqrt(x ^ 2 + z ^ 2), x)), "x*z*sqrt(x^2/z^2 + 1)/2 + z^2*asinh(x/z)/2")
  expect_equal(mi_fmt(integrate(sqrt(x) ^ 3, x)), "2*x^(5/2)/5")
  expect_equal(mi_fmt(integrate(sqrt(x), x)), "2*x^(3/2)/3")
  expect_equal(mi_fmt(integrate(x * Abs(9 - x ^ 2), x)), "Integral(x*Abs(x^2 - 9), x)")
  expect_equal(mi_fmt(integrate(x * exp(x) * log(x), x)), "(x*exp(x) - exp(x))*log(x) - exp(x) + Ei(x)")
  expect_equal(mi_fmt(integrate(x * sec(x) ^ 2, x)), "x*tan(x) + log(cos(x))")
  expect_equal(mi_fmt(integrate(x * sin(y), x)), "x^2*sin(y)/2")
  expect_equal(mi_fmt(integrate(x * sqrt(1 + 2 * x), x)), "2*x^2*sqrt(2*x + 1)/5 + x*sqrt(2*x + 1)/15 - sqrt(2*x + 1)/15")
  expect_equal(mi_fmt(integrate(x ^ 1000 * sin(y), x)), "x^1001*sin(y)/1001")
  expect_equal(mi_fmt(integrate(x ^ 2 * sqrt(5 - x ^ 2), x)), "Piecewise((I*x^5/(4*sqrt(x^2 - 5)) - 15*I*x^3/(8*sqrt(x^2 - 5)) + 25*I*x/(8*sqrt(x^2 - 5)) - 25*I*acosh(sqrt(5)*x/5)/8, Abs(x^2) > 5), (-x^5/(4*sqrt(5 - x^2)) + 15*x^3/(8*sqrt(5 - x^2)) - 25*x/(8*sqrt(5 - x^2)) + 25*asin(sqrt(5)*x/5)/8, True))")
  expect_equal(mi_fmt(integrate(x ^ 2, x)), "x^3/3")
  expect_equal(mi_fmt(integrate(x ^ y, x)), "Piecewise((x^(y + 1)/(y + 1), Ne(y, -1)), (log(x), True))")
  expect_equal(mi_fmt(integrate(y + x + exp(x), x)), "x^2/2 + x*y + exp(x)")
  expect_equal(mi_fmt(integrate(x*cos(x)^2, x)), "x^2*sin(x)^2/4 + x^2*cos(x)^2/4 + x*sin(x)*cos(x)/2 + cos(x)^2/4")
  expect_equal(mi_fmt(integrate(sin(x)^3, x)), "cos(x)^3/3 - cos(x)")
  expect_equal(mi_fmt(integrate(sin(x)^2*cos(x)^2, x)), "x/8 - sin(2*x)*cos(2*x)/16")
  expect_equal(mi_fmt(integrate(tan(x)^2, x)), "-x + sin(x)/cos(x)")
  expect_equal(mi_fmt(integrate(sec(x), x)), "-log(sin(x) - 1)/2 + log(sin(x) + 1)/2")
  expect_equal(mi_fmt(integrate(1/cos(x), x)), "-log(sin(x) - 1)/2 + log(sin(x) + 1)/2")
  expect_equal(mi_fmt(integrate(cot(x), x)), "log(sin(x))")
  expect_equal(mi_fmt(integrate(sinh(x)^2, x)), "x*sinh(x)^2/2 - x*cosh(x)^2/2 + sinh(x)*cosh(x)/2")
  expect_equal(mi_fmt(integrate(x^2*exp(x), x)), "(x^2 - 2*x + 2)*exp(x)")
  expect_equal(mi_fmt(integrate(x*log(x)^2, x)), "x^2*log(x)^2/2 - x^2*log(x)/2 + x^2/4")
  expect_equal(mi_fmt(integrate(atan(x), x)), "x*atan(x) - log(x^2 + 1)/2")
  expect_equal(mi_fmt(integrate(asin(x), x)), "x*asin(x) + sqrt(1 - x^2)")
  expect_equal(mi_fmt(integrate(acos(x), x)), "x*acos(x) - sqrt(1 - x^2)")
  expect_equal(mi_fmt(integrate(log(x)/x^2, x)), "-log(x)/x - 1/x")
  expect_equal(mi_fmt(integrate(x/(x^2 - 1), x)), "log(x^2 - 1)/2")
  expect_equal(mi_fmt(integrate(1/(x^2 - 1), x)), "log(x - 1)/2 - log(x + 1)/2")
  expect_equal(mi_fmt(integrate(1/(x^3 + 1), x)), "log(x + 1)/3 - log(x^2 - x + 1)/6 + sqrt(3)*atan(2*sqrt(3)*x/3 - sqrt(3)/3)/3")
  expect_equal(mi_fmt(integrate(exp(2*x)*cos(3*x), x)), "3*exp(2*x)*sin(3*x)/13 + 2*exp(2*x)*cos(3*x)/13")
  expect_equal(mi_fmt(integrate(x^3*exp(-x^2), x)), "(-x^2 - 1)*exp(-x^2)/2")
  expect_equal(mi_fmt(integrate(1/(1 + exp(x)), x)), "x - log(exp(x) + 1)")
  expect_equal(mi_fmt(integrate(exp(x)/(1 + exp(2*x)), x)), "RootSum(4*w^2 + 1, Lambda(w, w*log(2*w + exp(x))))")
  expect_equal(mi_fmt(integrate(sqrt(1 + x), x)), "2*(x + 1)^(3/2)/3")
  expect_equal(mi_fmt(integrate(1/sqrt(1 - x^2), x)), "asin(x)")
  expect_equal(mi_fmt(integrate(1/sqrt(1 + x^2), x)), "asinh(x)")
  expect_equal(mi_fmt(integrate(x/sqrt(1 + x^2), x)), "sqrt(x^2 + 1)")
  expect_equal(mi_fmt(integrate(x^2/sqrt(1 - x^2), x)), "-x*sqrt(1 - x^2)/2 + asin(x)/2")
  expect_equal(mi_fmt(integrate(sqrt(1 + x^2), x)), "x*sqrt(x^2 + 1)/2 + asinh(x)/2")
  expect_equal(mi_fmt(integrate(1/(x*(1 + x)), x)), "log(x) - log(x + 1)")
  expect_equal(mi_fmt(integrate(log(1 + x^2), x)), "x*log(x^2 + 1) - 2*x + 2*atan(x)")
  expect_equal(mi_fmt(integrate(x*atan(x), x)), "x^2*atan(x)/2 - x/2 + atan(x)/2")
  expect_equal(mi_fmt(integrate(exp(x)*sin(x)*cos(x), x)), "exp(x)*sin(x)^2/5 + exp(x)*sin(x)*cos(x)/5 - exp(x)*cos(x)^2/5")
  expect_equal(mi_fmt(integrate(cos(x)/(1 + sin(x)), x)), "log(sin(x) + 1)")
  expect_equal(mi_fmt(integrate(1/(2 + cos(x)), x)), "2*sqrt(3)*atan(sqrt(3)*tan(x/2)/3)/3")
  expect_equal(mi_fmt(integrate(sin(x)*cos(2*x), x)), "2*sin(x)*sin(2*x)/3 + cos(x)*cos(2*x)/3")
  expect_equal(mi_fmt(integrate(x^5*exp(x^3), x)), "(x^3 - 1)*exp(x^3)/3")
  expect_equal(mi_fmt(integrate(exp(sqrt(x)), x)), "2*sqrt(x)*exp(sqrt(x)) - 2*exp(sqrt(x))")
  expect_equal(mi_fmt(integrate(sin(log(x)), x)), "x*sin(log(x))/2 - x*cos(log(x))/2")
  expect_equal(mi_fmt(integrate(x*sin(x)*cos(x), x)), "x*sin(x)^2/4 - x*cos(x)^2/4 + sin(x)*cos(x)/4")
  expect_equal(mi_fmt(integrate(log(log(x))/x, x)), "log(x)*log(log(x)) - log(x)")
  expect_equal(mi_fmt(integrate(exp(x)*(x + 1), x)), "x*exp(x)")
})
