x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z")
s <- function(e) sstr(e)

test_that("integer helpers match SymPy", {
  expect_equal(igcd(12, 18, -8), 2)
  expect_equal(ilcm(4, 6, -10), 60)
  expect_equal(ilcm(0, 5), 0)
  expect_equal(mod_inverse(-3, 11), 7)
  expect_error(mod_inverse(2, 4), "does not exist")
  expect_equal(s(mod_inverse(Rational(2, 3), 7)), "3/2")
  expect_equal(integer_nthroot(26, 3), list(root = 2, exact = FALSE))
  expect_equal(integer_log(125, 5), list(e = 3, exact = TRUE))
  expect_equal(trailing(-8), 3)
  expect_equal(num_digits(255, 16), 2)
  expect_equal(num_digits(0), 1)
  expect_equal(ntt(c(1, 2, 3, 5), 769), c(11, 581, 766, 184))
  expect_equal(intt(c(11, 768, 9, 762), 769), c(3, 292, 7, 478))
  expect_equal(ntt(c(1, 2, 3), 17), c(6, 7, 2, 6))
})

test_that("factor_terms and gcd_terms match SymPy", {
  expect_equal(s(factor_terms(3*x^2*y + 6*x*y^2)), "3*x*y*(x + 2*y)")
  expect_equal(s(factor_terms(-2*x - 4)), "-2*(x + 2)")
  expect_equal(s(factor_terms(x/2 + y/3)), "(3*x + 2*y)/6")
  expect_equal(s(factor_terms(x^Rational(3, 2) + sqrt(x))), "sqrt(x)*(x + 1)")
  expect_equal(s(factor_terms(x^Rational(3, 2)*y + x*y)), "y*(x^(3/2) + x)")
  expect_equal(s(factor_terms(1/x + 1/x^2)), "(1 + 1/x)/x")
  expect_equal(s(factor_terms(x*(y*z + y*x) + 2*x)), "x*(y*(x + z) + 2)")
  expect_equal(s(factor_terms(sin(2*x + 2*y))), "sin(2*(x + y))")
  expect_equal(s(gcd_terms(x/2 + 1/x)), "(x^2 + 2)/(2*x)")
  expect_equal(s(gcd_terms((x + 1)^2*y + (x + 1)*y^2)), "y*(x + 1)*(x + y + 1)")
  expect_equal(s(gcd_terms(x + 1/y)), "(x*y + 1)/y")
})

test_that("bool_map and UnevaluatedExpr", {
  a <- Symbol("a"); b <- Symbol("b")
  m <- bool_map(Or(And(a, b), Not(a)), Or(And(x, y), Not(x)))
  expect_equal(vapply(m$mapping, s, ""), c(a = "x", b = "y"))
  expect_false(bool_map(Xor(a, b), Or(a, b)))
  e <- x * UnevaluatedExpr(1 / x)
  expect_equal(s(e), "x*1/x")
  expect_equal(s(doit(e)), "1")
})
