# Expected values are SymPy's outputs for the same calls (subs, expand and core evaluation).

skip_on_cran()

x <- Symbol("x"); y <- Symbol("y"); z <- Symbol("z"); t <- Symbol("t"); u <- Symbol("u"); a <- Symbol("a"); b <- Symbol("b"); c <- Symbol("c"); p <- Symbol("p", positive = TRUE); A <- Symbol("A", commutative = FALSE); f <- Function("f")
mi_fmt <- function(v) if (is.null(v)) "None" else gsub("\n", " ", sstr(v))

test_that("subs, expand and core evaluation match SymPy", {
  expect_equal(mi_fmt(subs(-2*t-1, 2*t+2, u)), "1 - u")
  expect_equal(mi_fmt(subs(x^4, x^2, y)), "y^2")
  expect_equal(mi_fmt(subs(exp(2*x), exp(x), y)), "y^2")
  expect_equal(mi_fmt(subs(2*x*y, x*y, u)), "2*u")
  expect_equal(mi_fmt(subs(x^2*y, x*y, u)), "u*x")
  expect_equal(mi_fmt(subs(x - 1, 1, y)), "x - y")
  expect_equal(mi_fmt(subs(4^x, 2^x, y)), "y^2")
  expect_equal(mi_fmt(subs(exp(x + 2), exp(x), y)), "y*exp(2)")
  expect_equal(mi_fmt(subs(6*x*y, 2*x, u)), "3*u*y")
  expect_equal(mi_fmt(subs(x^3*exp(x), x^2, y)), "x^3*exp(x)")
  expect_equal(mi_fmt(subs(x, x^2, y)), "x")
  expect_equal(mi_fmt(subs(x + 1/x, 1/x, y)), "y + 1/y")
  expect_equal(mi_fmt(subs(x, sqrt(x), y)), "y^2")
  expect_equal(mi_fmt(subs(a + b + c, b + c, x)), "a + x")
  expect_equal(mi_fmt(subs(a + b + c, -b - c, x)), "a - x")
  expect_equal(mi_fmt(subs(2 + a, 3 + a, y)), "y - 1")
  expect_equal(mi_fmt(subs(x*y*z, x*y, 2)), "2*z")
  expect_equal(mi_fmt(subs(x^6, x^4, y)), "x^6")
  expect_equal(mi_fmt(subs(exp(3*x + 1), exp(x), y)), "E*y^3")
  expect_equal(mi_fmt(subs(2^(2*x), 2^x, y)), "y^2")
  expect_equal(mi_fmt(subs(Derivative(f(x), x), x, 0)), "Subs(Derivative(f(x), x), x, 0)")
  expect_equal(mi_fmt(subs(Derivative(f(x, y), x), y, 2)), "Derivative(f(x, 2), x)")
  expect_equal(mi_fmt(subs(Derivative(f(x), list(x, 2)), x, 0)), "Subs(Derivative(f(x), (x, 2)), x, 0)")
  expect_equal(mi_fmt(subs(Derivative(f(x), x), f(x), y)), "Derivative(y, x)")
  expect_equal(mi_fmt(expand((x + 1)*(x + 2) + 1, deep = FALSE)), "(x + 1)*(x + 2) + 1")
  expect_equal(mi_fmt(expand(sin(x*(y + 1))*(x + 1), deep = FALSE)), "x*sin(x*(y + 1)) + sin(x*(y + 1))")
  expect_equal(mi_fmt(expand(Integral((x + 1)^2, x))), "Integral(1, x) + Integral(2*x, x) + Integral(x^2, x)")
  expect_equal(mi_fmt(expand(exp(x + y)*(x + 1)^2)), "x^2*exp(x)*exp(y) + 2*x*exp(x)*exp(y) + exp(x)*exp(y)")
  expect_equal(mi_fmt(expand(log(as_sym(4)/9))), "-2*log(3) + 2*log(2)")
  expect_equal(mi_fmt(expand(log(-2*x))), "log(-x) + log(2)")
  expect_equal(mi_fmt(expand(log(p*(y + z)))), "log(p) + log(y + z)")
  expect_equal(mi_fmt(expand(x*(x + 1)^2)), "x^3 + 2*x^2 + x")
  expect_equal(mi_fmt(expand_trig(sin(x + y + z))), "(-sin(y)*sin(z) + cos(y)*cos(z))*sin(x) + (sin(y)*cos(z) + sin(z)*cos(y))*cos(x)")
  expect_equal(mi_fmt(expand_trig(cos(3*x))), "4*cos(x)^3 - 3*cos(x)")
  expect_equal(mi_fmt(expand_trig(sin(4*x))), "-8*sin(x)^3*cos(x) + 4*sin(x)*cos(x)")
  expect_equal(mi_fmt(expand_trig(tan(x + y))), "(tan(x) + tan(y))/(-tan(x)*tan(y) + 1)")
  expect_equal(mi_fmt(expand_trig(tan(3*x))), "(-tan(x)^3 + 3*tan(x))/(1 - 3*tan(x)^2)")
  expect_equal(mi_fmt(expand_trig(sinh(2*x))), "2*sinh(x)*cosh(x)")
  expect_equal(mi_fmt(expand_trig(cosh(x + y))), "sinh(x)*sinh(y) + cosh(x)*cosh(y)")
  expect_equal(mi_fmt(expand_trig(tanh(2*x))), "2*tanh(x)/(tanh(x)^2 + 1)")
  expect_equal(mi_fmt(expand_trig(sec(2*x))), "1/(2*cos(x)^2 - 1)")
  expect_equal(mi_fmt(expand_trig(cot(x + y))), "(cot(x)*cot(y) - 1)/(cot(x) + cot(y))")
  expect_equal(mi_fmt(expand_trig(coth(2*x))), "(coth(x)^2 + 1)/(2*coth(x))")
  expect_equal(mi_fmt(expand_log(log(as_sym(8))/log(as_sym(2)))), "3")
  expect_equal(mi_fmt(expand_log(log(as_sym(12))/log(as_sym(3)))), "1 + 2*log(2)/log(3)")
  expect_equal(mi_fmt(expand_log(log(as_sym(12)))), "log(12)")
  expect_equal(mi_fmt(expand((x + 1)^(as_sym(5)/2))), "x^2*sqrt(x + 1) + 2*x*sqrt(x + 1) + sqrt(x + 1)")
  expect_equal(mi_fmt(expand((x + 1)^(-as_sym(5)/2))), "1/(x^2*sqrt(x + 1) + 2*x*sqrt(x + 1) + sqrt(x + 1))")
  expect_equal(mi_fmt(expand(2^(x + 3))), "8*2^x")
  expect_equal(mi_fmt(expand((x + y)^3*(x - y))), "x^4 + 2*x^3*y - 2*x*y^3 - y^4")
  expect_equal(mi_fmt(expand_mul((x + 1)*(y + (z + 1)*(x + 2)))), "x^2*z + x^2 + x*y + 3*x*z + 3*x + y + 2*z + 2")
  expect_equal(mi_fmt(expand(((x + 1)*(x + 2))^2)), "x^4 + 6*x^3 + 13*x^2 + 12*x + 4")
  expect_equal(mi_fmt(expand_power_exp(A^(x + y))), "A^x*A^y")
  expect_equal(mi_fmt(expand_power_base((x*y)^z, force = TRUE)), "x^z*y^z")
  expect_equal(mi_fmt(expand_complex(exp(x))), "I*exp(re(x))*sin(im(x)) + exp(re(x))*cos(im(x))")
  expect_equal(mi_fmt(expand((1 + sym_I)^5)), "-4 - 4*I")
  expect_equal(mi_fmt(log(1 + sym_I)), "log(sqrt(2)) + I*pi/4")
  expect_equal(mi_fmt(log(-1 + sym_I)), "log(sqrt(2)) + 3*I*pi/4")
  expect_equal(mi_fmt(log(2 - 2*sym_I)), "log(2*sqrt(2)) - I*pi/4")
  expect_equal(mi_fmt(log(sqrt(as_sym(3)) + sym_I)), "log(2) + I*pi/6")
  expect_equal(mi_fmt(1/sqrt(sym_I)), "-I^(3/2)")
  expect_equal(mi_fmt(sym_I^(as_sym(5)/2)), "-sqrt(I)")
  expect_equal(mi_fmt(2/sqrt(sym_I)), "-2*I^(3/2)")
  expect_equal(mi_fmt(Intersection(Interval(-as_sym(1)/4, as_sym(1)/4), Integers)), "Range(0, 1, 1)")
  expect_equal(mi_fmt(Intersection(Interval(0, 10, TRUE, TRUE), Naturals)), "Range(1, 10, 1)")
  expect_equal(mi_fmt(solveset(cos(x), x, domain = Interval(0, S_Pi))), "{pi/2}")
})
