# Expected values are SymPy's outputs for the same calls (ratint).

skip_unless_full_tests()

skip_on_cran()

x <- Symbol("x"); a <- Symbol("a"); b <- Symbol("b"); c <- Symbol("c"); t <- Symbol("t")
ap <- Symbol("ap", positive = TRUE); bp <- Symbol("bp", positive = TRUE); cp <- Symbol("cp", positive = TRUE)
k <- Symbol("k", real = TRUE); a0 <- Symbol("a0", real = TRUE)
mi_fmt <- function(v) if (is.null(v)) "None" else gsub("\n", " ", sstr(v))

test_that("ratint match SymPy", {
  expect_equal(mi_fmt(ratint(S_Zero, x)), "0")
  expect_equal(mi_fmt(ratint(Integer(7), x)), "7*x")
  expect_equal(mi_fmt(ratint(x, x)), "x^2/2")
  expect_equal(mi_fmt(ratint(8*x^7 + 2*x + 1, x)), "x^8 + x^2 + x")
  expect_equal(mi_fmt(ratint(1/(x + 1), x)), "log(x + 1)")
  expect_equal(mi_fmt(ratint((x^3 - x)/(x - 1), x)), "x^3/3 + x^2/2")
  expect_equal(mi_fmt(ratint(x/((x - a)*(x + a)), x)), "log(-a^2 + x^2)/2")
  expect_equal(mi_fmt(ratint(1/(x^2 + 1), x, real = FALSE)), "-I*log(x - I)/2 + I*log(x + I)/2")
  expect_equal(mi_fmt(ratint((x^4 - 3*x^2 + 6)/(x^6 - 5*x^4 + 5*x^2 + 4), x)), "atan(x) + atan(x^3) + atan(x^5/2 - 3*x^3/2 + x/2)")
  expect_equal(mi_fmt(ratint((x^7 - 24*x^4 - 4*x^2 + 8*x - 8)/(x^8 + 6*x^6 + 12*x^4 + 8*x^2), x)), "log(x) + (3*x^3 + 8*x^2 + 6*x + 4)/(x^5 + 4*x^3 + 4*x)")
  expect_equal(mi_fmt(ratint((x^3*(x^7 - 24*x^4 - 4*x^2 + 8*x - 8))/(x*(x^8 + 6*x^6 + 12*x^4 + 8*x^2)), x)), "x^2/2 - 3*log(x^2 + 2) - 5*sqrt(2)*atan(sqrt(2)*x/2) + (14*x^3 - 6*x^2 + 16*x - 12)/(x^4 + 4*x^2 + 4)")
  expect_equal(mi_fmt(ratint((x^5 - x^4 + 4*x^3 + x^2 - x + 5)/(x^4 - 2*x^3 + 5*x^2 - 4*x + 4), x)), "x^2/2 + x + (9 - 4*x)/(7*x^2 - 7*x + 14) + log(x^2 - x + 2)/2 + 13*sqrt(7)*atan(2*sqrt(7)*x/7 - sqrt(7)/7)/49")
  expect_equal(mi_fmt(ratint(1/(x^2 + x + 1), x)), "2*sqrt(3)*atan(2*sqrt(3)*x/3 + sqrt(3)/3)/3")
  expect_equal(mi_fmt(ratint(1/(x^2 + x + 1), x, real = FALSE)), "-sqrt(3)*I*log(x + 1/2 - sqrt(3)*I/2)/3 + sqrt(3)*I*log(x + 1/2 + sqrt(3)*I/2)/3")
  expect_equal(mi_fmt(ratint(1/(x^3 + 1), x, real = FALSE)), "log(x + 1)/3 + (-1/6 - sqrt(3)*I/6)*log(x - 1/2 - sqrt(3)*I/2) + (-1/6 + sqrt(3)*I/6)*log(x - 1/2 + sqrt(3)*I/2)")
  expect_equal(mi_fmt(ratint(1/(x*(a + b*x)^3), x)), "(3*a + 2*b*x)/(2*a^4 + 4*a^3*b*x + 2*a^2*b^2*x^2) + (log(x) - log(a/b + x))/a^3")
  expect_equal(mi_fmt(ratint(x/(1 - x^2), x)), "-log(x^2 - 1)/2")
  expect_equal(mi_fmt(ratint(-x/(1 - x^2), x)), "log(x^2 - 1)/2")
  expect_equal(mi_fmt(ratint(diff(x/4 - 4/(1 - x), x), x)), "x/4 + 4/(x - 1)")
  expect_equal(mi_fmt(ratint(1/(x^2 + 16), x)), "atan(x/4)/4")
  expect_equal(mi_fmt(ratint(1/(x^2 + a^2), x)), "(-I*log(-I*a + x)/2 + I*log(I*a + x)/2)/a")
  expect_equal(mi_fmt(ratint((2*x + 1)/(x^2 + x + 1) + 1/x, x)), "log(x^3 + x^2 + x)")
  expect_equal(mi_fmt(ratint((4*x + 7)/(x^2 + 4*x + 6) + 2/x, x)), "2*log(x) + 2*log(x^2 + 4*x + 6) - sqrt(2)*atan(sqrt(2)*x/2 + sqrt(2))/2")
  expect_equal(mi_fmt(ratint(1/(a*x^2 + b*x + c), x)), "-sqrt(-1/(4*a*c - b^2))*log(x + (-4*a*c*sqrt(-1/(4*a*c - b^2)) + b^2*sqrt(-1/(4*a*c - b^2)) + b)/(2*a)) + sqrt(-1/(4*a*c - b^2))*log(x + (4*a*c*sqrt(-1/(4*a*c - b^2)) - b^2*sqrt(-1/(4*a*c - b^2)) + b)/(2*a))")
  expect_equal(mi_fmt(ratint(1/(x^4 - 1), x)), "log(x - 1)/4 - log(x + 1)/4 - atan(x)/2")
  expect_equal(mi_fmt(ratint(1/(x^6 + 1), x)), "-sqrt(3)*log(x^2 - sqrt(3)*x + 1)/12 + sqrt(3)*log(x^2 + sqrt(3)*x + 1)/12 + atan(x)/3 + atan(2*x - sqrt(3))/6 + atan(2*x + sqrt(3))/6")
  expect_equal(mi_fmt(ratint(x^3/(x^2 + 3*x + 2), x)), "x^2/2 - 3*x - log(x + 1) + 8*log(x + 2)")
  expect_equal(mi_fmt(ratint(1/(x^2 - 2), x)), "sqrt(2)*log(x - sqrt(2))/4 - sqrt(2)*log(x + sqrt(2))/4")
  expect_equal(mi_fmt(ratint(1/(x^3 - 2), x)), "2^(1/3)*log(x - 2^(1/3))/6 - 2^(1/3)*log(x^2 + 2^(1/3)*x + 2^(2/3))/12 - 2^(1/3)*sqrt(3)*atan(2^(2/3)*sqrt(3)*x/3 + sqrt(3)/3)/6")
  expect_equal(mi_fmt(ratint(1/(x^5 + 1), x)), "log(x + 1)/5 + (-1/20 + sqrt(5)/20)*log(x^2 + x*(-1/2 + sqrt(5)/2) + 1) + (-sqrt(5)/20 - 1/20)*log(x^2 + x*(-sqrt(5)/2 - 1/2) + 1) - 2*sqrt(5/8 - sqrt(5)/8)*atan(-2*sqrt(2)*x/sqrt(5 - sqrt(5)) + sqrt(2)/(2*sqrt(5 - sqrt(5))) + sqrt(10)/(2*sqrt(5 - sqrt(5))))/5 + 2*sqrt(sqrt(5)/8 + 5/8)*atan(2*sqrt(2)*x/sqrt(sqrt(5) + 5) - sqrt(2)/(2*sqrt(sqrt(5) + 5)) + sqrt(10)/(2*sqrt(sqrt(5) + 5)))/5")
  expect_equal(mi_fmt(ratint((x + 1)/(x^2 + 1)^2, x)), "(x - 1)/(2*x^2 + 2) + atan(x)/2")
  expect_equal(mi_fmt(ratint(1/(x^2 + 1)^3, x)), "(3*x^3 + 5*x)/(8*x^4 + 16*x^2 + 8) + 3*atan(x)/8")
  expect_equal(mi_fmt(ratint(x^2/(x^4 + 1), x)), "sqrt(2)*log(x^2 - sqrt(2)*x + 1)/8 - sqrt(2)*log(x^2 + sqrt(2)*x + 1)/8 + sqrt(2)*atan(sqrt(2)*x - 1)/4 + sqrt(2)*atan(sqrt(2)*x + 1)/4")
  expect_equal(mi_fmt(ratint(1/(3*x^2 + 2), x)), "sqrt(6)*atan(sqrt(6)*x/2)/6")
  expect_equal(mi_fmt(ratint(1/(x*(x + 1)*(x + 2)), x)), "-log(x + 1) + log(x^2 + 2*x)/2")
  expect_equal(mi_fmt(ratint((3*x^2 + 2)/(x^3 + 2*x + 5), x)), "log(x^3 + 2*x + 5)")
  expect_equal(mi_fmt(ratint(x/(x^2 + a), x)), "log(a + x^2)/2")
  expect_equal(mi_fmt(ratint(1/(x - a), x)), "log(-a + x)")
  expect_equal(mi_fmt(ratint(1/(x - a)^2, x)), "-1/(-a + x)")
  expect_equal(mi_fmt(ratint(1/((x - a)*(x - b)), x)), "log(-a^2/(2*(a - b)) + a*b/(a - b) - a/2 - b^2/(2*(a - b)) - b/2 + x)/(a - b) - log(a^2/(2*(a - b)) - a*b/(a - b) - a/2 + b^2/(2*(a - b)) - b/2 + x)/(a - b)")
  expect_equal(mi_fmt(ratint(1/(x^2 + 2*x + 5), x)), "atan(x/2 + 1/2)/2")
  expect_equal(mi_fmt(ratint(x/(x^2 + 2*x + 5), x)), "log(x^2 + 2*x + 5)/2 - atan(x/2 + 1/2)/2")
  expect_equal(mi_fmt(ratint(1/(x^2 + 1)/(x^2 + 4), x)), "-atan(x/2)/6 + atan(x)/3")
  expect_equal(mi_fmt(ratint(sym_I/(x^2 + 1), x)), "log(x - I)/2 - log(x + I)/2")
  expect_equal(mi_fmt(ratint(1/(x^2 + k^2 + 1), x)), "atan(x/sqrt(k^2 + 1))/sqrt(k^2 + 1)")
  expect_equal(mi_fmt(ratint((x^2 + 1 - k^2)/(x^2 + 1 + a0^2), x)), "x - (a0^2 + k^2)*atan(x/sqrt(a0^2 + 1))/sqrt(a0^2 + 1)")
  expect_equal(mi_fmt(ratint(Rational(1, 2)/(x^2 + 3), x)), "sqrt(3)*atan(sqrt(3)*x/3)/6")
  expect_equal(mi_fmt(ratint((x + Rational(1, 3))/(2*x^2 - 3), x)), "(sqrt(6)/36 + 1/4)*log(x - sqrt(6)/2) + (1/4 - sqrt(6)/36)*log(x + sqrt(6)/2)")
  expect_equal(mi_fmt(ratint(1/(x^4 + x^2 + 1), x)), "-log(x^2 - x + 1)/4 + log(x^2 + x + 1)/4 + sqrt(3)*atan(2*sqrt(3)*x/3 - sqrt(3)/3)/6 + sqrt(3)*atan(2*sqrt(3)*x/3 + sqrt(3)/3)/6")
  expect_equal(mi_fmt(ratint(1/(x^3 - x^2 - x + 1), x)), "-log(x - 1)/4 + log(x + 1)/4 - 1/(2*x - 2)")
  expect_equal(mi_fmt(ratint((x^4 + 1)/(x^3 + x), x)), "x^2/2 + log(x) - log(x^2 + 1)")
  expect_equal(mi_fmt(ratint(x^2/(x - 1)^3, x)), "(3 - 4*x)/(2*x^2 - 4*x + 2) + log(x - 1)")
  expect_equal(mi_fmt(ratint(1/(x^2*(x^2 + 1)), x)), "-atan(x) - 1/x")
})
