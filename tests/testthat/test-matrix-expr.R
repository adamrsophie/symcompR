# Reference values from SymPy.
n <- Symbol("n")
A <- MatrixSymbol("A", 2, 2); B <- MatrixSymbol("B", 2, 2); C <- MatrixSymbol("C", 2, 3)
X <- MatrixSymbol("X", n, n); Y <- MatrixSymbol("Y", n, n); v <- MatrixSymbol("v", 3, 1)

test_that("MatAdd, MatMul and MatPow canonicalize like SymPy", {
  expect_equal(sstr(A*B), "A*B")
  expect_equal(sstr(A + A), "2*A")
  expect_equal(sstr(A*Identity(2)), "A")
  expect_equal(sstr(A + ZeroMatrix(2, 2)), "A")
  expect_equal(sstr(A*ZeroMatrix(2, 2)), "0")
  expect_equal(sstr(A^-1), "A^(-1)")
  expect_equal(sstr(A^-1*A), "I")
  expect_equal(sstr(A^2*A), "A^3")
  expect_equal(sstr(X + Y + X), "2*X + Y")
  expect_equal(sstr(A - 2*B), "A - 2*B")
  expect_equal(sstr(A*B - A*B), "0")
  expect_equal(sstr(A/2), "(1/2)*A")
  expect_equal(sstr(-2*A*B), "-2*A*B")
  expect_equal(sstr((A + B)*A), "(A + B)*A")
  expect_equal(sstr((X^2)^3), "X^6")
  expect_equal(sstr(X^0), "I")
  expect_error(C*A, "ShapeError")
  expect_equal(vapply(mat_shape(A*C), sstr, ""), c("2", "3"))
})

test_that("transpose, inverse, trace and determinant rules", {
  expect_equal(sstr(t(A*B)), "B.T*A.T")
  expect_equal(sstr(t(A + B)), "A.T + B.T")
  expect_equal(sstr(t(2*A)), "2*A.T")
  expect_equal(sstr(t(A)*t(B) + t(B*A)), "2*A.T*B.T")
  expect_equal(sstr(Transpose(A*B)), "(A*B).T")
  expect_equal(sstr(Transpose(Transpose(X))), "X.T.T")
  expect_equal(sstr(t(t(X))), "X")
  expect_equal(sstr(Inverse(A*B)), "(A*B)^(-1)")
  expect_equal(sstr(Inverse(Inverse(X))), "(X^(-1))^(-1)")
  expect_equal(sstr(doit(Trace(A + B))), "Trace(A) + Trace(B)")
  expect_equal(sstr(doit(Trace(2*A))), "2*Trace(A)")
  expect_equal(sstr(sym_det(A*B)), "Determinant(A)*Determinant(B)")
  expect_equal(sstr(doit(Determinant(2*A))), "4*Determinant(A)")
  expect_equal(sstr(sym_det(A^-1)), "1/Determinant(A)")
  expect_equal(sstr(doit(Determinant(Identity(3)))), "1")
})

test_that("explicit forms, elements and block matrices", {
  expect_equal(sstr(MatrixElement(A*B, 0, 1)), "A[0, 0]*B[0, 1] + A[0, 1]*B[1, 1]")
  expect_equal(sstr(MatrixElement(Inverse(A), 0, 0)), "A[1, 1]/(A[0, 0]*A[1, 1] - A[0, 1]*A[1, 0])")
  E <- as_explicit(A*B)
  expect_equal(sstr(.mget(E, 2L, 1L)), "A[1, 0]*B[0, 0] + A[1, 1]*B[1, 0]")
  expect_equal(sstr(block_collapse(BlockMatrix(list(list(A, B), list(B, A))) * BlockMatrix(list(list(A), list(B))))),
               "Matrix([\n[A^2 + B^2],\n[A*B + B*A]])")
  expect_equal(sstr(block_collapse(t(BlockMatrix(list(list(A, B), list(B, A)))))), "Matrix([\n[A.T, B.T],\n[B.T, A.T]])")
  expect_equal(sstr(BlockDiagMatrix(A, B)), "Matrix([\n[A, 0],\n[0, B]])")
  expect_equal(vapply(mat_shape(BlockMatrix(list(list(A, B)))), sstr, ""), c("2", "4"))
  i <- Symbol("i"); j <- Symbol("j")
  expect_equal(vapply(as_explicit(FunctionMatrix(2, 2, Lambda(list(i, j), i + j)))$data, sstr, ""), c("0", "1", "1", "2"))
  expect_equal(vapply(as_explicit(DiagMatrix(v))$data[c(1, 5, 9)], sstr, ""), c("v[0, 0]", "v[1, 0]", "v[2, 0]"))
  expect_equal(vapply(matrix_symbols(A*B + X), sstr, ""), c("A", "B", "X"))
  expect_equal(latex(A*t(B)), "A B^{T}")
  expect_equal(latex(Trace(A)), "\\operatorname{tr}\\left(A \\right)")
  expect_equal(latex(MatrixElement(A, 0, 1)), "{A}_{0,1}")
})

test_that("explicit matrix builders", {
  expect_equal(sstr(sym_trace(Matrix(list(list(1, 2), list(3, 4))))), "5")
  expect_equal(vapply(banded(3, list("0" = 1, "1" = 2))$data, sstr, ""), c("1", "2", "0", "0", "1", "2", "0", "0", "1"))
  b <- banded(list("0" = 1, "-1" = c(2, 3)))
  expect_equal(c(b$nrow, b$ncol), c(3L, 2L))
  expect_equal(vapply(rot_givens(0, 1, S_Pi/3)$data[1:2], sstr, ""), c("1/2", "sqrt(3)/2"))
  expect_equal(vapply(SparseMatrix(2, 2, list(list(0, 0, 1), list(1, 1, 5)))$data, sstr, ""), c("1", "0", "0", "5"))
  expect_equal(sstr(Permanent(Matrix(list(list(1, 2), list(3, 4))))), "10")
})

test_that("p12 review fixes for matrix expressions", {
  R1 <- MatrixSymbol("R", 2, 3); R2 <- MatrixSymbol("S", 3, 2)
  expect_equal(sstr(doit(Determinant(R1*R2))), "Determinant(R*S)")
  expect_equal(sstr(doit(Inverse(R1*R2))), "(R*S)^(-1)")
  E <- as_explicit(block_collapse(BlockMatrix(list(list(Identity(2)))) + BlockDiagMatrix(Identity(1), Identity(1))))
  expect_equal(vapply(E$data, sstr, ""), c("2", "0", "0", "2"))
  expect_equal(vapply(banded(2, list("0" = Symbol("x")))$data, sstr, ""), c("x", "0", "0", "x"))
  expect_equal(vapply(doit(Transpose(Matrix(list(list(1, 2), list(3, 4)))))$data, sstr, ""), c("1", "3", "2", "4"))
  nz <- Symbol("n", integer = TRUE, positive = TRUE)
  expect_equal(sstr(doit(Permanent(MatrixSymbol("A", nz, nz)))), "Permanent(A)")
})

test_that("p13 h2 fixes: block partitions, identity blocks, explicit blocks", {
  A <- MatrixSymbol("A", 2, 2); B <- MatrixSymbol("B", 1, 1); C <- MatrixSymbol("C", 1, 1)
  expect_equal(sstr(block_collapse(BlockMatrix(list(list(Identity(2)))) * BlockDiagMatrix(Identity(1), Identity(1)))), "I")
  expect_equal(sstr(block_collapse(BlockMatrix(list(list(A))) * BlockDiagMatrix(B, C))),
               "Matrix([[A]])*Matrix([\n[B, 0],\n[0, C]])")
  expect_equal(sstr(BlockMatrix(list(list(A)))), "Matrix([[A]])")
  expect_equal(capture.output(print(as_explicit(BlockDiagMatrix(Matrix(list(list(1))))))),
               capture.output(print(Matrix(list(list(1))))))
  expect_equal(sstr(block_collapse(BlockMatrix(list(list(A, A))) * BlockMatrix(list(list(A), list(A))))), "2*A^2")
})

test_that("MatrixSlice and blockcut follow SymPy", {
  X <- MatrixSymbol("X", 4, 4); n <- Symbol("n"); Y <- MatrixSymbol("Y", n, n)
  shp <- function(e) vapply(mat_shape(e), sstr, "")
  expect_equal(sstr(MatrixSlice(X, c(0, 2), c(1, 3))), "X[:2, 1:3]")
  expect_equal(sstr(MatrixSlice(X, c(NA, NA, 2), c(NA, NA))), "X[::2, :]")
  expect_equal(sstr(MatrixSlice(X, 1, c(NA, NA))), "X[1:2, :]")
  expect_equal(sstr(MatrixSlice(X, c(NA, NA), 2)), "X[:, 2:3]")
  expect_equal(sstr(MatrixSlice(MatrixSlice(X, c(0, 2), c(0, 2)), c(1, NA), c(NA, NA))), "X[1:2, :2]")
  expect_equal(shp(MatrixSlice(X, c(0, 4, 2), c(1, 4, 2))), c("2", "2"))
  expect_equal(shp(MatrixSlice(Y, c(1, NA), c(NA, NA))), c("n - 1", "n"))
  expect_equal(latex(MatrixSlice(X, c(0, 2), c(1, 3))), "X\\left[:2, 1:3\\right]")
  expect_equal(sstr(blockcut(X, c(1, 3), c(2, 2))), "Matrix([\n[X[:1, :2], X[:1, 2:]],\n[X[1:, :2], X[1:, 2:]]])")
  E <- as_explicit(MatrixSlice(X, c(0, 2), c(1, 3)))
  expect_equal(sstr(.mget(E, 2L, 2L)), "X[1, 2]")
  expect_error(MatrixSlice(X, c(0, 5), c(0, 1)), "IndexError")
})
