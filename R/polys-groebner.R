# Groebner bases by Buchberger's algorithm with Gebauer-Moeller criteria,
# after sympy/polys/groebnertools.py.

.lcm_mono <- function(a, b) pmax(a, b)

.spoly <- function(f, g) {
  lf <- qp_lm(f)
  lg <- qp_lm(g)
  l <- .lcm_mono(lf, lg)
  a <- qp_mul_term(f, l - lf, 1 / qp_lc(f))
  b <- qp_mul_term(g, l - lg, 1 / qp_lc(g))
  qp_sub(a, b)
}

# Reduce G to a reduced Groebner basis.
.reduce_basis <- function(G) {
  G <- lapply(G, qp_monic)
  # drop polynomials whose leading monomial is divisible by another's
  keep <- rep(TRUE, length(G))
  for (i in seq_along(G)) for (j in seq_along(G)) {
    if (i != j && keep[i] && keep[j] && .mono_divides(qp_lm(G[[j]]), qp_lm(G[[i]]))) {
      if (!all(qp_lm(G[[j]]) == qp_lm(G[[i]])) || j < i) {
        keep[i] <- FALSE
      }
    }
  }
  G <- G[keep]
  out <- G
  for (i in seq_along(G)) {
    out[[i]] <- qp_monic(qp_rem_multi(G[[i]], G[-i]))
  }
  out <- Filter(Negate(qp_is_zero), out)
  ord <- order(vapply(out, function(p) paste(sprintf("%06d", 999999L - qp_lm(p)), collapse = ""), ""),
               decreasing = FALSE)
  out[ord]
}

# ponytail: plain Buchberger with the product criterion and normal pair
# selection; add Gebauer-Moeller or F4 if large systems become slow.
.groebner_qp <- function(F, order = "lex") {
  old <- .ORDER$current
  .ORDER$current <- order
  on.exit(.ORDER$current <- old)
  F <- lapply(F, qp_reorder, order = order)
  F <- Filter(Negate(qp_is_zero), lapply(F, qp_monic))
  if (!length(F)) return(list())
  n <- qp_nvars(F[[1L]])
  if (any(vapply(F, qp_is_const, TRUE))) return(list(qp_const(1, n)))
  G <- F[!duplicated(vapply(F, function(p) paste(.mono_keys(p$e), as.character(p$c), collapse = ";"), ""))]
  pairs <- list()
  add_pairs <- function(k) {
    if (k > 1L) for (i in seq_len(k - 1L)) {
      a <- qp_lm(G[[i]])
      b <- qp_lm(G[[k]])
      l <- pmax(a, b)
      if (all(l == a + b)) next
      pairs[[length(pairs) + 1L]] <<- list(i, k, sum(l))
    }
  }
  for (k in seq_along(G)) add_pairs(k)
  while (length(pairs)) {
    k <- which.min(vapply(pairs, `[[`, 0, 3L))
    pr <- pairs[[k]]
    pairs <- pairs[-k]
    h <- qp_rem_multi(.spoly(G[[pr[[1L]]]], G[[pr[[2L]]]]), G)
    if (qp_is_zero(h)) next
    h <- qp_monic(h)
    if (qp_is_const(h)) return(list(qp_const(1, n)))
    G[[length(G) + 1L]] <- h
    add_pairs(length(G))
  }
  .reduce_basis(G)
}

#' Groebner bases
#'
#' `groebner(F, gens, order)` computes the reduced Groebner basis of the ideal
#' generated by the polynomials `F`, with `"lex"`, `"grlex"` or `"grevlex"`
#' monomial order, like SymPy's `groebner()`. `is_zero_dimensional()` tests
#' whether the corresponding system has finitely many solutions.
#'
#' @param F A list of polynomial expressions.
#' @param ... Generators, in order.
#' @param order Monomial order.
#' @return A list of expressions.
#' @examples
#' x <- Symbol("x"); y <- Symbol("y")
#' groebner(list(x^2 + y^2 - 1, x - y), x, y)
#' @export
groebner <- function(F, ..., order = "lex") {
  F <- lapply(F, function(z) {
    z <- as_sym(z)
    if (is_relational(z)) .sub(z$args[[1L]], z$args[[2L]]) else z
  })
  gens <- .gens_of(F, list(...))
  cv <- .to_qpolys(F, gens)
  G <- .gb_sorted(.groebner_qp(cv$polys, order), order)
  out <- lapply(G, function(g) qpoly_to_expr(qp_primitive(g)$poly, cv$gens))
  structure(out, gens = cv$gens, order = order)
}

#' @rdname groebner
#' @export
is_zero_dimensional <- function(F, ...) {
  G <- groebner(F, ..., order = "grevlex")
  gens <- attr(G, "gens")
  cv <- .to_qpolys(G, gens)
  n <- length(gens)
  lms <- lapply(cv$polys, function(p) qp_lm(qp_reorder(p, "grevlex")))
  all(vapply(seq_len(n), function(j) any(vapply(lms, function(m) m[j] > 0 && sum(m) == m[j], TRUE)), TRUE))
}
