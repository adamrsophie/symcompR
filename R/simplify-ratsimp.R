# Rational simplification modulo a prime ideal, after ratsimpmodprime in
# sympy/simplify/ratsimp.py, with the linear solves of minsolve_linear_system
# in sympy/solvers/solvers.py, and trigsimp_groebner of
# sympy/simplify/trigsimp.py.

# solve_linear_system for equations linear in syms with rational
# coefficients: the reduced row echelon form, pivots in column order;
# list(sol = named list of pivot values, ok = consistent).
.lin_solve_rat <- function(eqs, syms) {
  n <- length(syms)
  qv <- function(z) {
    if (!(z$type %in% c("Integer", "Rational"))) stop("the linear system needs rational coefficients", call. = FALSE)
    as.character(z$value)
  }
  rows <- lapply(eqs, function(e) {
    e <- expand(e)
    cs <- lapply(syms, function(s) .expr_coeff(e, s))
    rest <- expand(.sub(e, .add(lapply(seq_len(n), function(j) .mul(list(cs[[j]], syms[[j]]))))))
    gmp::as.bigq(c(vapply(cs, qv, ""), qv(.neg(rest))))
  })
  if (!length(rows)) return(list(sol = list(), ok = TRUE, pivots = integer()))
  M <- do.call(rbind, lapply(rows, function(r) as.character(r)))
  A <- gmp::as.bigq(M); dim(A) <- dim(M)
  r <- 1L; piv <- integer()
  for (j in seq_len(n)) {
    if (r > nrow(A)) break
    k <- which(vapply(r:nrow(A), function(i) A[i, j] != 0, TRUE))
    if (!length(k)) next
    k <- r + k[1L] - 1L
    if (k != r) { tmp <- A[r, ]; A[r, ] <- A[k, ]; A[k, ] <- tmp }
    A[r, ] <- A[r, ] / A[r, j]
    for (i in seq_len(nrow(A))) if (i != r && A[i, j] != 0) A[i, ] <- A[i, ] - A[i, j] * A[r, ]
    piv <- c(piv, j); r <- r + 1L
  }
  if (r <= nrow(A)) for (i in r:nrow(A)) if (A[i, n + 1L] != 0) return(list(sol = NULL, ok = FALSE))
  free <- setdiff(seq_len(n), piv)
  sol <- list()
  for (t in seq_along(piv)) {
    j <- piv[t]
    v <- .add(c(list(make_rational(A[t, n + 1L])), lapply(free, function(f) .mul(list(make_rational(-A[t, f]), syms[[f]])))))
    sol[[syms[[j]]$key]] <- list(sym = syms[[j]], val = v)
  }
  list(sol = sol, ok = TRUE)
}
# minsolve_linear_system(quick = TRUE): a solution with many zeros
.minsolve_quick <- function(eqs, syms) {
  s0 <- .lin_solve_rat(eqs, syms)
  if (!s0$ok) return(NULL)
  if (!length(s0$sol) || all(vapply(s0$sol, function(p) is_zero_num(p$val), TRUE))) return(s0$sol)
  s <- s0$sol
  determined <- list()
  update <- function() {
    del <- character()
    for (k in names(s)) {
      v <- s[[k]]$val
      if (length(determined)) v <- subs(v, unname(lapply(determined, function(p) list(p$sym, p$val))))
      s[[k]]$val <<- v
      if (!length(free_symbols(v))) { del <- c(del, k); determined[[k]] <<- list(sym = s[[k]]$sym, val = v) }
    }
    for (k in del) s[[k]] <<- NULL
  }
  update()
  while (length(s)) {
    vals <- lapply(s, `[[`, "val")
    keys <- lapply(vals, function(v) list(length(free_symbols(v)), .sort_key(v)))
    k <- .key_sort(keys, vals)[[length(vals)]]
    kfree <- free_symbols(k)
    x <- .key_sort(lapply(kfree, .sort_key), kfree)[[length(kfree)]]
    if (length(kfree) != 1L) {
      val <- S_Zero
    } else {
      val <- .neg(.div(subs(k, x, S_Zero), .expr_coeff(expand(k), x)))
      if (is_zero_num(val) && !any(vapply(s, function(p) !is_zero_num(subs(p$val, x, val)), TRUE))) val <- S_One
    }
    determined[[x$key]] <- list(sym = x, val = val)
    update()
  }
  determined
}

# minsolve_linear_system(quick = FALSE): the fewest nonzero variables
.minsolve_exhaustive <- function(eqs, syms) {
  best <- .minsolve_quick(eqs, syms)
  if (is.null(best)) return(NULL)
  N <- length(syms)
  n0 <- sum(vapply(best, function(p) !is_zero_num(p$val), TRUE))
  if (n0 - 1L < 2L) return(best)
  for (n in (n0 - 1L):2L) {
    this <- NULL
    for (nz in utils::combn(N, n, simplify = FALSE)) {
      sub_syms <- syms[nz]
      zero <- lapply(syms[-nz], function(s) list(s, S_Zero))
      eqs2 <- lapply(eqs, function(e) if (length(zero)) subs(e, zero) else e)
      s <- .lin_solve_rat(eqs2, sub_syms)
      if (s$ok && length(s$sol) && !all(vapply(s$sol, function(p) is_zero_num(p$val), TRUE))) {
        ones <- lapply(sub_syms, function(z) list(z, S_One))
        out <- lapply(s$sol, function(p) list(sym = p$sym, val = subs(p$val, ones)))
        for (j in seq_len(N)) if (is.null(out[[syms[[j]]$key]]))
          out[[syms[[j]]$key]] <- list(sym = syms[[j]], val = if (j %in% nz) S_One else S_Zero)
        this <- out
        break
      }
    }
    if (is.null(this)) break
    best <- this
  }
  best
}

#' Rational simplification modulo a prime ideal
#'
#' `ratsimpmodprime(expr, G, ...)` simplifies a rational function modulo the
#' prime ideal generated by `G` (a Groebner basis), as SymPy's
#' `ratsimpmodprime()`: it searches for a numerator and denominator of
#' least total degree (Monagan and Pearce's algorithm). With `quick =
#' FALSE` it also minimizes the number of terms, and with `polynomial =
#' TRUE` it only reduces numerator and denominator modulo `G`.
#'
#' @param expr A rational expression.
#' @param G A list of polynomials forming a Groebner basis of a prime ideal.
#' @param ... Generators.
#' @param quick Stop at the first solution.
#' @param polynomial Only reduce the numerator and the denominator.
#' @param order The monomial order.
#' @return An expression.
#' @examples
#' x <- Symbol("x"); y <- Symbol("y")
#' eq <- (x + y^5 + y) / (x - y)
#' \donttest{
#' ratsimpmodprime(eq, list(x * y^5 - x - y), x, y, order = "lex")
#' }
#' @export
ratsimpmodprime <- function(expr, G, ..., quick = TRUE, polynomial = FALSE, order = "lex") {
  expr <- as_sym(expr)
  G <- lapply(G, as_sym)
  nd <- .as_numer_denom(cancel(expr))
  num <- nd[[1L]]; denom <- nd[[2L]]
  gens <- .gens_of(c(list(num, denom), G), list(...))
  if (!length(gens)) return(expr)
  cv <- tryCatch(.to_qpolys(c(list(num, denom), G), gens), error = function(err) NULL)
  if (is.null(cv)) return(expr)
  gens <- cv$gens
  ng <- length(gens)
  lms <- lapply(cv$polys[-(1:2)], function(p) qp_lm(qp_reorder(p, order)))
  divides <- function(m, lm) all(m >= lm)
  stair <- list(list(S_One))
  staircase <- function(n) {
    while (length(stair) <= n) {
      k <- length(stair)
      res <- list()
      combs <- if (k == 0L) list(integer()) else .comb_rep(ng, k)
      for (mi in combs) {
        m <- tabulate(mi, nbins = ng)
        if (!any(vapply(lms, function(lm) divides(m, lm), TRUE)))
          res[[length(res) + 1L]] <- .mul(lapply(seq_len(ng), function(j) .pow(gens[[j]], .int(m[j]))))
      }
      stair[[k + 1L]] <<- c(res, stair[[k]])
    }
    stair[[n + 1L]]
  }
  tdeg <- function(e) if (is_zero_num(e)) 0 else total_degree(e, gens)
  tested <- character()
  red <- function(e, gg) reduced(e, G, gg, order = order)$r
  rec <- function(a, b, allsol, N = 0L, D = 0L) {
    cc <- a; dd <- b; steps <- 0L
    maxdeg <- tdeg(a) + tdeg(b)
    bound <- if (quick) maxdeg - 1 else maxdeg
    while (N + D <= bound && !(paste(N, D) %in% tested)) {
      tested <<- c(tested, paste(N, D))
      M1 <- staircase(N); M2 <- staircase(D)
      Cs <- lapply(seq_along(M1) - 1L, function(i) Dummy(paste0("c", i)))
      Ds <- lapply(seq_along(M2) - 1L, function(i) Dummy(paste0("d", i)))
      vars <- c(Cs, Ds)
      c_hat <- .add(Map(function(ci, m) .mul(list(ci, m)), Cs, M1))
      d_hat <- .add(Map(function(di, m) .mul(list(di, m)), Ds, M2))
      r <- red(expand(.sub(.mul(list(a, d_hat)), .mul(list(b, c_hat)))), c(gens, vars))
      s <- if (is_zero_num(r)) list() else coeffs(do.call(Poly, c(list(r), gens)))
      sol <- .minsolve_quick(s, vars)
      if (!is.null(sol) && length(sol) && !all(vapply(sol, function(p) is_zero_num(p$val), TRUE))) {
        sl <- unname(lapply(sol, function(p) list(p$sym, p$val)))
        cc <- subs(c_hat, sl); dd <- subs(d_hat, sl)
        ones <- lapply(vars, function(v) list(v, S_One))
        cc <- expand(subs(cc, ones)); dd <- expand(subs(dd, ones))
        if (is_zero_num(dd)) stop("Ideal not prime?", call. = FALSE)
        allsol[[length(allsol) + 1L]] <- list(c_hat, d_hat, s, vars)
        if (N + D != maxdeg) allsol <- allsol[length(allsol)]
        break
      }
      steps <- steps + 1L; N <- N + 1L; D <- D + 1L
    }
    if (steps > 0L) {
      r1 <- rec(cc, dd, allsol, N, D - steps); cc <- r1[[1L]]; dd <- r1[[2L]]; allsol <- r1[[3L]]
      r2 <- rec(cc, dd, allsol, N - steps, D); cc <- r2[[1L]]; dd <- r2[[2L]]; allsol <- r2[[3L]]
    }
    list(cc, dd, allsol)
  }
  num <- red(num, gens); denom <- red(denom, gens)
  if (polynomial) return(cancel(.div(num, denom)))
  res <- rec(num, denom, list())
  cc <- res[[1L]]; dd <- res[[2L]]; allsol <- res[[3L]]
  if (!quick && length(allsol)) {
    newsol <- lapply(allsol, function(t) {
      sol <- .minsolve_exhaustive(t[[3L]], t[[4L]])
      sl <- unname(lapply(sol, function(p) list(p$sym, p$val)))
      list(expand(subs(t[[1L]], sl)), expand(subs(t[[2L]], sl)))
    })
    nt <- function(e) if (e$type == "Add") length(e$args) else 1L
    sizes <- vapply(newsol, function(p) nt(p[[1L]]) + nt(p[[2L]]), 0)
    best <- newsol[[which.min(sizes)]]
    cc <- best[[1L]]; dd <- best[[2L]]
  }
  .div(cc, dd)
}

# _parallel_poly_from_expr with gens and domain=ZZ: the coefficient of each
# monomial of each expression, in order, through ZZ.from_sympy, which raises
# CoercionFailed (sympy/polys/domains/integerring.py:82).
.zz_coeff_check <- function(exprs, gens) {
  gk <- vapply(gens, .k, "")
  base <- function(f) if (f$type == "Pow" && f$args[[2L]]$type == "Integer") f$args[[1L]] else f
  for (e in exprs) {
    e <- expand(e)
    cf <- list()
    for (t in if (e$type == "Add") .sympy_args(e) else list(e)) {
      fs <- if (t$type == "Mul") .sympy_args(t) else list(t)
      isg <- vapply(fs, function(f) base(f)$key %in% gk, NA)
      m <- paste0("m", paste(vapply(fs[isg], .k, ""), collapse = "*"))
      c0 <- .mul(fs[!isg])
      cf[[m]] <- if (is.null(cf[[m]])) c0 else .add(list(cf[[m]], c0))
    }
    for (v in cf) if (!(v$type == "Integer" || (v$type == "Float" && num_value_dbl(v) == round(num_value_dbl(v)))))
      stop(CoercionFailed(paste0("expected an integer, got ", .str(v))))
  }
}

# combinations_with_replacement(range(n), k), as 1-based index vectors
.comb_rep <- function(n, k) {
  out <- list(); cur <- integer()
  rec <- function(start, left) {
    if (left == 0L) { out[[length(out) + 1L]] <<- cur; return(invisible()) }
    for (i in start:n) { cur <<- c(cur, i); rec(i, left - 1L); cur <<- cur[-length(cur)] }
  }
  rec(1L, k)
  out
}

#' @rdname trigsimp
#' @export
trigsimp_groebner <- function(expr, hints = list(), quick = FALSE, order = "grlex", polynomial = FALSE) {
  expr <- as_sym(expr)
  tfun <- function(nm, a) fcall(nm, list(a))
  fname <- function(h) if (is.character(h)) h else if (is.function(h)) {
    m <- c("sin", "cos", "tan", "sinh", "cosh", "tanh")[vapply(list(sin, cos, tan, sinh, cosh, tanh), function(f) identical(f, h), TRUE)]
    if (length(m)) m else NULL
  } else NULL
  # parse_hints
  n <- 1L; funcs <- character(); iterables <- list(); extragens <- list()
  for (h in hints) {
    if (is.numeric(h) || (is_sym(h) && h$type == "Integer")) n <- as.integer(if (is_sym(h)) h$value else h)
    else if (!is.null(fname(h))) funcs <- c(funcs, fname(h))
    else if (is.list(h) && !is_sym(h)) {
      fn <- fname(h[[1L]]); args <- lapply(h[-1L], as_sym)
      iterables[[length(iterables) + 1L]] <- list(fn, args)
      ex <- c(lapply(args, function(a) tfun(fn, a)), list(tfun(fn, .add(args))))
      extragens <- c(extragens, .gens_of(ex, list()))
    } else extragens[[length(extragens) + 1L]] <- as_sym(h)
  }
  myI <- Dummy("I")
  expr <- subs(expr, S_I, myI)
  nd <- .as_numer_denom(cancel(expr))
  num <- nd[[1L]]; denom <- nd[[2L]]
  gens0 <- tryCatch(.gens_of(list(num, denom), list()), error = function(err) NULL)
  if (is.null(gens0)) return(subs(expr, myI, S_I))
  # analyse_gens
  allf <- c("sin", "cos", "tan", "sinh", "cosh", "tanh")
  gens <- c(gens0, extragens)
  gens <- gens[!duplicated(vapply(gens, .k, ""))]
  isf <- function(g) g$type == "Function" && g$name %in% allf
  freegens <- Filter(Negate(isf), gens)
  trigdict <- list()
  for (g in Filter(isf, gens)) {
    sp <- as_coeff_mul_split(g$args[[1L]])
    k <- sp[[2L]]$key
    if (is.null(trigdict[[k]])) trigdict[[k]] <- list(var = sp[[2L]], items = list())
    trigdict[[k]]$items[[length(trigdict[[k]]$items) + 1L]] <- list(c = sp[[1L]], fn = g$name)
  }
  res <- list(); newgens <- list()
  build_ideal <- function(x, terms) {
    I <- list(); y <- Dummy("y")
    for (t in terms) {
      fn <- t[[1L]]; cf <- t[[2L]]
      for (cst in list(list("cos", "sin", "tan", .sub(.add(list(.sq(fcall("cos", list(x))), .sq(fcall("sin", list(x))))), S_One)),
                       list("cosh", "sinh", "tanh", .sub(.sub(.sq(fcall("cosh", list(x))), .sq(fcall("sinh", list(x)))), S_One)))) {
        cc <- cst[[1L]]; ss <- cst[[2L]]; tt <- cst[[3L]]
        if (is_one_num(cf) && fn %in% c(cc, ss)) I[[length(I) + 1L]] <- cst[[4L]]
        else if (fn == tt) I[[length(I) + 1L]] <- .sub(.mul(list(tfun(tt, .mul(list(cf, x))), tfun(cc, .mul(list(cf, x))))), tfun(ss, .mul(list(cf, x))))
        else if (fn %in% c(cc, ss)) {
          cn <- subs(expand_trig(tfun(fn, .mul(list(cf, y)))), y, x)
          I[[length(I) + 1L]] <- .sub(tfun(fn, .mul(list(cf, x))), cn)
        }
      }
    }
    I[!duplicated(vapply(I, .k, ""))]
  }
  for (td in trigdict) {
    fns <- vapply(td$items, `[[`, "", "fn")
    vals <- lapply(td$items, `[[`, "c")
    # reduce(igcd, val) (sympy/simplify/trigsimp.py:307): as_int refuses a non integer
    if (length(vals) > 1L) for (v in vals) if (v$type != "Integer") stop(.sympy_condition("ValueError", paste0(.str(v), " is not an integer")))
    g <- Reduce(function(a, b) .num_gcd(a, b), vals)
    terms <- Map(function(fn, v) list(fn, .div(v, g)), fns, vals)
    fs <- unique(c(funcs, fns))
    for (cst in list(c("cos", "sin", "tan"), c("cosh", "sinh", "tanh")))
      if (any(cst %in% fs)) fs <- unique(c(fs, cst[1:2]))
    for (fn in fs) for (k in seq_len(n)) terms[[length(terms) + 1L]] <- list(fn, .int(k))
    extra <- list()
    for (t in terms) {
      fn <- t[[1L]]; v <- t[[2L]]
      if (fn == "tan") extra <- c(extra, list(list("sin", v), list("cos", v)))
      if (fn %in% c("sin", "cos") && "tan" %in% fs) extra <- c(extra, list(list("tan", v)))
      if (fn == "tanh") extra <- c(extra, list(list("sinh", v), list("cosh", v)))
      if (fn %in% c("sinh", "cosh") && "tanh" %in% fs) extra <- c(extra, list(list("tanh", v)))
    }
    terms <- c(terms, extra)
    x <- .mul(list(g, td$var))
    res <- c(res, build_ideal(x, terms))
    ng <- lapply(terms, function(t) tfun(t[[1L]], .mul(list(t[[2L]], x))))
    newgens <- c(newgens, ng)
  }
  for (it in iterables) {
    fn <- it[[1L]]; args <- it[[2L]]
    if (fn == "tan") { iterables <- c(iterables, list(list("sin", args), list("cos", args))); next }
    if (fn == "tanh") { iterables <- c(iterables, list(list("sinh", args), list("cosh", args))); next }
    ds <- lapply(seq_along(args), function(i) Dummy(paste0("d", i - 1L)))
    ex <- subs(expand_trig(tfun(fn, .add(ds))), Map(function(d, a) list(d, a), ds, args))
    res[[length(res) + 1L]] <- .sub(tfun(fn, .add(args)), ex)
  }
  if (any(vapply(gens, function(g) identical(g$key, myI$key), TRUE))) {
    res[[length(res) + 1L]] <- .add(list(.sq(myI), S_One))
    freegens <- Filter(function(g) !identical(g$key, myI$key), freegens)
    newgens[[length(newgens) + 1L]] <- myI
  }
  res <- res[!duplicated(vapply(res, .k, ""))]
  newgens <- newgens[!duplicated(vapply(newgens, .k, ""))]
  # sets in SymPy: a deterministic order here
  newgens <- .key_sort(lapply(newgens, .sort_key), newgens)
  if (!length(newgens)) return(subs(expr, myI, S_I))
  # groebner(ideal, order=order, gens=gens, domain=ZZ) (sympy/simplify/trigsimp.py:372)
  .zz_coeff_check(res, newgens)
  G <- do.call(groebner, c(list(res), newgens, list(order = order)))
  back <- list(list(myI, S_I))
  gk <- vapply(newgens, .k, "")
  in_gens <- function(e, set_keys) all(vapply(.gens_of(list(e), list()), function(z) z$key %in% set_keys, TRUE))
  if (length(freegens) && in_gens(denom, gk)) {
    P <- do.call(Poly, c(list(num), c(newgens, freegens)))
    ms <- monoms(P); cs <- coeffs(P)
    nG <- length(newgens)
    # eject: group the terms by the exponents of the free generators
    grp <- list()
    for (i in seq_along(ms)) {
      fm <- ms[[i]][-seq_len(nG)]
      k <- paste(fm, collapse = ",")
      tm <- .mul(c(list(cs[[i]]), lapply(seq_len(nG), function(j) .pow(newgens[[j]], .int(ms[[i]][j])))))
      if (is.null(grp[[k]])) grp[[k]] <- list(m = fm, c = tm) else grp[[k]]$c <- .add(list(grp[[k]]$c, tm))
    }
    out <- list()
    for (gp in grp) {
      coeff <- gp$c
      ourg <- vapply(.gens_of(list(coeff, denom), list()), .k, "")
      # parallel_poly_from_expr([coeff, denom]) (sympy/simplify/trigsimp.py:384)
      if (!length(ourg)) stop(PolificationFailed(paste0("Cannot construct polynomials from ", .str(coeff), ", ", .str(denom))))
      changed <- TRUE
      while (changed) {
        changed <- FALSE
        for (p in res) {
          pg <- vapply(.gens_of(list(p), list()), .k, "")
          if (!all(pg %in% ourg) && !all(pg %in% setdiff(pg, ourg))) { changed <- TRUE; ourg <- unique(c(ourg, pg)) }
        }
      }
      realgens <- newgens[gk %in% ourg]
      ourG <- Filter(function(gg) in_gens(gg, ourg), G)
      fac <- .mul(lapply(seq_along(freegens), function(j) .pow(freegens[[j]], .int(gp$m[j]))))
      r <- do.call(ratsimpmodprime, c(list(.div(coeff, denom), ourG), realgens, list(order = order, quick = quick, polynomial = polynomial)))
      out[[length(out) + 1L]] <- .mul(list(fac, subs(r, back)))
    }
    return(.add(out))
  }
  r <- do.call(ratsimpmodprime, c(list(expr, as.list(G)), c(freegens, newgens), list(order = order, quick = quick, polynomial = polynomial)))
  subs(r, back)
}
