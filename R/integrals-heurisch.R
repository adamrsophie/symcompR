# The heuristic Risch algorithm, after sympy/integrals/heurisch.py.
# ponytail: Python sets become insertion-ordered lists; where SymPy iterates
# a set without ordered() the order can differ (it is hash based there).

.hset_add <- function(s, e) if (e$key %in% vapply(s, `[[`, "", "key")) s else c(s, list(e))
.hset_union <- function(a, b) { for (e in b) a <- .hset_add(a, e); a }

.heur_components <- function(f, x) {
  f <- as_sym(f); x <- as_sym(x)
  result <- list()
  if (!.has1(f, x)) return(result)
  if (f$type %in% c("Symbol", "Dummy") && .is_comm(f)) return(list(f))
  if (f$type == "Function" || f$type == "Derivative") {
    for (g in f$args) result <- .hset_union(result, .heur_components(g, x))
    return(.hset_add(result, f))
  }
  if (f$type == "Pow") {
    result <- .hset_union(result, .heur_components(f$args[[1L]], x))
    ex <- f$args[[2L]]
    if (ex$type != "Integer") {
      if (ex$type == "Rational") result <- .hset_add(result, .pow(f$args[[1L]], Rational(1, as.integer(as.character(gmp::denominator(gmp::as.bigq(ex$value)))))))
      else result <- .hset_add(.hset_union(result, .heur_components(ex, x)), f)
    }
    return(result)
  }
  for (g in f$args) result <- .hset_union(result, .heur_components(g, x))
  result
}

.heur_syms <- new.env()
.hsymbols <- function(name, n) {
  l <- .heur_syms[[name]]
  if (is.null(l)) l <- list()
  while (length(l) < n) l[[length(l) + 1L]] <- Dummy(paste0(name, length(l)))
  .heur_syms[[name]] <- l
  l[seq_len(n)]
}

# The order of `for g in set(terms)`: DiffCache.get_diff of f(n, z) also
# caches f(n - 1, z), so a Bessel function is visited before the ones of
# lower order by an integer, which then come from the cache (the order the
# Python sets give in SymPy's test of besselj(nu + 1, x))
.heur_diff_order <- function(terms) {
  bes <- which(vapply(terms, function(g) g$type == "Function" && !is.null(.BESSEL_DIFF(g$name, S_One, S_One)), NA))
  if (length(bes) < 2L) return(terms)
  ord <- bes
  for (i in seq_along(ord)[-1L]) {
    j <- i
    while (j > 1L) {
      a <- terms[[ord[j - 1L]]]; b <- terms[[ord[j]]]
      d <- if (identical(a$name, b$name) && identical(a$args[[2L]]$key, b$args[[2L]]$key)) .sub(b$args[[1L]], a$args[[1L]]) else S_Zero
      if (!(d$type == "Integer" && d$value > 0L)) break
      ord[c(j - 1L, j)] <- ord[c(j, j - 1L)]
      j <- j - 1L
    }
  }
  c(terms[ord], terms[-bes])
}

.BESSEL_DIFF <- function(name, n, z) {
  f <- function(a, b) fcall(name, list(a, b))
  switch(name,
    besselj = , bessely = , hankel1 = , hankel2 = list(.sub(f(.sub(n, S_One), z), .div(.mul(list(n, f(n, z))), z)), .sub(.div(.mul(list(.sub(n, S_One), f(.sub(n, S_One), z))), z), f(n, z))),
    besseli = list(.sub(f(.sub(n, S_One), z), .div(.mul(list(n, f(n, z))), z)), .add(list(.div(.mul(list(.sub(n, S_One), f(.sub(n, S_One), z))), z), f(n, z)))),
    besselk = list(.sub(.neg(f(.sub(n, S_One), z)), .div(.mul(list(n, f(n, z))), z)), .sub(.div(.mul(list(.sub(n, S_One), f(.sub(n, S_One), z))), z), f(n, z))),
    jn = , yn = list(.sub(f(.sub(n, S_One), z), .div(.mul(list(.add(list(n, S_One)), f(n, z))), z)), .sub(.div(.mul(list(.sub(n, S_One), f(.sub(n, S_One), z))), z), f(n, z))),
    NULL)
}

.diff_cache <- function(x) {
  env <- new.env(); env$x <- x; env$keys <- character(); env$vals <- list()
  env$get <- function(f) {
    i <- match(f$key, env$keys)
    if (!is.na(i)) return(env$vals[[i]])
    put <- function(k, v) { env$keys <- c(env$keys, k$key); env$vals[[length(env$vals) + 1L]] <- v }
    if (f$type == "Function" && !is.null(.BESSEL_DIFF(f$name, S_One, S_One))) {
      n <- f$args[[1L]]; z <- f$args[[2L]]
      d <- .BESSEL_DIFF(f$name, n, z)
      dz <- env$get(z)
      put(f, .mul(list(d[[1L]], dz)))
      put(fcall(f$name, list(.sub(n, S_One), z)), .mul(list(d[[2L]], dz)))
    } else put(f, cancel(.diff1(f, env$x)))
    env$vals[[match(f$key, env$keys)]]
  }
  env
}

#' The heuristic Risch algorithm
#'
#' Ports of SymPy's `heurisch()` and `heurisch_wrapper()`
#' (sympy/integrals/heurisch.py): a candidate antiderivative with
#' undetermined coefficients over the differential field generated by the
#' components of the integrand, solved as a linear system.
#'
#' @param f The integrand.
#' @param x The variable.
#' @param rewrite Rewrite trigonometric functions with `tan` and `tanh`.
#' @param hints `NULL`, an empty list for the built-in special function
#'   hints, or a list of extra terms.
#' @param mappings,retries,degree_offset,unnecessary_permutations,try_heurisch As SymPy.
#' @return The antiderivative or `NULL`.
#' @examples
#' x <- Symbol("x")
#' heurisch(x*cos(x), x)
#' @export
heurisch <- function(f, x, rewrite = FALSE, hints = NULL, mappings = NULL, retries = 3, degree_offset = 0,
                     unnecessary_permutations = NULL, try_heurisch = NULL) {
  f <- as_sym(f); x <- as_sym(x)
  if (!isTRUE(try_heurisch) && .has_function(f, c("Abs", "re", "im", "sign", "Heaviside", "DiracDelta", "floor", "ceiling", "arg"))) return(NULL)
  if (!.has1(f, x)) return(.mul(list(f, x)))
  if (f$type != "Add") {
    sp <- .as_coeff_mul_dep(f, x)
    indep <- sp[[1L]]; f <- .mul(sp[[2L]])
  } else indep <- S_One
  rw <- list(list(c("sin", "cos", "cot"), "tan"), list(c("sinh", "cosh", "coth"), "tanh"))
  if (rewrite) {
    for (r in rw) f <- .map_bottom_up(f, function(z) if (z$type == "Function" && z$name %in% r[[1L]]) rewrite(z, r[[2L]]) else z)
  } else {
    if (!any(vapply(rw, function(r) .has_function(f, r[[1L]]), NA))) rewrite <- TRUE
  }
  terms <- .heur_components(f, x)
  dcache <- .diff_cache(x)
  if (!is.null(hints)) {
    if (!length(hints)) {
      a <- Wild("a", exclude = list(x)); b <- Wild("b", exclude = list(x)); c <- Wild("c", exclude = list(x))
      mt <- function(e, pat) { m <- tryCatch(sym_match(e, pat), error = function(err) NULL); if (is.null(m) || !length(m)) NULL else m }
      for (g in terms) {
        if (g$type == "Function" && g$name == "li") {
          M <- mt(g$args[[1L]], a * x^b)
          if (!is.null(M)) terms <- .hset_add(terms, x * (fcall("li", list(M$a * x^M$b)) - (M$a * x^M$b)^(-1 / M$b) * Ei((M$b + 1) * log(M$a * x^M$b) / M$b)))
        } else if (g$type == "Function" && g$name == "exp") {
          M <- mt(g$args[[1L]], a * x^2)
          if (!is.null(M)) terms <- .hset_add(terms, if (isTRUE(ask_fact(M$a, "positive"))) erfi(sqrt(M$a) * x) else erf(sqrt(-M$a) * x))
          M <- mt(g$args[[1L]], a * x^2 + b * x + c)
          if (!is.null(M)) {
            if (isTRUE(ask_fact(M$a, "positive")))
              terms <- .hset_add(terms, sqrt(S_Pi / 4 * -M$a) * exp(M$c - M$b^2 / (4 * M$a)) * erfi(sqrt(M$a) * x + M$b / (2 * sqrt(M$a))))
            else if (isTRUE(ask_fact(M$a, "negative")))
              terms <- .hset_add(terms, sqrt(S_Pi / 4 * -M$a) * exp(M$c - M$b^2 / (4 * M$a)) * erf(sqrt(-M$a) * x - M$b / (2 * sqrt(-M$a))))
          }
          M <- mt(g$args[[1L]], a * log(x)^2)
          if (!is.null(M)) {
            if (isTRUE(ask_fact(M$a, "positive"))) terms <- .hset_add(terms, erfi(sqrt(M$a) * log(x) + 1 / (2 * sqrt(M$a))))
            if (isTRUE(ask_fact(M$a, "negative"))) terms <- .hset_add(terms, erf(sqrt(-M$a) * log(x) - 1 / (2 * sqrt(-M$a))))
          }
        } else if (g$type == "Pow" && g$args[[2L]]$type == "Rational" && gmp::denominator(gmp::as.bigq(g$args[[2L]]$value)) == 2) {
          M <- mt(g$args[[1L]], a * x^2 + b)
          if (!is.null(M) && isTRUE(ask_fact(M$b, "positive"))) {
            if (isTRUE(ask_fact(M$a, "positive"))) terms <- .hset_add(terms, asinh(sqrt(M$a / M$b) * x))
            else if (isTRUE(ask_fact(M$a, "negative"))) terms <- .hset_add(terms, asin(sqrt(-M$a / M$b) * x))
          }
          M <- mt(g$args[[1L]], a * x^2 - b)
          if (!is.null(M) && isTRUE(ask_fact(M$b, "positive"))) {
            if (isTRUE(ask_fact(M$a, "positive"))) {
              dF <- 1 / sqrt(M$a * x^2 - M$b)
              F <- log(2 * sqrt(M$a) * sqrt(M$a * x^2 - M$b) + 2 * M$a * x) / sqrt(M$a)
              dcache$keys <- c(dcache$keys, F$key); dcache$vals[[length(dcache$vals) + 1L]] <- dF
              terms <- .hset_add(terms, F)
            } else if (isTRUE(ask_fact(M$a, "negative")))
              terms <- .hset_add(terms, -M$b / 2 * sqrt(-M$a) * atan(sqrt(-M$a) * x / sqrt(M$a * x^2 - M$b)))
          }
        }
      }
    } else terms <- .hset_union(terms, lapply(hints, as_sym))
  }
  for (g in .heur_diff_order(terms)) terms <- .hset_union(terms, .heur_components(dcache$get(g), x))
  V <- .hsymbols("x", length(terms))
  pairs <- Map(function(tm, v) list(tm, v), terms, V)
  keyed <- lapply(pairs, function(p) list(.mul(.as_coeff_mul_dep(p[[1L]], x)[[2L]]), p))
  ord <- .key_sort(lapply(keyed, function(k) list(.nodes(Tuple(k[[1L]], Tuple(k[[2L]][[1L]], k[[2L]][[2L]]))),
                                                  .sort_key(Tuple(k[[1L]], Tuple(k[[2L]][[1L]], k[[2L]][[2L]]))))), keyed)
  mapping <- rev(lapply(ord, `[[`, 2L))
  rev_mapping <- lapply(mapping, function(p) list(p[[2L]], p[[1L]]))
  if (is.null(mappings)) {
    if (!identical(mapping[[length(mapping)]][[1L]]$key, x$key)) stop("heurisch: x is not the last mapping")
    unnecessary_permutations <- list(mapping[[length(mapping)]])
    mapping <- mapping[-length(mapping)]
    tkeys <- vapply(mapping, function(p) .heur_type(p[[1L]]), "")
    groups <- lapply(unique(tkeys), function(k) mapping[tkeys == k])
    perms <- if (length(groups)) permutations(seq_along(groups)) else list(integer())
    if (!is.list(perms)) perms <- list(perms)
    mappings <- lapply(perms, function(pi) unlist(lapply(groups[pi], function(gr) .heur_ordered_pairs(gr)), recursive = FALSE))
  } else if (is.null(unnecessary_permutations)) unnecessary_permutations <- list()
  subst <- function(expr, mp) { for (p in mp) expr <- subs(expr, p[[1L]], p[[2L]]); expr }
  found <- FALSE
  # mappings is a generator in SymPy: a retry continues after the mapping used
  used <- 0L
  for (mp in mappings) {
    used <- used + 1L
    mp <- c(mp, unnecessary_permutations)
    diffs <- lapply(terms, function(g) subst(dcache$get(g), mp))
    dens <- lapply(diffs, function(g) .as_numer_denom(g)[[2L]])
    if (all(vapply(dens, function(h) isTRUE(do.call(is_polynomial, c(list(h), V))), NA)) && .is_rational_function_in(subst(f, mp), V)) {
      denom <- Reduce(function(p, q) .heur_lcm(p, q, V), dens)
      found <- TRUE
      mapping <- mp
      break
    }
  }
  if (!found) {
    if (!rewrite) {
      result <- heurisch(f, x, rewrite = TRUE, hints = hints, unnecessary_permutations = unnecessary_permutations)
      if (!is.null(result)) return(.mul(list(indep, result)))
    }
    return(NULL)
  }
  numers <- lapply(diffs, function(g) cancel(.mul(list(denom, g))))
  derivation_h <- function(h) .add(Map(function(d, v) .mul(list(d, .diff1(h, v))), numers, V))
  deflation <- function(p) {
    for (y in V) {
      if (!.has1(p, y)) next
      if (!is_zero_num(derivation_h(p))) {
        pr <- P_primitive(.P(p, y))
        q <- pr[[2L]]
        return(.mul(list(deflation(pr[[1L]]), P_expr(P_gcd(q, P_diff(q))))))
      }
    }
    p
  }
  splitter <- function(p) {
    for (y in V) {
      if (!.has1(p, y)) next
      if (!is_zero_num(derivation_h(y))) {
        pr <- P_primitive(.P(p, y))
        c <- pr[[1L]]; qp <- pr[[2L]]; q <- P_expr(qp)
        h <- P_gcd(.P(q, y), .P(derivation_h(q), y))
        s <- P_expr(P_quo(h, P_gcd(qp, P_diff(qp))))
        c_split <- splitter(c)
        if (!.has1(s, y)) return(list(c_split[[1L]], .mul(list(q, c_split[[2L]]))))
        q_split <- splitter(cancel(.div(q, s)))
        return(list(.mul(list(c_split[[1L]], q_split[[1L]], s)), .mul(list(c_split[[2L]], q_split[[2L]]))))
      }
    }
    list(S_One, p)
  }
  special <- list()
  for (term in terms) {
    if (term$type != "Function") next
    st <- subst(term, mapping)
    if (term$name == "tan") special[[length(special) + 1L]] <- list(.add(list(S_One, .sq(st))), FALSE)
    else if (term$name == "tanh") { special[[length(special) + 1L]] <- list(.add(list(S_One, st)), FALSE); special[[length(special) + 1L]] <- list(.sub(S_One, st), FALSE) }
    else if (term$name == "LambertW") special[[length(special) + 1L]] <- list(st, TRUE)
  }
  F <- subst(f, mapping)
  nd <- .as_numer_denom(F); Pn <- nd[[1L]]; Qd <- nd[[2L]]
  u_split <- splitter(denom); v_split <- splitter(Qd)
  polys <- .uniq_syms(c(v_split, list(u_split[[1L]]), lapply(special, `[[`, 1L)))
  s <- .mul(c(list(u_split[[1L]]), lapply(Filter(function(k) k[[2L]], special), `[[`, 1L)))
  polified <- lapply(list(s, Pn, Qd), function(p) if (isTRUE(do.call(is_polynomial, c(list(p), V)))) p else NULL)
  if (any(vapply(polified, is.null, NA))) return(NULL)
  tdeg <- function(p) { p <- expand(p); if (!any(vapply(V, function(v) .has1(p, v), NA))) 0 else do.call(total_degree, c(list(p), V)) }
  a <- tdeg(s); b <- tdeg(Pn); c <- tdeg(Qd)
  poly_denom <- .mul(list(s, v_split[[1L]], deflation(v_split[[2L]])))
  .exponent <- function(g) {
    if (g$type == "Pow") {
      ex <- g$args[[2L]]
      if (ex$type == "Rational") {
        q <- gmp::as.bigq(ex$value); pp <- as.numeric(gmp::numerator(q)); qq <- as.numeric(gmp::denominator(q))
        if (pp > 0) return(pp + qq - 1) else return(abs(pp + qq))
      }
      return(1)
    }
    if (length(g$args)) return(max(vapply(g$args, .exponent, 0)))
    1
  }
  A <- .exponent(f); B <- a + max(b, c)
  deg <- if (A > 1 && B > 1) A + B - 1 + degree_offset else A + B + degree_offset
  monoms <- .bool_print_order(itermonomials(V, deg))
  poly_coeffs <- .hsymbols("A", length(monoms))
  poly_part <- .add(Map(function(cf, m) .mul(list(cf, m)), poly_coeffs, monoms))
  reducibles <- list()
  for (poly in .bool_print_order(polys)) {
    fl <- do.call(factor_list, c(list(poly), V))
    reducibles <- .hset_add(reducibles, as_sym(fl$coeff))
    for (fk in fl$factors) reducibles <- .hset_add(reducibles, fk[[1L]])
  }
  integrate_field <- function(field = NULL) {
    atans <- list(); pairs <- list()
    if (identical(field, "Q")) irreducibles <- reducibles
    else {
      irreducibles <- list()
      for (poly in .bool_print_order(reducibles)) {
        zV <- Filter(function(v) .has1(poly, v), V)
        for (z in .bool_print_order(zV)) {
          irreducibles <- .hset_union(irreducibles, root_factors(poly, z, filter = field))
          break
        }
      }
    }
    log_part <- list(); atan_part <- list()
    for (poly in .bool_print_order(irreducibles)) {
      m <- collect(poly, S_I, evaluate = FALSE)
      y <- m[["I"]] %||% S_Zero
      if (!is_zero_num(y)) {
        xx <- m[["1"]] %||% S_Zero
        if (.contains_key(xx, S_I$key) || .contains_key(y, S_I$key)) next
        pairs[[length(pairs) + 1L]] <- list(xx, y)
        irreducibles <- Filter(function(p) !identical(p$key, poly$key), irreducibles)
      }
    }
    while (length(pairs)) {
      pr <- pairs[[length(pairs)]]; pairs[[length(pairs)]] <- NULL
      xx <- pr[[1L]]; y <- pr[[2L]]
      j <- which(vapply(pairs, function(q) identical(q[[1L]]$key, xx$key) && identical(q[[2L]]$key, .neg(y)$key), NA))
      if (length(j)) {
        pairs <- pairs[-j[1L]]
        if (could_extract_minus_sign(y)) y <- .neg(y)
        irreducibles <- .hset_add(irreducibles, .add(list(.mul(list(xx, xx)), .mul(list(y, y)))))
        atans <- .hset_add(atans, fcall("atan", list(.div(xx, y))))
      } else irreducibles <- .hset_add(irreducibles, .add(list(xx, .mul(list(S_I, y)))))
    }
    Bs <- .hsymbols("B", length(irreducibles)); Cs <- .hsymbols("C", length(atans))
    pc <- poly_coeffs
    oi <- .bool_print_order(irreducibles)
    for (k in rev(seq_along(oi))) if (.has_any_of(oi[[k]], V)) { pc[[length(pc) + 1L]] <- Bs[[k]]; log_part[[length(log_part) + 1L]] <- .mul(list(Bs[[k]], fcall("log", list(oi[[k]])))) }
    oa <- .bool_print_order(atans)
    for (k in rev(seq_along(oa))) if (.has_any_of(oa[[k]], V)) { pc[[length(pc) + 1L]] <- Cs[[k]]; atan_part[[length(atan_part) + 1L]] <- .mul(list(Cs[[k]], oa[[k]])) }
    candidate <- .add(c(list(.div(poly_part, poly_denom)), log_part, atan_part))
    h <- .sub(F, .div(derivation_h(candidate), denom))
    raw_numer <- .as_numer_denom(h)[[1L]]
    solution <- .heur_solve(raw_numer, pc, V)
    if (is.null(solution)) return(NULL)
    res <- candidate
    for (k in seq_along(pc)) res <- subs(res, pc[[k]], solution[[k]])
    res
  }
  more_free <- Filter(function(s) !any(vapply(V, function(v) identical(v$key, s$key), NA)), free_symbols(F))
  solution <- if (!length(more_free)) { r <- integrate_field("Q"); if (is.null(r)) integrate_field() else r } else integrate_field()
  if (!is.null(solution)) {
    antideriv <- solution
    for (p in rev_mapping) antideriv <- subs(antideriv, p[[1L]], p[[2L]])
    antideriv <- expand(cancel(antideriv))
    if (antideriv$type == "Add") antideriv <- .add(Filter(function(t) .has1(t, x), antideriv$args))
    return(.mul(list(indep, antideriv)))
  }
  if (retries >= 0) {
    result <- heurisch(f, x, mappings = mappings[-seq_len(used)], rewrite = rewrite, hints = hints, retries = retries - 1, unnecessary_permutations = unnecessary_permutations)
    if (!is.null(result)) return(.mul(list(indep, result)))
  }
  NULL
}

.heur_type <- function(e) if (e$type == "Function") paste0("F:", e$name) else e$type
.heur_ordered_pairs <- function(gr) {
  keys <- lapply(gr, function(p) { tp <- Tuple(p[[1L]], p[[2L]]); list(.nodes(tp), .sort_key(tp)) })
  .key_sort(keys, gr)
}

# raw_numer as a qpoly in gens, multiplied out in the sparse representation
# (ring.from_expr) rather than by expand(); NULL when it is not a polynomial
# in gens with rational coefficients
.qp_from_expr <- function(ex, gk, n) {
  j <- match(ex$key, gk)
  if (!is.na(j)) return(qp_var(j, n))
  switch(ex$type,
    Integer = , Rational = qp_const(ex$value, n),
    Add = {
      ps <- lapply(ex$args, .qp_from_expr, gk, n)
      if (any(vapply(ps, is.null, NA))) return(NULL)
      qp_norm(do.call(rbind, lapply(ps, `[[`, "e")), do.call(c, lapply(ps, `[[`, "c")))
    },
    Mul = {
      ps <- lapply(ex$args, .qp_from_expr, gk, n)
      if (any(vapply(ps, is.null, NA))) return(NULL)
      ps <- ps[order(vapply(ps, function(q) length(q$c), 1L))]
      Reduce(qp_mul, ps)
    },
    Pow = {
      k <- ex$args[[2L]]
      if (k$type != "Integer" || k$value < 0) return(NULL)
      b <- .qp_from_expr(ex$args[[1L]], gk, n)
      if (is.null(b)) NULL else qp_pow(b, as.integer(k$value))
    },
    NULL)
}

# The rows (coefficients of pc, then minus the constant) of the linear
# equations in the unknowns pc, one per monomial in V of raw_numer; NULL
# when raw_numer is not a polynomial that is linear in pc.
.heur_rows_qp <- function(raw_numer, pc, V) {
  vk <- vapply(V, function(s) s$key, ""); pk <- vapply(pc, function(s) s$key, "")
  extra <- Filter(function(s) !(s$key %in% c(vk, pk)), free_symbols(raw_numer))
  gk <- c(vk, pk, vapply(extra, function(s) s$key, ""))
  p <- .qp_from_expr(raw_numer, gk, length(gk))
  if (is.null(p)) return(NULL)
  if (!length(p$c)) return(list())
  nv <- length(V); n <- length(pc)
  E <- p$e
  P <- E[, nv + seq_len(n), drop = FALSE]
  deg <- rowSums(P)
  if (any(deg > 1L)) return(NULL)
  slot <- rep(n + 1L, nrow(E))
  if (any(deg == 1L)) slot[deg == 1L] <- max.col(P[deg == 1L, , drop = FALSE], ties.method = "first")
  X <- E[, nv + n + seq_along(extra), drop = FALSE]
  # indexing a bigq vector copies it, so read the coefficients as strings
  cs <- as.character(p$c)
  num <- new.env(hash = TRUE)
  rat <- function(s) {
    v <- num[[s]]
    if (is.null(v)) { v <- make_rational(gmp::as.bigq(s)); num[[s]] <- v }
    v
  }
  coef <- function(i) {
    parts <- list(rat(cs[i]))
    for (j in which(X[i, ] > 0L)) parts[[length(parts) + 1L]] <- .pow(extra[[j]], .int(X[i, j]))
    z <- .mul(parts)
    if (slot[i] == n + 1L) .neg(z) else z
  }
  g <- .mono_keys(E[, seq_len(nv), drop = FALSE])
  lapply(split(seq_along(g), factor(g, levels = unique(g))), function(ii) {
    acc <- vector("list", n + 1L)
    for (i in ii) acc[[slot[i]]] <- c(acc[[slot[i]]], list(coef(i)))
    lapply(acc, function(z) if (is.null(z)) S_Zero else .add(z))
  })
}

# solve_lin_sys of the coefficients of raw_numer in V for the unknowns pc;
# free unknowns become zero
.heur_solve <- function(raw_numer, pc, V) {
  n <- length(pc)
  rows <- .heur_rows_qp(raw_numer, pc, V)
  if (is.null(rows)) {
    rows <- .heur_rows_expr(raw_numer, pc, V)
    if (isFALSE(rows)) return(NULL)
  }
  sol <- rep(list(S_Zero), n)
  if (!length(rows)) return(sol)
  rr <- .sp_rref(lapply(rows, .sp_row), stop = n + 1L)
  if (is.null(rr)) return(NULL)
  for (k in seq_along(rr$piv)) {
    r <- rr$rows[[k]]
    w <- match(n + 1L, r$j)
    if (!is.na(w)) sol[[rr$piv[k]]] <- r$v[[w]]
  }
  sol
}

# The same rows through expand(); FALSE when raw_numer is not a polynomial
# in V.
.heur_rows_expr <- function(raw_numer, pc, V) {
  e <- expand(raw_numer)
  # the coefficients of the monomials in V (ring.from_expr(raw_numer).coeffs())
  terms <- if (e$type == "Add") e$args else list(e)
  grp <- list(); keys <- character()
  for (t in terms) {
    fs <- if (t$type == "Mul") t$args else list(t)
    dep <- vapply(fs, function(f) .has_any_of(f, V), NA)
    if (any(vapply(fs[dep], function(f) !(f$type %in% c("Symbol", "Dummy") || (f$type == "Pow" && f$args[[2L]]$type == "Integer" && f$args[[2L]]$value > 0)), NA)))
      return(FALSE)
    mon <- .mul(fs[dep]); cf <- .mul(fs[!dep])
    k <- mon$key
    if (k %in% keys) grp[[k]] <- c(grp[[k]], list(cf)) else { keys <- c(keys, k); grp[[k]] <- list(cf) }
  }
  eqs <- lapply(grp, .add)
  n <- length(pc)
  pk <- vapply(pc, function(u) u$key, "")
  # coefficients of the unknowns in one pass over the terms of a linear
  # equation; NULL when a term is not linear in them
  lin_row <- function(eq) {
    acc <- vector("list", n + 1L)
    for (t in if (eq$type == "Add") eq$args else list(eq)) {
      fs <- if (t$type == "Mul") t$args else list(t)
      hit <- match(vapply(fs, function(f) f$key, ""), pk)
      w <- which(!is.na(hit))
      if (length(w) > 1L) return(NULL)
      if (length(w) == 1L) { slot <- hit[w]; cf <- .mul(fs[-w]) } else {
        if (any(vapply(free_symbols(t), function(s) s$key, "") %in% pk)) return(NULL)
        slot <- n + 1L; cf <- .neg(t)
      }
      acc[[slot]] <- c(acc[[slot]], list(cf))
    }
    lapply(acc, function(z) if (is.null(z)) S_Zero else .cancel_poly(.add(z)))
  }
  rows <- lapply(eqs, function(eq) {
    r <- lin_row(eq)
    if (!is.null(r)) return(r)
    eq <- expand(eq)
    r <- lin_row(eq)
    if (!is.null(r)) return(r)
    c(lapply(pc, function(u) cancel(.diff1(eq, u))), list(cancel(.neg(subs(eq, lapply(pc, function(u) list(u, S_Zero)))))))
  })
  rows
}

#' @rdname heurisch
#' @export
heurisch_wrapper <- function(f, x, rewrite = FALSE, hints = NULL, mappings = NULL, retries = 3, degree_offset = 0,
                             unnecessary_permutations = NULL, try_heurisch = NULL) {
  f <- as_sym(f); x <- as_sym(x)
  if (!.has1(f, x)) return(.mul(list(f, x)))
  res <- heurisch(f, x, rewrite, hints, mappings, retries, degree_offset, unnecessary_permutations, try_heurisch)
  if (!is_sym(res)) return(res)
  slns <- list()
  for (d in .bool_print_order(denoms(res))) {
    s <- tryCatch(.heur_solve_dicts(d, x), error = function(e) list())
    slns <- c(slns, s)
  }
  if (!length(slns)) return(res)
  slns <- slns[!duplicated(vapply(slns, .heur_dict_key, ""))]
  slns0 <- list()
  for (d in denoms(f)) slns0 <- c(slns0, tryCatch(.heur_solve_dicts(d, x), error = function(e) list()))
  k0 <- vapply(slns0, .heur_dict_key, "")
  slns <- Filter(function(s) !(.heur_dict_key(s) %in% k0), slns)
  if (!length(slns)) return(res)
  pairs <- list()
  for (sd in slns) {
    fe <- f; for (kv in sd) fe <- subs(fe, kv[[1L]], kv[[2L]])
    expr <- heurisch(fe, x, rewrite, hints, mappings, retries, degree_offset, unnecessary_permutations, try_heurisch)
    cond <- do.call(And, lapply(sd, function(kv) Eq(kv[[1L]], kv[[2L]])))
    generic <- do.call(Or, lapply(sd, function(kv) Ne(kv[[1L]], kv[[2L]])))
    if (is.null(expr)) expr <- integrate(fe, x)
    pairs[[length(pairs) + 1L]] <- list(expr, cond)
  }
  if (length(pairs) == 1L)
    pairs <- list(list(heurisch(f, x, rewrite, hints, mappings, retries, degree_offset, unnecessary_permutations, try_heurisch), generic), list(pairs[[1L]][[1L]], S_true))
  else pairs[[length(pairs) + 1L]] <- list(heurisch(f, x, rewrite, hints, mappings, retries, degree_offset, unnecessary_permutations, try_heurisch), S_true)
  do.call(Piecewise, pairs)
}

# solve([d], dict=True, exclude=(x,)): solutions for the parameters
.heur_solve_dicts <- function(d, x) {
  syms <- .poly_sort_gens(Filter(function(s) !identical(s$key, x$key), free_symbols(d)))
  if (!length(syms)) return(list())
  v <- syms[[1L]]
  sl <- solve(d, v)
  lapply(sl, function(r) list(list(v, r)))
}
.heur_dict_key <- function(s) paste(vapply(s, function(kv) paste0(kv[[1L]]$key, "=", kv[[2L]]$key), ""), collapse = ";")

# root_factors (sympy/polys/polyroots.py)
root_factors <- function(f, x, filter = NULL) {
  f <- as_sym(f); x <- as_sym(x)
  zeros <- roots(f, x, filter = filter)
  if (!length(zeros)) return(list(f))
  mult <- attr(zeros, "multiplicity")
  vals <- unclass(zeros)[seq_along(zeros)]
  pr <- Map(function(r, m) list(r, m), vals, mult)
  keys <- lapply(pr, function(p) { tp <- Tuple(p[[1L]], .int(p[[2L]])); list(.nodes(tp), .sort_key(tp)) })
  pr <- .key_sort(keys, pr)
  factors <- list(); N <- 0L
  for (p in pr) { factors <- c(factors, rep(list(.sub(x, p[[1L]])), p[[2L]])); N <- N + p[[2L]] }
  if (N < degree(f, x)) {
    G <- .mul(factors)
    factors[[length(factors) + 1L]] <- quo(f, G, x)
  }
  factors
}

# lcm(p, q, *V) with the other generators in the ground domain
.heur_lcm <- function(p, q, V) {
  r <- tryCatch(do.call(lcm, c(list(p, q), V)), error = function(e) NULL)
  if (!is.null(r)) return(r)
  pe <- expand(p); qe <- expand(q)
  others <- Filter(function(g) !any(vapply(V, function(v) identical(v$key, g$key), NA)), .find_gens(list(pe, qe)))
  allg <- c(V, others)
  g <- .mpoly_gcd(pe, qe, allg, FALSE)
  expand(cancel(.div(.mul(list(pe, qe)), g)))
}
